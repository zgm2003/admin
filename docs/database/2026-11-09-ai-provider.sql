-- AI 供应商配置。
-- API Key 只保存 AES-GCM 密文；页面不回传明文。
CREATE TABLE IF NOT EXISTS ai_provider (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(128) NOT NULL CHECK (length(name) BETWEEN 1 AND 128),
    vendor smallint NOT NULL CHECK (vendor IN (1, 2, 3)),
    protocol smallint NOT NULL CHECK (protocol IN (1, 2, 3)),
    base_url varchar(2048) NOT NULL CHECK (base_url ~ '^https://[^[:space:]]+$'),
    api_key_ciphertext text NOT NULL CHECK (length(api_key_ciphertext) > 0),
    encryption_key_id varchar(64) NOT NULL CHECK (length(encryption_key_id) > 0),
    timeout_ms integer NOT NULL DEFAULT 60000 CHECK (timeout_ms BETWEEN 1000 AND 300000),
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 1000000),
    status smallint NOT NULL DEFAULT 0 CHECK (status IN (0, 1)),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE INDEX IF NOT EXISTS ix_ai_provider_status_sort
    ON ai_provider (status, sort_order, id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_ai_provider_vendor
    ON ai_provider (vendor, sort_order, id) WHERE deleted_at IS NULL;

COMMENT ON TABLE ai_provider IS 'AI 供应商通道配置；同一厂商允许多条通道';
COMMENT ON COLUMN ai_provider.vendor IS '厂商：1=OpenAI，2=Anthropic，3=Google';
COMMENT ON COLUMN ai_provider.protocol IS '协议：1=OpenAI 兼容，2=Anthropic，3=Gemini';
COMMENT ON COLUMN ai_provider.api_key_ciphertext IS 'AI 供应商 API Key 的 AES-GCM 密文，不存明文';
COMMENT ON COLUMN ai_provider.status IS '0=停用，1=启用';
