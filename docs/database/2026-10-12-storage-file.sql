-- Offline forward migration; runner executes in one transaction with services stopped.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
LOCK TABLE permission_auth_platform, permission_menu, permission_role, permission_role_menu, system_scheduler_schedule IN SHARE ROW EXCLUSIVE MODE;
CREATE TABLE IF NOT EXISTS storage_file (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL CHECK (user_id > 0),
 platform_id BIGINT NOT NULL CHECK (platform_id > 0),
 kind SMALLINT NOT NULL CHECK (kind IN (1,2)),
 cos_config_id BIGINT NOT NULL CHECK (cos_config_id > 0),
 config_version BIGINT NOT NULL CHECK (config_version > 0),
 upload_rule_id BIGINT NOT NULL CHECK (upload_rule_id > 0),
 rule_code VARCHAR(128) NOT NULL CHECK (btrim(rule_code) <> ''),
 object_key VARCHAR(1024) NOT NULL UNIQUE CHECK (btrim(object_key) <> ''),
 upload_object_key VARCHAR(1024) NULL CHECK (upload_object_key IS NULL OR (btrim(upload_object_key) <> '' AND upload_object_key <> object_key)),
 original_name VARCHAR(255) NOT NULL CHECK (btrim(original_name) <> ''),
 mime_type VARCHAR(255) NOT NULL CHECK (btrim(mime_type) <> ''),
 size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
 etag VARCHAR(255) NOT NULL DEFAULT '',
 status SMALLINT NOT NULL CHECK (status IN (1,2,3)),
 credential_expires_at TIMESTAMPTZ NULL,
 completed_at TIMESTAMPTZ NULL,
 request_key UUID NULL,
 source_file_id BIGINT NULL CHECK (source_file_id IS NULL OR source_file_id > 0),
 operation_lease_until TIMESTAMPTZ NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at TIMESTAMPTZ NULL
);
CREATE INDEX IF NOT EXISTS ix_storage_file_owner_list ON storage_file(platform_id,user_id,created_at DESC,id DESC) WHERE kind=1 AND status=2 AND deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_storage_file_cleanup ON storage_file(status,credential_expires_at,id) WHERE deleted_at IS NULL AND status IN (1,3);
CREATE INDEX IF NOT EXISTS ix_storage_file_temporary_cleanup ON storage_file(credential_expires_at,id) WHERE status=2 AND upload_object_key IS NOT NULL AND deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_storage_file_request ON storage_file(platform_id,user_id,request_key) WHERE request_key IS NOT NULL;
DO $migration$
DECLARE
 target_platform RECORD;
 parent BIGINT;
 page BIGINT;
 existing RECORD;
 action_code TEXT;
 role_id_value BIGINT;
 changed BOOLEAN;
 affected INTEGER;
BEGIN
 IF (SELECT count(*) FROM permission_auth_platform WHERE code='admin' AND is_enabled=1 AND deleted_at IS NULL) <> 1 THEN RAISE EXCEPTION 'Exactly one active Admin platform required'; END IF;
 FOR target_platform IN SELECT id FROM permission_auth_platform WHERE code='admin' AND is_enabled=1 AND deleted_at IS NULL LOOP
  SELECT id INTO parent FROM permission_menu WHERE platform_id=target_platform.id AND code='storage' AND menu_type='directory' AND is_enabled=1 AND deleted_at IS NULL;
  IF parent IS NULL THEN RAISE EXCEPTION 'Admin cloud directory missing'; END IF;
  changed := FALSE;
  IF EXISTS(SELECT 1 FROM permission_menu WHERE platform_id=target_platform.id AND deleted_at IS NULL AND (path='/storage/file' OR component_path='storage/file') AND code<>'storage:file:view') THEN RAISE EXCEPTION 'My Files page path conflict'; END IF;
  SELECT * INTO existing FROM permission_menu WHERE platform_id=target_platform.id AND code='storage:file:view' AND deleted_at IS NULL;
  IF FOUND THEN
   IF existing.menu_type <> 'page' OR existing.parent_id IS DISTINCT FROM parent OR existing.path IS DISTINCT FROM '/storage/file' OR existing.component_path IS DISTINCT FROM 'storage/file' OR existing.i18n_key IS DISTINCT FROM 'menu.storage.file' OR existing.is_hidden <> 0 OR existing.is_enabled <> 1 THEN RAISE EXCEPTION 'My Files page code conflict'; END IF;
   page := existing.id;
  ELSE
   INSERT INTO permission_menu(platform_id,parent_id,menu_type,name,code,i18n_key,path,component_path,sort_order,is_enabled,is_hidden) VALUES(target_platform.id,parent,'page','我的文件','storage:file:view','menu.storage.file','/storage/file','storage/file',20,1,0) RETURNING id INTO page;
   changed := TRUE;
  END IF;
  FOREACH action_code IN ARRAY ARRAY['storage:file:list','storage:file:detail','storage:file:delete'] LOOP
   SELECT * INTO existing FROM permission_menu WHERE platform_id=target_platform.id AND code=action_code AND deleted_at IS NULL;
   IF FOUND THEN
    IF existing.menu_type <> 'action' OR existing.parent_id IS DISTINCT FROM page OR existing.is_hidden <> 1 OR existing.is_enabled <> 1 OR existing.path IS NOT NULL OR existing.component_path IS NOT NULL OR existing.i18n_key IS NOT NULL OR existing.icon IS NOT NULL THEN RAISE EXCEPTION 'My Files action code conflict'; END IF;
   ELSE
    INSERT INTO permission_menu(platform_id,parent_id,menu_type,name,code,sort_order,is_enabled,is_hidden) VALUES(target_platform.id,page,'action',CASE action_code WHEN 'storage:file:list' THEN '查看本人文件列表' WHEN 'storage:file:detail' THEN '查看本人文件' ELSE '删除本人文件' END,action_code,0,1,1);
    changed := TRUE;
   END IF;
  END LOOP;
  SELECT id INTO role_id_value FROM permission_role WHERE code='registered_user' AND is_enabled=1 AND deleted_at IS NULL;
  IF role_id_value IS NULL THEN RAISE EXCEPTION 'registered_user role missing'; END IF;
  INSERT INTO permission_role_menu(role_id,menu_id)
   SELECT role_id_value,m.id FROM permission_menu m WHERE m.platform_id=target_platform.id AND m.deleted_at IS NULL AND m.code IN ('storage:file:view','storage:file:list','storage:file:detail','storage:file:delete') AND NOT EXISTS(SELECT 1 FROM permission_role_menu rm WHERE rm.role_id=role_id_value AND rm.menu_id=m.id AND rm.deleted_at IS NULL);
  GET DIAGNOSTICS affected = ROW_COUNT;
  IF affected > 0 THEN changed := TRUE; END IF;
  IF changed THEN UPDATE permission_auth_platform SET menu_version=menu_version+1,updated_at=CURRENT_TIMESTAMP WHERE id=target_platform.id; END IF;
 END LOOP;
END $migration$;
-- Refuse incompatible pre-existing objects instead of treating IF NOT EXISTS as verification.
DO $verify$
DECLARE bad_count INTEGER;
BEGIN
 SELECT count(*) INTO bad_count FROM (VALUES
 ('id','bigint'),('user_id','bigint'),('platform_id','bigint'),('kind','smallint'),
 ('cos_config_id','bigint'),('config_version','bigint'),('upload_rule_id','bigint'),
 ('rule_code','character varying'),('object_key','character varying'),('upload_object_key','character varying'),
 ('original_name','character varying'),('mime_type','character varying'),('size_bytes','bigint'),('etag','character varying'),
 ('status','smallint'),('credential_expires_at','timestamp with time zone'),('completed_at','timestamp with time zone'),
 ('request_key','uuid'),('source_file_id','bigint'),('operation_lease_until','timestamp with time zone'),('created_at','timestamp with time zone'),('updated_at','timestamp with time zone'),('deleted_at','timestamp with time zone')
 ) expected(name,type_name) WHERE NOT EXISTS(SELECT 1 FROM information_schema.columns c WHERE c.table_schema=current_schema() AND c.table_name='storage_file' AND c.column_name=expected.name AND c.data_type=expected.type_name);
 IF EXISTS(SELECT 1 FROM information_schema.columns c WHERE c.table_schema=current_schema() AND c.table_name='storage_file' AND c.column_name IN ('id','user_id','platform_id','kind','cos_config_id','config_version','upload_rule_id','rule_code','object_key','original_name','mime_type','size_bytes','etag','status','created_at','updated_at') AND c.is_nullable<>'NO') THEN RAISE EXCEPTION 'storage_file nullable required column'; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='storage_file'::regclass AND contype='p' AND pg_get_constraintdef(oid)='PRIMARY KEY (id)') OR NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='storage_file'::regclass AND contype='u' AND pg_get_constraintdef(oid)='UNIQUE (object_key)') THEN RAISE EXCEPTION 'storage_file uniqueness incompatible'; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='storage_file'::regclass AND contype='c' AND convalidated AND pg_get_constraintdef(oid) LIKE '%size_bytes > 0%') OR NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='storage_file'::regclass AND contype='c' AND convalidated AND pg_get_constraintdef(oid) LIKE '%kind = ANY (ARRAY[1, 2])%') OR NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='storage_file'::regclass AND contype='c' AND convalidated AND pg_get_constraintdef(oid) LIKE '%status = ANY (ARRAY[1, 2, 3])%') THEN RAISE EXCEPTION 'storage_file check constraints incompatible'; END IF;
 IF bad_count<>0 THEN RAISE EXCEPTION 'storage_file pre-existing schema incompatible'; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_indexes WHERE schemaname=current_schema() AND indexname='ix_storage_file_owner_list' AND indexdef LIKE '%(platform_id, user_id, created_at DESC, id DESC)%' AND indexdef LIKE '%WHERE ((kind = 1) AND (status = 2) AND (deleted_at IS NULL))%')
 OR NOT EXISTS(SELECT 1 FROM pg_indexes WHERE schemaname=current_schema() AND indexname='ix_storage_file_cleanup' AND indexdef LIKE '%(status, credential_expires_at, id)%' AND indexdef LIKE '%WHERE ((deleted_at IS NULL) AND (status = ANY (ARRAY[1, 3])))%')
 OR NOT EXISTS(SELECT 1 FROM pg_indexes WHERE schemaname=current_schema() AND indexname='ix_storage_file_temporary_cleanup' AND indexdef LIKE '%(credential_expires_at, id)%' AND indexdef LIKE '%WHERE ((status = 2) AND (upload_object_key IS NOT NULL) AND (deleted_at IS NULL))%')
 OR NOT EXISTS(SELECT 1 FROM pg_indexes WHERE schemaname=current_schema() AND indexname='ux_storage_file_request' AND indexdef LIKE 'CREATE UNIQUE INDEX%' AND indexdef LIKE '%(platform_id, user_id, request_key)%' AND indexdef LIKE '%WHERE (request_key IS NOT NULL)%') THEN RAISE EXCEPTION 'storage_file pre-existing index incompatible'; END IF;
END $verify$;

-- Durable recurring cleanup is seeded offline, never by API/Worker startup.
DO $schedule$
BEGIN
 IF EXISTS(SELECT 1 FROM system_scheduler_schedule WHERE builtin_key='storage.file.scan' AND (deleted_at IS NOT NULL OR task_type<>'storage.file.scan')) THEN RAISE EXCEPTION 'storage file cleanup schedule conflict'; END IF;
 IF (SELECT count(*) FROM system_scheduler_schedule WHERE builtin_key='storage.file.scan') > 1 THEN RAISE EXCEPTION 'duplicate storage file cleanup schedule'; END IF;
 INSERT INTO system_scheduler_schedule(name,description,task_type,cron_expression,timezone,params,is_enabled,next_run_at,builtin_key)
 SELECT '文件清理巡检','清理过期上传、删除文件与头像副本','storage.file.scan','* * * * *','UTC','{}'::jsonb,1,CURRENT_TIMESTAMP+INTERVAL '1 minute','storage.file.scan'
 WHERE NOT EXISTS(SELECT 1 FROM system_scheduler_schedule WHERE builtin_key='storage.file.scan');
END $schedule$;
