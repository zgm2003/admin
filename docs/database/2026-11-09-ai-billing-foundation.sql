-- AI 计费基础：供应商 token 倍率、模型类型、缓存价、供应商模型与媒体价格。
-- token 模型使用供应商倍率；图片/视频/音频按供应商单位价格直接计费。

SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';

ALTER TABLE ai_provider
    ADD COLUMN IF NOT EXISTS token_rate_multiplier_ppm bigint NOT NULL DEFAULT 1000000;
ALTER TABLE ai_provider
    DROP CONSTRAINT IF EXISTS ai_provider_token_rate_multiplier_ppm_check;
ALTER TABLE ai_provider
    ADD CONSTRAINT ai_provider_token_rate_multiplier_ppm_check
        CHECK (token_rate_multiplier_ppm BETWEEN 0 AND 100000000);

COMMENT ON COLUMN ai_provider.token_rate_multiplier_ppm IS
    'Token 计费模型（聊天、token 音频）的供应商倍率；1,000,000 = 1.0x';

ALTER TABLE ai_official_model
    ADD COLUMN IF NOT EXISTS model_kind smallint NOT NULL DEFAULT 1;
ALTER TABLE ai_official_model
    DROP CONSTRAINT IF EXISTS ai_official_model_model_kind_check;
ALTER TABLE ai_official_model
    ADD CONSTRAINT ai_official_model_model_kind_check
        CHECK (model_kind IN (1, 2, 3, 4));

ALTER TABLE ai_official_model
    ADD COLUMN IF NOT EXISTS cache_read_cny_micros bigint,
    ADD COLUMN IF NOT EXISTS cache_write_cny_micros bigint,
    ADD COLUMN IF NOT EXISTS cache_read_usd_micros bigint,
    ADD COLUMN IF NOT EXISTS cache_write_usd_micros bigint;
ALTER TABLE ai_official_model
    DROP CONSTRAINT IF EXISTS ai_official_model_cache_read_cny_micros_check;
ALTER TABLE ai_official_model
    DROP CONSTRAINT IF EXISTS ai_official_model_cache_write_cny_micros_check;
ALTER TABLE ai_official_model
    DROP CONSTRAINT IF EXISTS ai_official_model_cache_read_usd_micros_check;
ALTER TABLE ai_official_model
    DROP CONSTRAINT IF EXISTS ai_official_model_cache_write_usd_micros_check;
ALTER TABLE ai_official_model
    ADD CONSTRAINT ai_official_model_cache_read_cny_micros_check
        CHECK (cache_read_cny_micros IS NULL OR cache_read_cny_micros >= 0),
    ADD CONSTRAINT ai_official_model_cache_write_cny_micros_check
        CHECK (cache_write_cny_micros IS NULL OR cache_write_cny_micros >= 0),
    ADD CONSTRAINT ai_official_model_cache_read_usd_micros_check
        CHECK (cache_read_usd_micros IS NULL OR cache_read_usd_micros >= 0),
    ADD CONSTRAINT ai_official_model_cache_write_usd_micros_check
        CHECK (cache_write_usd_micros IS NULL OR cache_write_usd_micros >= 0);

UPDATE ai_official_model
SET model_kind = 1
WHERE model_kind IS DISTINCT FROM 1;

COMMENT ON COLUMN ai_official_model.model_kind IS
    '模型类型：1=聊天，2=图片，3=视频，4=音频';
COMMENT ON COLUMN ai_official_model.cache_read_cny_micros IS
    '缓存读取价格，CNY micros / 1M tokens；NULL 表示未配置';
COMMENT ON COLUMN ai_official_model.cache_write_cny_micros IS
    '缓存写入价格，CNY micros / 1M tokens；NULL 表示未配置';
COMMENT ON COLUMN ai_official_model.cache_read_usd_micros IS
    '缓存读取参考价，USD micros / 1M tokens；NULL 表示未配置';
COMMENT ON COLUMN ai_official_model.cache_write_usd_micros IS
    '缓存写入参考价，USD micros / 1M tokens；NULL 表示未配置';

CREATE TABLE IF NOT EXISTS ai_provider_model (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id bigint NOT NULL REFERENCES ai_provider(id) ON DELETE CASCADE,
    upstream_model varchar(200) NOT NULL,
    model_key varchar(200) NOT NULL,
    display_name varchar(200) NOT NULL,
    model_kind smallint NOT NULL CHECK (model_kind IN (1, 2, 3, 4)),
    pricing_mode smallint NOT NULL CHECK (pricing_mode IN (1, 2)),
    price_unit smallint NOT NULL CHECK (price_unit IN (1, 2, 3, 4, 5, 6)),
    official_model_id bigint REFERENCES ai_official_model(id) ON DELETE RESTRICT,
    source smallint NOT NULL DEFAULT 2 CHECK (source IN (1, 2)),
    status smallint NOT NULL DEFAULT 0 CHECK (status IN (0, 1)),
    last_seen_at timestamptz,
    version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT ai_provider_model_token_mode_check
        CHECK (pricing_mode <> 1 OR (official_model_id IS NOT NULL AND price_unit = 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_provider_model_upstream_active
    ON ai_provider_model (provider_id, upstream_model) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_provider_model_key_active
    ON ai_provider_model (provider_id, model_key) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_ai_provider_model_provider_status
    ON ai_provider_model (provider_id, status, model_kind, id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_ai_provider_model_official_model
    ON ai_provider_model (official_model_id) WHERE deleted_at IS NULL;

COMMENT ON TABLE ai_provider_model IS
    '供应商通道可用模型；token 模型使用供应商倍率，媒体模型使用供应商单位价格';
COMMENT ON COLUMN ai_provider_model.upstream_model IS
    '上游返回的模型 ID';
COMMENT ON COLUMN ai_provider_model.model_key IS
    '系统对外模型标识，默认与 upstream_model 相同';
COMMENT ON COLUMN ai_provider_model.model_kind IS
    '模型类型：1=聊天，2=图片，3=视频，4=音频';
COMMENT ON COLUMN ai_provider_model.pricing_mode IS
    '计费模式：1=官方 token 价 × 供应商倍率，2=供应商单位价格';
COMMENT ON COLUMN ai_provider_model.price_unit IS
    '计价单位：1=百万 token，2=张，3=秒，4=分钟，5=百万字符，6=次';
COMMENT ON COLUMN ai_provider_model.official_model_id IS
    'token 计费必须映射官方模型；媒体模型可为空';
COMMENT ON COLUMN ai_provider_model.source IS
    '来源：1=手工，2=上游同步';
COMMENT ON COLUMN ai_provider_model.status IS
    '0=停用/未完成定价，1=启用';

CREATE TABLE IF NOT EXISTS ai_provider_model_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_model_id bigint NOT NULL REFERENCES ai_provider_model(id) ON DELETE CASCADE,
    tier_key varchar(64) NOT NULL DEFAULT 'default',
    tier_label varchar(64) NOT NULL DEFAULT '',
    price_cny_micros bigint NOT NULL CHECK (price_cny_micros >= 0),
    status smallint NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_provider_model_price_tier_active
    ON ai_provider_model_price (provider_model_id, tier_key) WHERE deleted_at IS NULL;

COMMENT ON TABLE ai_provider_model_price IS
    '供应商媒体模型单位价格；图片按质量、视频按分辨率、音频按单位设置';
COMMENT ON COLUMN ai_provider_model_price.tier_key IS
    '价格档位：default、quality:low、quality:medium、quality:high、resolution:1080p 等';
COMMENT ON COLUMN ai_provider_model_price.tier_label IS
    '价格档位显示名称';
COMMENT ON COLUMN ai_provider_model_price.price_cny_micros IS
    '单价，CNY micros；单位由 ai_provider_model.price_unit 决定';
