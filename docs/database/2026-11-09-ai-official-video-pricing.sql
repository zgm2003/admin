-- Seedance 2.5 / 2.0 系列官方视频目录与按分辨率/秒价格。

ALTER TABLE public.ai_official_model
    DROP CONSTRAINT IF EXISTS ai_official_model_vendor_check;
ALTER TABLE public.ai_official_model
    ADD CONSTRAINT ai_official_model_vendor_check
    CHECK (vendor = ANY (ARRAY[1, 2, 3, 4]));

ALTER TABLE public.ai_provider
    DROP CONSTRAINT IF EXISTS ai_provider_vendor_check;
ALTER TABLE public.ai_provider
    ADD CONSTRAINT ai_provider_vendor_check
    CHECK (vendor = ANY (ARRAY[1, 2, 3, 4]));

CREATE TABLE public.ai_official_model_price (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    official_model_id bigint NOT NULL REFERENCES public.ai_official_model(id) ON DELETE CASCADE,
    tier_key          varchar(64) NOT NULL,
    tier_label        varchar(64) NOT NULL DEFAULT '',
    price_cny_micros  bigint,
    unit              varchar(16) NOT NULL DEFAULT 'second',
    sort_order        integer NOT NULL DEFAULT 0,
    version           bigint NOT NULL DEFAULT 1,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_official_model_price_tier_key_check CHECK (length(tier_key) BETWEEN 1 AND 64),
    CONSTRAINT ai_official_model_price_tier_label_check CHECK (length(tier_label) <= 64),
    CONSTRAINT ai_official_model_price_price_check CHECK (price_cny_micros IS NULL OR price_cny_micros >= 0),
    CONSTRAINT ai_official_model_price_unit_check CHECK (unit = ANY (ARRAY['second', 'minute', 'item'])),
    CONSTRAINT ai_official_model_price_sort_order_check CHECK (sort_order >= 0),
    CONSTRAINT ai_official_model_price_version_check CHECK (version >= 1),
    CONSTRAINT ai_official_model_price_model_tier_uq UNIQUE (official_model_id, tier_key)
);

CREATE INDEX ai_official_model_price_model_sort_idx
    ON public.ai_official_model_price (official_model_id, sort_order);
