-- Temporary canonical shape: compare parsed checks/indexes, not only names.
CREATE TEMP TABLE ai_payment_expected (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    transaction_no varchar(32) NOT NULL,
    user_id bigint NOT NULL,
    platform_id bigint NOT NULL,
    amount_units bigint NOT NULL,
    balance_after_units bigint NOT NULL,
    order_id bigint,
    redeem_code_id bigint,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    direction smallint NOT NULL,
    balance_before_units bigint NOT NULL,
    ai_usage_charge_id bigint,
    CONSTRAINT payment_transaction_pkey PRIMARY KEY(id),
    CONSTRAINT ck_payment_transaction_amount CHECK(amount_units>0),
    CONSTRAINT ck_payment_transaction_balance CHECK(balance_after_units::numeric >= (- '9223372036854775808'::numeric)+amount_units::numeric),
    CONSTRAINT ck_payment_transaction_source_xor CHECK((order_id IS NOT NULL) <> (redeem_code_id IS NOT NULL)),
    CONSTRAINT ck_payment_transaction_direction CHECK(direction IN(1,2)),
    CONSTRAINT ck_payment_transaction_ai_source_xor CHECK(num_nonnulls(order_id,redeem_code_id,ai_usage_charge_id)=1),
    CONSTRAINT ck_payment_transaction_ai_source_direction CHECK(
        (direction=1 AND ai_usage_charge_id IS NULL AND (order_id IS NOT NULL OR redeem_code_id IS NOT NULL)) OR
        (direction=2 AND ai_usage_charge_id IS NOT NULL AND order_id IS NULL AND redeem_code_id IS NULL)),
    CONSTRAINT ck_payment_transaction_direction_balance CHECK(
        (direction=1 AND balance_after_units::numeric=balance_before_units::numeric+amount_units::numeric) OR
        (direction=2 AND balance_after_units::numeric=balance_before_units::numeric-amount_units::numeric))
) ON COMMIT DROP;
CREATE UNIQUE INDEX ux_payment_transaction_no ON ai_payment_expected(transaction_no);
CREATE UNIQUE INDEX ux_payment_transaction_order ON ai_payment_expected(order_id) WHERE order_id IS NOT NULL;
CREATE UNIQUE INDEX ux_payment_transaction_redeem_code ON ai_payment_expected(redeem_code_id) WHERE redeem_code_id IS NOT NULL;
CREATE INDEX ix_payment_transaction_created ON ai_payment_expected(created_at DESC,id DESC);
CREATE INDEX ix_payment_transaction_user_created ON ai_payment_expected(user_id,created_at DESC,id DESC);
CREATE UNIQUE INDEX ux_payment_transaction_ai_usage_charge ON ai_payment_expected(ai_usage_charge_id) WHERE ai_usage_charge_id IS NOT NULL;

CREATE OR REPLACE FUNCTION pg_temp.ai_payment_assert_shape(extended boolean) RETURNS void
LANGUAGE plpgsql AS $shape$
DECLARE
    target oid := to_regclass(format('%I.payment_transaction',current_schema()));
    expected oid := 'pg_temp.ai_payment_expected'::regclass;
    checks text[];
    item record;
    reference_oid oid;
    local_att smallint;
    reference_att smallint;
BEGIN
    IF target IS NULL THEN RAISE EXCEPTION 'required payment_transaction is missing'; END IF;
    IF EXISTS (
        WITH actual AS (
            SELECT attname,atttypid,atttypmod,attnotnull,attidentity,attgenerated,
                   coalesce(pg_get_expr(d.adbin,d.adrelid),'') AS default_expr
              FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
             WHERE a.attrelid=target AND a.attnum>0 AND NOT a.attisdropped
        ), wanted AS (
            SELECT attname,atttypid,atttypmod,attnotnull,attidentity,attgenerated,
                   coalesce(pg_get_expr(d.adbin,d.adrelid),'') AS default_expr
              FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
             WHERE a.attrelid=expected AND a.attnum>0 AND NOT a.attisdropped
               AND (extended OR a.attname NOT IN('direction','balance_before_units','ai_usage_charge_id'))
        ) SELECT 1 FROM ((TABLE actual EXCEPT TABLE wanted) UNION ALL (TABLE wanted EXCEPT TABLE actual)) difference
    ) THEN RAISE EXCEPTION 'payment_transaction columns/defaults drifted or extension is partial'; END IF;

    checks := CASE WHEN extended THEN ARRAY[
        'payment_transaction_pkey','ck_payment_transaction_amount','ck_payment_transaction_direction',
        'ck_payment_transaction_ai_source_xor','ck_payment_transaction_ai_source_direction','ck_payment_transaction_direction_balance'
    ] ELSE ARRAY['payment_transaction_pkey','ck_payment_transaction_amount','ck_payment_transaction_balance','ck_payment_transaction_source_xor'] END;
    IF EXISTS (
        WITH actual AS (
            SELECT conname,contype,pg_get_constraintdef(oid) AS definition,convalidated,condeferrable,condeferred
              FROM pg_constraint WHERE conrelid=target AND contype NOT IN('f','n')
        ), wanted AS (
            SELECT conname,contype,pg_get_constraintdef(oid) AS definition,convalidated,condeferrable,condeferred
              FROM pg_constraint WHERE conrelid=expected AND conname=ANY(checks)
        ) SELECT 1 FROM ((TABLE actual EXCEPT TABLE wanted) UNION ALL (TABLE wanted EXCEPT TABLE actual)) difference
    ) THEN RAISE EXCEPTION 'payment_transaction check/primary-key constraints drifted'; END IF;

    IF EXISTS (
        WITH actual AS (
            SELECT c.relname,i.indisunique,i.indisprimary,i.indisvalid,i.indisready,
                   substring(pg_get_indexdef(i.indexrelid) FROM ' USING .*$') AS definition
              FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid WHERE i.indrelid=target
        ), wanted AS (
            SELECT c.relname,i.indisunique,i.indisprimary,i.indisvalid,i.indisready,
                   substring(pg_get_indexdef(i.indexrelid) FROM ' USING .*$') AS definition
              FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid WHERE i.indrelid=expected
               AND (extended OR c.relname<>'ux_payment_transaction_ai_usage_charge')
        ) SELECT 1 FROM ((TABLE actual EXCEPT TABLE wanted) UNION ALL (TABLE wanted EXCEPT TABLE actual)) difference
    ) THEN RAISE EXCEPTION 'payment_transaction indexes drifted'; END IF;

    IF (SELECT count(*) FROM pg_constraint WHERE conrelid=target AND contype='f') <> (CASE WHEN extended THEN 5 ELSE 4 END) THEN
        RAISE EXCEPTION 'payment_transaction foreign key set drifted';
    END IF;
    FOR item IN SELECT * FROM (VALUES
        ('fk_payment_transaction_order','order_id','payment_order','id'),
        ('fk_payment_transaction_redeem_code','redeem_code_id','payment_redeem_code','id'),
        ('fk_payment_transaction_user','user_id','payment_wallet','user_id'),
        ('fk_payment_transaction_platform','platform_id','permission_auth_platform','id'),
        ('fk_payment_transaction_ai_usage_charge','ai_usage_charge_id','ai_usage_charge','id')
    ) f(name,local_column,reference_table,reference_column) LOOP
        IF NOT extended AND item.local_column='ai_usage_charge_id' THEN CONTINUE; END IF;
        reference_oid := to_regclass(format('%I.%I',current_schema(),item.reference_table));
        SELECT attnum INTO local_att FROM pg_attribute WHERE attrelid=target AND attname=item.local_column AND NOT attisdropped;
        SELECT attnum INTO reference_att FROM pg_attribute WHERE attrelid=reference_oid AND attname=item.reference_column AND NOT attisdropped;
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint WHERE conrelid=target AND conname=item.name AND contype='f'
               AND confrelid=reference_oid AND conkey=ARRAY[local_att] AND confkey=ARRAY[reference_att]
               AND confdeltype='r' AND confupdtype='a' AND confmatchtype='s' AND convalidated AND NOT condeferrable
        ) THEN RAISE EXCEPTION 'payment_transaction foreign key % drifted',item.name; END IF;
    END LOOP;

    IF (SELECT count(*) FROM pg_trigger WHERE tgrelid=target AND NOT tgisinternal)<>2 THEN
        RAISE EXCEPTION 'payment_transaction guard set drifted';
    END IF;
    FOR item IN SELECT * FROM (VALUES
        ('payment_transaction_immutable','payment_transaction_immutable_guard',18,
         'BEGIN RAISE EXCEPTION ''payment transactions are immutable''; END'),
        ('payment_transaction_no_delete','payment_fact_no_delete_guard',42,
         'BEGIN RAISE EXCEPTION ''payment financial facts cannot be physically removed''; END')
    ) g(name,function_name,trigger_type,body) LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_trigger t JOIN pg_proc p ON p.oid=t.tgfoid
              JOIN pg_namespace n ON n.oid=p.pronamespace JOIN pg_language l ON l.oid=p.prolang
             WHERE t.tgrelid=target AND NOT t.tgisinternal AND t.tgname=item.name
               AND t.tgenabled='O' AND t.tgtype=item.trigger_type AND t.tgqual IS NULL AND t.tgnargs=0
               AND t.tgattr = ''::int2vector
               AND n.nspname=current_schema() AND p.proname=item.function_name AND NOT p.prosecdef
               AND p.prorettype='trigger'::regtype AND l.lanname='plpgsql'
               AND regexp_replace(p.prosrc,'\s+','','g')=regexp_replace(item.body,'\s+','','g')
        ) THEN RAISE EXCEPTION 'payment_transaction guard % missing, disabled or drifted',item.name; END IF;
    END LOOP;
END
$shape$;

DO $migration$
DECLARE
    target oid := to_regclass(format('%I.payment_transaction',current_schema()));
    extended boolean;
    qualified_table text := format('%I.payment_transaction',current_schema());
BEGIN
    IF target IS NULL THEN RAISE EXCEPTION 'required payment_transaction is missing'; END IF;
    IF to_regclass(format('%I.ai_usage_charge',current_schema())) IS NULL THEN
        RAISE EXCEPTION 'required ai_usage_charge missing; apply AI core first';
    END IF;
    EXECUTE 'LOCK TABLE '||qualified_table||' IN ACCESS EXCLUSIVE MODE';
    extended := EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid=target AND attname='direction' AND NOT attisdropped);
    PERFORM pg_temp.ai_payment_assert_shape(extended);
    IF extended THEN RETURN; END IF;
    -- Detect invalid legacy facts before touching protection; numeric avoids wrap.
    IF EXISTS(SELECT 1 FROM payment_transaction WHERE amount_units<=0 OR num_nonnulls(order_id,redeem_code_id)<>1
        OR balance_after_units::numeric-amount_units::numeric < -9223372036854775808::numeric
        OR balance_after_units::numeric-amount_units::numeric > 9223372036854775807::numeric)
    THEN RAISE EXCEPTION 'legacy ledger facts invalid or before balance outside bigint'; END IF;

    EXECUTE 'ALTER TABLE '||qualified_table||' ADD COLUMN direction smallint, ADD COLUMN balance_before_units bigint, ADD COLUMN ai_usage_charge_id bigint';
    -- Only UPDATE protection is disabled, under an exclusive lock in one transaction.
    -- Every failure rolls back the backfill and trigger state together.
    EXECUTE 'ALTER TABLE '||qualified_table||' DISABLE TRIGGER payment_transaction_immutable';
    EXECUTE 'UPDATE '||qualified_table||' SET direction=1,balance_before_units=(balance_after_units::numeric-amount_units::numeric)::bigint';
    EXECUTE 'ALTER TABLE '||qualified_table||' ENABLE TRIGGER payment_transaction_immutable';
    EXECUTE 'ALTER TABLE '||qualified_table||' ALTER COLUMN direction SET NOT NULL, ALTER COLUMN balance_before_units SET NOT NULL';
    EXECUTE 'ALTER TABLE '||qualified_table||' DROP CONSTRAINT ck_payment_transaction_source_xor, DROP CONSTRAINT ck_payment_transaction_balance';
    EXECUTE 'ALTER TABLE '||qualified_table||' ADD CONSTRAINT ck_payment_transaction_direction CHECK(direction IN(1,2)),
        ADD CONSTRAINT ck_payment_transaction_ai_source_xor CHECK(num_nonnulls(order_id,redeem_code_id,ai_usage_charge_id)=1),
        ADD CONSTRAINT ck_payment_transaction_ai_source_direction CHECK(
            (direction=1 AND ai_usage_charge_id IS NULL AND (order_id IS NOT NULL OR redeem_code_id IS NOT NULL)) OR
            (direction=2 AND ai_usage_charge_id IS NOT NULL AND order_id IS NULL AND redeem_code_id IS NULL)),
        ADD CONSTRAINT ck_payment_transaction_direction_balance CHECK(
            (direction=1 AND balance_after_units::numeric=balance_before_units::numeric+amount_units::numeric) OR
            (direction=2 AND balance_after_units::numeric=balance_before_units::numeric-amount_units::numeric)),
        ADD CONSTRAINT fk_payment_transaction_ai_usage_charge FOREIGN KEY(ai_usage_charge_id) REFERENCES '||format('%I.ai_usage_charge',current_schema())||'(id) ON DELETE RESTRICT';
    EXECUTE 'CREATE UNIQUE INDEX ux_payment_transaction_ai_usage_charge ON '||qualified_table||'(ai_usage_charge_id) WHERE ai_usage_charge_id IS NOT NULL';
    PERFORM pg_temp.ai_payment_assert_shape(true);
END
$migration$;
