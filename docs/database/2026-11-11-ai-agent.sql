-- AI Agent 配置表。
-- 只保存可配置智能体；不包含对话、运行时、部署或工具绑定。
-- 由维护者执行；API/Worker 启动不执行 DDL。

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.ai_agent (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(128) NOT NULL,
    description character varying(500) DEFAULT ''::character varying NOT NULL,
    system_prompt text NOT NULL,
    provider_model_id bigint NOT NULL,
    status smallint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 1 NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    deleted_at timestamp with time zone,
    CONSTRAINT ai_agent_name_check CHECK (length(name) >= 1 AND length(name) <= 128),
    CONSTRAINT ai_agent_description_check CHECK (length(description) <= 500),
    CONSTRAINT ai_agent_system_prompt_check CHECK (length(system_prompt) >= 1 AND length(system_prompt) <= 20000),
    CONSTRAINT ai_agent_status_check CHECK (status IN (0, 1)),
    CONSTRAINT ai_agent_version_check CHECK (version >= 1),
    CONSTRAINT ai_agent_provider_model_fk FOREIGN KEY (provider_model_id)
        REFERENCES public.ai_provider_model (id) ON DELETE RESTRICT
);

COMMENT ON TABLE public.ai_agent IS '可配置智能体；绑定一个已启用且配置完整的对话模型';
COMMENT ON COLUMN public.ai_agent.provider_model_id IS '绑定的供应商对话模型；运行时不能使用已停用或已删除的模型';
COMMENT ON COLUMN public.ai_agent.system_prompt IS '智能体系统提示词，运行时作为系统消息';
COMMENT ON COLUMN public.ai_agent.status IS '0=停用，1=启用';

CREATE INDEX IF NOT EXISTS ai_agent_provider_model_id_idx
    ON public.ai_agent (provider_model_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS ai_agent_status_id_idx
    ON public.ai_agent (status, id DESC)
    WHERE deleted_at IS NULL;
