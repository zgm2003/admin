-- AI 工具目录：内置 function tools 与「AI 工具」管理菜单。
-- 可重复执行。

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.ai_tool (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL,
    name varchar(128) NOT NULL,
    description varchar(500) NOT NULL DEFAULT '',
    category varchar(32) NOT NULL DEFAULT 'internal',
    status smallint NOT NULL DEFAULT 1,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    deleted_at timestamp with time zone,
    CONSTRAINT ai_tool_code_check CHECK (length(code) >= 1 AND length(code) <= 64),
    CONSTRAINT ai_tool_name_check CHECK (length(name) >= 1 AND length(name) <= 128),
    CONSTRAINT ai_tool_status_check CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_tool_code_active
    ON public.ai_tool (code)
    WHERE deleted_at IS NULL;

INSERT INTO public.ai_tool (code, name, description, category, status, sort_order)
VALUES
    ('system.user_count', '用户总数', '查询系统用户总数、启用用户数、停用用户数和今日新增用户数。', 'internal', 1, 10),
    ('system.server_overview', '服务器概览', '查询当前 API 服务器的主机、CPU、内存、磁盘、运行时长和数据库连接池概览。', 'internal', 1, 20)
ON CONFLICT (code) WHERE deleted_at IS NULL DO NOTHING;

DO $$
DECLARE
    v_platform_id bigint := 1;
    v_ai_id bigint;
    v_page_id bigint;
    v_menu_id bigint;
BEGIN
    SELECT id INTO v_ai_id
    FROM public.permission_menu
    WHERE platform_id = v_platform_id AND code = 'ai' AND deleted_at IS NULL;

    IF v_ai_id IS NULL THEN
        RAISE EXCEPTION 'AI directory menu is missing';
    END IF;

    INSERT INTO public.permission_menu (
        parent_id, menu_type, code, i18n_key, path, component_path, icon,
        sort_order, status, is_hidden, created_at, updated_at, platform_id, name, remark
    ) VALUES (
        v_ai_id, 'page', 'ai:tool:view', 'navigation.aiTool',
        '/ai/tool', 'ai/tool', 'lucide:sparkles',
        60, 1, 0, now(), now(), v_platform_id, 'AI 工具', 'AI 内置 function tools'
    )
    ON CONFLICT (platform_id, code) WHERE deleted_at IS NULL DO NOTHING
    RETURNING id INTO v_page_id;

    IF v_page_id IS NULL THEN
        SELECT id INTO v_page_id
        FROM public.permission_menu
        WHERE platform_id = v_platform_id AND code = 'ai:tool:view' AND deleted_at IS NULL;
    END IF;

    INSERT INTO public.permission_menu (
        parent_id, menu_type, code, name, sort_order, status, is_hidden, created_at, updated_at, platform_id
    )
    SELECT v_page_id, 'action', action_code, action_name, action_sort, 1, 1, now(), now(), v_platform_id
    FROM (VALUES
        ('ai:tool:list', '查看 AI 工具', 10),
        ('ai:tool:status', '启停 AI 工具', 20)
    ) AS actions(action_code, action_name, action_sort)
    WHERE NOT EXISTS (
        SELECT 1 FROM public.permission_menu
        WHERE platform_id = v_platform_id AND code = actions.action_code AND deleted_at IS NULL
    );

    -- AI 工具属于管理配置，仅授予超级管理员。
    FOR v_menu_id IN
        SELECT id FROM public.permission_menu
        WHERE platform_id = v_platform_id
          AND deleted_at IS NULL
          AND code IN ('ai:tool:view', 'ai:tool:list', 'ai:tool:status')
    LOOP
        INSERT INTO public.permission_role_menu (role_id, menu_id, created_at, updated_at)
        SELECT 41, v_menu_id, now(), now()
        WHERE NOT EXISTS (
            SELECT 1 FROM public.permission_role_menu
            WHERE role_id = 41 AND menu_id = v_menu_id AND deleted_at IS NULL
        );
    END LOOP;

    UPDATE public.permission_auth_platform
    SET menu_version = menu_version + 1, updated_at = now()
    WHERE id = v_platform_id;
END $$;
