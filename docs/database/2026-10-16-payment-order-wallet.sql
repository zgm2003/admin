CREATE TABLE IF NOT EXISTS payment_callback_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id bigint NOT NULL,
    config_version bigint NOT NULL,
    dedupe_key bytea NOT NULL,
    order_id bigint,
    payload jsonb NOT NULL,
    process_status smallint NOT NULL,
    error_code smallint,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_callback_event_version FOREIGN KEY (config_id,config_version) REFERENCES payment_config_version(config_id,version) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_callback_event_order FOREIGN KEY (order_id) REFERENCES payment_order(id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_callback_event_dedupe CHECK (octet_length(dedupe_key) = 32),
    CONSTRAINT ck_payment_callback_event_payload CHECK (
        jsonb_typeof(payload) = 'object'
        AND payload ?& ARRAY['notifyId','orderNo','tradeNo','tradeStatus','appId','sellerId','totalAmount','paidAt']
        AND (payload - ARRAY['notifyId','orderNo','tradeNo','tradeStatus','appId','sellerId','totalAmount','paidAt']::text[]) = '{}'::jsonb
        AND (jsonb_typeof(payload->'notifyId') = 'null' OR (jsonb_typeof(payload->'notifyId') = 'string' AND octet_length(payload->>'notifyId') BETWEEN 1 AND 128 AND payload->>'notifyId' ~ '^[!-~]+$' AND payload->>'notifyId' !~ '[&=]'))
        AND jsonb_typeof(payload->'orderNo') = 'string' AND payload->>'orderNo' ~ '^[A-Za-z0-9_-]{1,32}$'
        AND (jsonb_typeof(payload->'tradeNo') = 'null' OR (jsonb_typeof(payload->'tradeNo') = 'string' AND octet_length(payload->>'tradeNo') BETWEEN 1 AND 64 AND payload->>'tradeNo' ~ '^[!-~]+$' AND payload->>'tradeNo' !~ '[&=]'))
        AND jsonb_typeof(payload->'tradeStatus') = 'string' AND octet_length(payload->>'tradeStatus') BETWEEN 1 AND 64 AND payload->>'tradeStatus' ~ '^[!-~]+$' AND payload->>'tradeStatus' !~ '[&=]'
        AND jsonb_typeof(payload->'appId') = 'string' AND octet_length(payload->>'appId') BETWEEN 1 AND 64 AND payload->>'appId' ~ '^[!-~]+$' AND payload->>'appId' !~ '[&=]'
        AND jsonb_typeof(payload->'sellerId') = 'string' AND octet_length(payload->>'sellerId') BETWEEN 1 AND 64 AND payload->>'sellerId' ~ '^[!-~]+$' AND payload->>'sellerId' !~ '[&=]'
        AND jsonb_typeof(payload->'totalAmount') = 'string' AND payload->>'totalAmount' ~ '^[0-9]+\.[0-9]{2}$'
        AND (payload->>'totalAmount')::numeric BETWEEN 0.01 AND 9223372036854.00
        AND (jsonb_typeof(payload->'paidAt') = 'null' OR (jsonb_typeof(payload->'paidAt') = 'string' AND octet_length(payload->>'paidAt') BETWEEN 1 AND 64 AND payload->>'paidAt' ~ '^[0-9T:.+Z-]+$'))
    ),
    CONSTRAINT ck_payment_callback_event_status CHECK (process_status IN (1,2,3,4)),
    CONSTRAINT ck_payment_callback_event_error CHECK (error_code IS NULL OR error_code BETWEEN 1 AND 9)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_payment_callback_event_dedupe ON payment_callback_event(config_id,config_version,dedupe_key);
CREATE INDEX IF NOT EXISTS ix_payment_callback_event_order ON payment_callback_event(order_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS ix_payment_callback_event_pending ON payment_callback_event(created_at,id) WHERE process_status=1;

DO $payment_guards$
DECLARE
    item record;
    function_oid oid;
BEGIN
    FOR item IN SELECT * FROM (VALUES
        ('payment_fact_no_delete_guard',$body$BEGIN
            RAISE EXCEPTION 'payment financial facts cannot be physically removed';
        END$body$),
        ('payment_transaction_immutable_guard',$body$BEGIN
            RAISE EXCEPTION 'payment transactions are immutable';
        END$body$),
        ('payment_wallet_identity_guard',$body$BEGIN
            IF ROW(NEW.user_id,NEW.created_at) IS DISTINCT FROM ROW(OLD.user_id,OLD.created_at) THEN
                RAISE EXCEPTION 'payment wallet identity is immutable';
            END IF;
            RETURN NEW;
        END$body$),
        ('payment_recharge_package_identity_guard',$body$BEGIN
            IF ROW(NEW.id,NEW.created_at) IS DISTINCT FROM ROW(OLD.id,OLD.created_at) THEN
                RAISE EXCEPTION 'payment recharge package identity is immutable';
            END IF;
            RETURN NEW;
        END$body$),
        ('payment_order_identity_guard',$body$BEGIN
            IF ROW(NEW.id,NEW.order_no,NEW.user_id,NEW.platform_id,NEW.package_id,NEW.package_name,NEW.amount_cents,NEW.config_id,NEW.config_version,NEW.pay_method,NEW.request_id,NEW.request_fingerprint,NEW.return_url,NEW.expires_at,NEW.created_at)
                IS DISTINCT FROM ROW(OLD.id,OLD.order_no,OLD.user_id,OLD.platform_id,OLD.package_id,OLD.package_name,OLD.amount_cents,OLD.config_id,OLD.config_version,OLD.pay_method,OLD.request_id,OLD.request_fingerprint,OLD.return_url,OLD.expires_at,OLD.created_at) THEN
                RAISE EXCEPTION 'payment order purchase facts are immutable';
            END IF;
            IF (OLD.status=2 AND ROW(NEW.status,NEW.provider_trade_no,NEW.paid_at,NEW.credited_at,NEW.closed_at) IS DISTINCT FROM ROW(OLD.status,OLD.provider_trade_no,OLD.paid_at,OLD.credited_at,OLD.closed_at))
                OR (OLD.status=3 AND NEW.status NOT IN (2,3))
                OR (OLD.closed_at IS NOT NULL AND NEW.closed_at IS DISTINCT FROM OLD.closed_at)
                OR (OLD.provider_trade_no IS NOT NULL AND NEW.provider_trade_no IS DISTINCT FROM OLD.provider_trade_no) THEN
                RAISE EXCEPTION 'payment order final facts cannot be rewritten';
            END IF;
            RETURN NEW;
        END$body$),
        ('payment_callback_event_identity_guard',$body$BEGIN
            IF ROW(NEW.id,NEW.config_id,NEW.config_version,NEW.dedupe_key,NEW.payload,NEW.created_at)
                IS DISTINCT FROM ROW(OLD.id,OLD.config_id,OLD.config_version,OLD.dedupe_key,OLD.payload,OLD.created_at)
                OR (OLD.order_id IS NOT NULL AND NEW.order_id IS DISTINCT FROM OLD.order_id)
                OR (OLD.process_status=2 AND NEW.process_status<>2) THEN
                RAISE EXCEPTION 'payment callback evidence is immutable';
            END IF;
            RETURN NEW;
        END$body$)
    ) AS functions(function_name,body) LOOP
        function_oid := to_regprocedure(format('%I.%I()',current_schema(),item.function_name));
        IF function_oid IS NULL THEN
            IF current_setting('payment.order_wallet_replay',true)='on' THEN
                RAISE EXCEPTION 'payment guard function missing: %',item.function_name;
            END IF;
            EXECUTE format('CREATE FUNCTION %I.%I() RETURNS trigger LANGUAGE plpgsql AS %L',current_schema(),item.function_name,item.body);
            function_oid := to_regprocedure(format('%I.%I()',current_schema(),item.function_name));
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM pg_proc p JOIN pg_language l ON l.oid=p.prolang
            WHERE p.oid=function_oid AND l.lanname='plpgsql' AND p.prorettype='trigger'::regtype
              AND NOT p.prosecdef AND p.proconfig IS NULL AND p.provolatile='v' AND p.proparallel='u'
              AND btrim(regexp_replace(p.prosrc,'\s+',' ','g'))=btrim(regexp_replace(item.body,'\s+',' ','g'))
        ) THEN
            RAISE EXCEPTION 'payment guard function contract differs: %',item.function_name;
        END IF;
    END LOOP;
    FOR item IN SELECT * FROM (VALUES
        ('payment_recharge_package','payment_recharge_package_no_delete','payment_fact_no_delete_guard',42,'BEFORE DELETE OR TRUNCATE','STATEMENT'),
        ('payment_wallet','payment_wallet_no_delete','payment_fact_no_delete_guard',42,'BEFORE DELETE OR TRUNCATE','STATEMENT'),
        ('payment_order','payment_order_no_delete','payment_fact_no_delete_guard',42,'BEFORE DELETE OR TRUNCATE','STATEMENT'),
        ('payment_transaction','payment_transaction_no_delete','payment_fact_no_delete_guard',42,'BEFORE DELETE OR TRUNCATE','STATEMENT'),
        ('payment_callback_event','payment_callback_event_no_delete','payment_fact_no_delete_guard',42,'BEFORE DELETE OR TRUNCATE','STATEMENT'),
        ('payment_transaction','payment_transaction_immutable','payment_transaction_immutable_guard',18,'BEFORE UPDATE','STATEMENT'),
        ('payment_recharge_package','payment_recharge_package_identity','payment_recharge_package_identity_guard',19,'BEFORE UPDATE','ROW'),
        ('payment_wallet','payment_wallet_identity','payment_wallet_identity_guard',19,'BEFORE UPDATE','ROW'),
        ('payment_order','payment_order_identity','payment_order_identity_guard',19,'BEFORE UPDATE','ROW'),
        ('payment_callback_event','payment_callback_event_identity','payment_callback_event_identity_guard',19,'BEFORE UPDATE','ROW')
    ) AS triggers(table_name,trigger_name,function_name,trigger_type,events,level) LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid=to_regclass(format('%I.%I',current_schema(),item.table_name)) AND tgname=item.trigger_name) THEN
            IF current_setting('payment.order_wallet_replay',true)='on' THEN
                RAISE EXCEPTION 'payment guard trigger missing: %',item.trigger_name;
            END IF;
            EXECUTE format('CREATE TRIGGER %I %s ON %I FOR EACH %s EXECUTE FUNCTION %I.%I()',item.trigger_name,item.events,item.table_name,item.level,current_schema(),item.function_name);
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM pg_trigger t
            WHERE t.tgrelid=to_regclass(format('%I.%I',current_schema(),item.table_name)) AND t.tgname=item.trigger_name
              AND NOT t.tgisinternal AND t.tgenabled='O' AND t.tgtype=item.trigger_type
              AND t.tgfoid=to_regprocedure(format('%I.%I()',current_schema(),item.function_name))
              AND t.tgqual IS NULL AND t.tgnargs=0 AND t.tgattr=''::int2vector
        ) THEN
            RAISE EXCEPTION 'payment guard trigger contract differs: %',item.trigger_name;
        END IF;
    END LOOP;
END $payment_guards$;

