-- Maintainer-only forward migration. Run the whole file in one transaction
-- with API/Worker stopped. No seed order, wallet or payment fact is created.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '2min';
SELECT pg_advisory_xact_lock(20261016, 201);

DO $payment_prerequisites$
DECLARE
    required_table text;
    existing_count integer;
BEGIN
    FOREACH required_table IN ARRAY ARRAY['payment_config','payment_config_version','user_account','permission_auth_platform'] LOOP
        IF to_regclass(format('%I.%I',current_schema(),required_table)) IS NULL THEN
            RAISE EXCEPTION 'payment prerequisite missing from target schema: %', required_table;
        END IF;
    END LOOP;
    SELECT count(*) INTO existing_count
    FROM unnest(ARRAY['payment_wallet','payment_order','payment_transaction','payment_callback_event']) t(name)
    WHERE to_regclass(format('%I.%I',current_schema(),t.name)) IS NOT NULL;
    IF existing_count NOT IN (0,4) THEN
        RAISE EXCEPTION 'payment financial schema must be entirely absent or complete';
    END IF;
    IF current_setting('payment.order_wallet_verify_only',true)='on'
       AND (existing_count<>4 OR to_regclass(format('%I.payment_recharge_package',current_schema())) IS NULL) THEN
        RAISE EXCEPTION 'payment schema missing; verification cannot create objects';
    END IF;
    PERFORM set_config('payment.order_wallet_replay', CASE WHEN existing_count=4 THEN 'on' ELSE 'off' END,true);
END $payment_prerequisites$;

DO $payment_existing_contract$
DECLARE
    item record;
    actual_names text[];
    index_name text;
BEGIN
    -- IF NOT EXISTS is not a schema validator. Reject a same-named partial or
    -- legacy table before any new payment fact can be created in this tx.
    FOR item IN SELECT * FROM (VALUES
        ('payment_recharge_package', ARRAY['id','name','amount_cents','badge','sort_order','is_enabled','created_at','updated_at','deleted_at']::text[]),
        ('payment_wallet', ARRAY['user_id','balance_units','created_at','updated_at']::text[]),
        ('payment_order', ARRAY['id','order_no','user_id','platform_id','package_id','package_name','amount_cents','config_id','config_version','pay_method','request_id','request_fingerprint','return_url','status','provider_trade_no','expires_at','paid_at','credited_at','closed_at','next_check_at','check_token','check_lease_until','created_at','updated_at']::text[]),
        ('payment_transaction', ARRAY['id','transaction_no','user_id','platform_id','amount_units','balance_after_units','order_id','redeem_code_id','created_at','updated_at']::text[]),
        ('payment_callback_event', ARRAY['id','config_id','config_version','dedupe_key','order_id','payload','process_status','error_code','created_at','updated_at']::text[])
    ) AS expected(table_name, columns) LOOP
        IF to_regclass(format('%I.%I',current_schema(),item.table_name)) IS NOT NULL THEN
            EXECUTE format('LOCK TABLE %I.%I IN ACCESS EXCLUSIVE MODE',current_schema(),item.table_name);
            SELECT array_agg(a.attname::text ORDER BY a.attnum)
              INTO actual_names
              FROM pg_attribute a
             WHERE a.attrelid = to_regclass(format('%I.%I',current_schema(),item.table_name))
               AND a.attnum > 0 AND NOT a.attisdropped;
            IF actual_names IS DISTINCT FROM item.columns THEN
                RAISE EXCEPTION 'payment table column contract differs: %', item.table_name;
            END IF;
        END IF;
    END LOOP;
    IF current_setting('payment.order_wallet_replay',true)='on' THEN
        FOREACH index_name IN ARRAY ARRAY[
            'ux_payment_order_order_no','ux_payment_order_request',
            'ux_payment_order_provider_trade','ix_payment_order_user_created','ix_payment_order_created',
            'ix_payment_order_reconcile_check','ix_payment_order_reconcile_expiry','ux_payment_transaction_no',
            'ux_payment_transaction_order','ix_payment_transaction_user_created','ix_payment_transaction_created',
            'ux_payment_callback_event_dedupe','ix_payment_callback_event_order','ix_payment_callback_event_pending'
        ] LOOP
            IF to_regclass(format('%I.%I',current_schema(),index_name)) IS NULL THEN
                RAISE EXCEPTION 'payment index missing; replay cannot repair schema: %',index_name;
            END IF;
        END LOOP;
    END IF;
END $payment_existing_contract$;

CREATE TABLE IF NOT EXISTS payment_recharge_package (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(128) NOT NULL,
    amount_cents bigint NOT NULL,
    badge varchar(32),
    sort_order integer NOT NULL DEFAULT 0,
    is_enabled smallint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at timestamptz,
    CONSTRAINT ck_payment_recharge_package_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_payment_recharge_package_amount CHECK (amount_cents BETWEEN 1 AND 9223372036854),
    CONSTRAINT ck_payment_recharge_package_sort CHECK (sort_order >= 0),
    CONSTRAINT ck_payment_recharge_package_enabled CHECK (is_enabled IN (0,1))
);

CREATE TABLE IF NOT EXISTS payment_wallet (
    user_id bigint PRIMARY KEY,
    balance_units bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_wallet_user FOREIGN KEY (user_id) REFERENCES user_account(id) ON DELETE RESTRICT
);

