-- AI 对话工作台：会话、消息、运行、事件与用量账单。
-- 只覆盖文本对话；不包含知识库、工具调用、图片/视频/音频生成。
-- 运行状态：1=排队 2=运行中 3=成功 4=失败 5=取消 6=超时
-- 消息角色：1=用户 2=助手；消息状态：1=流式中 2=完成 3=停止 4=失败
-- 账单状态：1=待结算 2=已结算 3=未计费 4=结算失败
-- 可重复执行。

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.ai_chat_conversation (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_id      bigint      NOT NULL,
    user_id          bigint      NOT NULL,
    agent_id         bigint      NOT NULL,
    title            varchar(128) NOT NULL,
    last_message_at  timestamptz NOT NULL DEFAULT now(),
    message_count    integer     NOT NULL DEFAULT 0,
    version          bigint      NOT NULL DEFAULT 1,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    deleted_at       timestamptz,
    CONSTRAINT ai_chat_conversation_title_check CHECK (length(title) >= 1 AND length(title) <= 128),
    CONSTRAINT ai_chat_conversation_message_count_check CHECK (message_count >= 0),
    CONSTRAINT ai_chat_conversation_version_check CHECK (version >= 1),
    CONSTRAINT ai_chat_conversation_user_fk FOREIGN KEY (user_id) REFERENCES public.user_account(id) ON DELETE RESTRICT,
    CONSTRAINT ai_chat_conversation_agent_fk FOREIGN KEY (agent_id) REFERENCES public.ai_agent(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ai_chat_conversation_user_idx
    ON public.ai_chat_conversation (user_id, last_message_at DESC, id DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ai_chat_conversation_platform_user_idx
    ON public.ai_chat_conversation (platform_id, user_id, last_message_at DESC, id DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS public.ai_chat_message (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint      NOT NULL,
    seq             integer     NOT NULL,
    role            smallint    NOT NULL,
    content         text        NOT NULL DEFAULT '',
    status          smallint    NOT NULL,
    run_id          bigint,
    delivery_seq    bigint      NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_chat_message_seq_check CHECK (seq >= 1),
    CONSTRAINT ai_chat_message_role_check CHECK (role IN (1, 2)),
    CONSTRAINT ai_chat_message_status_check CHECK (status IN (1, 2, 3, 4)),
    CONSTRAINT ai_chat_message_delivery_seq_check CHECK (delivery_seq >= 0),
    CONSTRAINT ai_chat_message_conversation_fk FOREIGN KEY (conversation_id) REFERENCES public.ai_chat_conversation(id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS ai_chat_message_conversation_seq_uidx
    ON public.ai_chat_message (conversation_id, seq);
CREATE INDEX IF NOT EXISTS ai_chat_message_run_idx
    ON public.ai_chat_message (run_id)
    WHERE run_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.ai_chat_run (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id           varchar(64) NOT NULL,
    platform_id          bigint      NOT NULL,
    user_id              bigint      NOT NULL,
    conversation_id      bigint      NOT NULL,
    agent_id             bigint      NOT NULL,
    provider_id          bigint      NOT NULL,
    provider_model_id    bigint      NOT NULL,
    provider_protocol    smallint    NOT NULL DEFAULT 1,
    agent_name           varchar(128) NOT NULL DEFAULT '',
    provider_name        varchar(128) NOT NULL DEFAULT '',
    model_key            varchar(128) NOT NULL,
    model_name           varchar(128) NOT NULL DEFAULT '',
    timeout_ms           integer     NOT NULL DEFAULT 60000,
    pricing_snapshot     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    status               smallint    NOT NULL DEFAULT 1,
    billing_status       smallint    NOT NULL DEFAULT 1,
    error_code           varchar(64)  NOT NULL DEFAULT '',
    error_message        varchar(1024) NOT NULL DEFAULT '',
    input_tokens         bigint      NOT NULL DEFAULT 0,
    cached_input_tokens  bigint      NOT NULL DEFAULT 0,
    cache_write_tokens   bigint      NOT NULL DEFAULT 0,
    output_tokens        bigint      NOT NULL DEFAULT 0,
    amount_units         bigint      NOT NULL DEFAULT 0,
    balance_before_units bigint,
    balance_after_units  bigint,
    first_token_ms       integer,
    duration_ms          integer,
    cancel_requested_at  timestamptz,
    started_at           timestamptz,
    finished_at          timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_chat_run_request_id_check CHECK (length(request_id) >= 1 AND length(request_id) <= 64),
    CONSTRAINT ai_chat_run_status_check CHECK (status IN (1, 2, 3, 4, 5, 6)),
    CONSTRAINT ai_chat_run_billing_status_check CHECK (billing_status IN (1, 2, 3, 4)),
    CONSTRAINT ai_chat_run_tokens_check CHECK (
        input_tokens >= 0 AND cached_input_tokens >= 0 AND cache_write_tokens >= 0 AND output_tokens >= 0
    ),
    CONSTRAINT ai_chat_run_amount_check CHECK (amount_units >= 0),
    CONSTRAINT ai_chat_run_timeout_check CHECK (timeout_ms BETWEEN 1000 AND 300000),
    CONSTRAINT ai_chat_run_first_token_ms_check CHECK (first_token_ms IS NULL OR first_token_ms >= 0),
    CONSTRAINT ai_chat_run_duration_ms_check CHECK (duration_ms IS NULL OR duration_ms >= 0),
    CONSTRAINT ai_chat_run_user_fk FOREIGN KEY (user_id) REFERENCES public.user_account(id) ON DELETE RESTRICT,
    CONSTRAINT ai_chat_run_conversation_fk FOREIGN KEY (conversation_id) REFERENCES public.ai_chat_conversation(id) ON DELETE RESTRICT,
    CONSTRAINT ai_chat_run_agent_fk FOREIGN KEY (agent_id) REFERENCES public.ai_agent(id) ON DELETE RESTRICT,
    CONSTRAINT ai_chat_run_provider_fk FOREIGN KEY (provider_id) REFERENCES public.ai_provider(id) ON DELETE RESTRICT,
    CONSTRAINT ai_chat_run_provider_model_fk FOREIGN KEY (provider_model_id) REFERENCES public.ai_provider_model(id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS ai_chat_run_request_uidx
    ON public.ai_chat_run (platform_id, user_id, request_id);
CREATE UNIQUE INDEX IF NOT EXISTS ai_chat_run_one_active_per_conversation_uidx
    ON public.ai_chat_run (conversation_id)
    WHERE status IN (1, 2);
CREATE INDEX IF NOT EXISTS ai_chat_run_user_idx
    ON public.ai_chat_run (user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ai_chat_run_status_idx
    ON public.ai_chat_run (status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ai_chat_run_conversation_idx
    ON public.ai_chat_run (conversation_id, id DESC);
CREATE INDEX IF NOT EXISTS ai_chat_run_provider_model_idx
    ON public.ai_chat_run (provider_model_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.ai_chat_run_event (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     bigint      NOT NULL,
    seq        integer     NOT NULL,
    type       varchar(48) NOT NULL,
    message    varchar(500) NOT NULL DEFAULT '',
    data       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_chat_run_event_seq_check CHECK (seq >= 1),
    CONSTRAINT ai_chat_run_event_type_check CHECK (length(type) >= 1),
    CONSTRAINT ai_chat_run_event_run_fk FOREIGN KEY (run_id) REFERENCES public.ai_chat_run(id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS ai_chat_run_event_run_seq_uidx
    ON public.ai_chat_run_event (run_id, seq);

CREATE TABLE IF NOT EXISTS public.ai_usage_charge (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               bigint      NOT NULL,
    platform_id          bigint      NOT NULL,
    user_id              bigint      NOT NULL,
    provider_id          bigint      NOT NULL,
    provider_model_id    bigint      NOT NULL,
    status               smallint    NOT NULL,
    input_tokens         bigint      NOT NULL DEFAULT 0,
    cached_input_tokens  bigint      NOT NULL DEFAULT 0,
    cache_write_tokens   bigint      NOT NULL DEFAULT 0,
    output_tokens        bigint      NOT NULL DEFAULT 0,
    rate_ppm             bigint      NOT NULL DEFAULT 1000000,
    pricing_snapshot     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    amount_units         bigint      NOT NULL DEFAULT 0,
    balance_before_units bigint,
    balance_after_units  bigint,
    unbilled_reason      varchar(255) NOT NULL DEFAULT '',
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_usage_charge_status_check CHECK (status IN (1, 2)),
    CONSTRAINT ai_usage_charge_tokens_check CHECK (
        input_tokens >= 0 AND cached_input_tokens >= 0 AND cache_write_tokens >= 0 AND output_tokens >= 0
    ),
    CONSTRAINT ai_usage_charge_amount_check CHECK (amount_units >= 0),
    CONSTRAINT ai_usage_charge_user_fk FOREIGN KEY (user_id) REFERENCES public.user_account(id) ON DELETE RESTRICT,
    CONSTRAINT ai_usage_charge_run_fk FOREIGN KEY (run_id) REFERENCES public.ai_chat_run(id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS ai_usage_charge_run_uidx
    ON public.ai_usage_charge (run_id);
CREATE INDEX IF NOT EXISTS ai_usage_charge_user_idx
    ON public.ai_usage_charge (user_id, created_at DESC, id DESC);

COMMENT ON TABLE public.ai_chat_conversation IS 'AI 工作台会话；每个会话绑定一个智能体，只做文本对话';
COMMENT ON TABLE public.ai_chat_message IS 'AI 对话消息；助手消息在运行开始即创建，流式期间增量更新，便于断线后拉快照';
COMMENT ON TABLE public.ai_chat_run IS 'AI 对话运行；记录状态、usage、价格快照和最终扣费';
COMMENT ON TABLE public.ai_chat_run_event IS 'AI 运行时间线；不记录每个 token，只记录开始、首字、计费、结束等关键事件';
COMMENT ON TABLE public.ai_usage_charge IS 'AI 用量账单；按 run 唯一，允许余额为负，不做预冻结';
COMMENT ON COLUMN public.ai_chat_run.pricing_snapshot IS '运行时价格快照，包含官方输入/输出/缓存价格和供应商倍率';
COMMENT ON COLUMN public.ai_chat_run.billing_status IS '1=待结算 2=已结算 3=未计费 4=结算失败';
COMMENT ON COLUMN public.ai_usage_charge.status IS '1=已结算 2=未计费';
