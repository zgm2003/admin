-- AI 智能体头像、消息反馈与聊天附件
-- 维护者手工执行，幂等；API/Worker 启动不执行 DDL。

ALTER TABLE ai_agent
  ADD COLUMN IF NOT EXISTS avatar VARCHAR(512) NOT NULL DEFAULT '';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'ai_agent'::regclass AND conname = 'ai_agent_avatar_check'
  ) THEN
    ALTER TABLE ai_agent
      ADD CONSTRAINT ai_agent_avatar_check CHECK (length(avatar) <= 512);
  END IF;
END $$;

ALTER TABLE ai_chat_message
  ADD COLUMN IF NOT EXISTS feedback SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS feedback_at TIMESTAMPTZ;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'ai_chat_message'::regclass AND conname = 'ai_chat_message_feedback_check'
  ) THEN
    ALTER TABLE ai_chat_message
      ADD CONSTRAINT ai_chat_message_feedback_check CHECK (feedback IN (-1, 0, 1));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS ai_chat_message_attachment (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id       BIGINT NOT NULL REFERENCES ai_chat_message(id) ON DELETE CASCADE,
  kind             SMALLINT NOT NULL,
  object_key       VARCHAR(512) NOT NULL,
  file_name        VARCHAR(255) NOT NULL,
  mime_type        VARCHAR(128) NOT NULL,
  size_bytes       BIGINT NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ai_chat_message_attachment_kind_check CHECK (kind IN (1, 2)),
  CONSTRAINT ai_chat_message_attachment_size_check CHECK (size_bytes >= 0),
  CONSTRAINT ai_chat_message_attachment_object_key_check CHECK (length(object_key) BETWEEN 1 AND 512),
  CONSTRAINT ai_chat_message_attachment_message_object_uidx UNIQUE (message_id, object_key)
);

CREATE INDEX IF NOT EXISTS ai_chat_message_attachment_message_idx
  ON ai_chat_message_attachment(message_id, id);
