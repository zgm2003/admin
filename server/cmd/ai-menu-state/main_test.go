func TestArgumentsDefaultToPreviewAndRequireStoppedAssertionForApply(t *testing.T) {
	v, err := parseArgs(nil, &bytes.Buffer{})
	if err != nil || v.Apply || v.EnvFile != ".env" {
		t.Fatalf("default arguments = %+v, %v", v, err)
	}
	for _, args := range [][]string{{"--apply"}, {"--platform-id", "2"}, {"extra"}} {
		if _, err := parseArgs(args, &bytes.Buffer{}); err == nil {
			t.Fatalf("accepted unsafe arguments: %v", args)
		}
	}
	v, err = parseArgs([]string{"--apply", "--services-stopped", "--env-file", "fixture.env"}, &bytes.Buffer{})
	if err != nil || !v.Apply || v.EnvFile != "fixture.env" {
		t.Fatalf("apply arguments = %+v, %v", v, err)
	}
}

func menuFixture(t *testing.T) (*gorm.DB, context.Context, *projectredis.Client, int64, int64, string) {
	t.Helper()
	if testing.Short() {
		t.Skip("isolated PostgreSQL and Redis integration")
	}
	if err := godotenv.Load("../../.env"); err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	db, ctx := testschema.Open(t, os.Getenv("POSTGRES_DSN"), "test_ai_menu_state")
	db = db.Session(&gorm.Session{Logger: logger.Default.LogMode(logger.Silent)})
	client, err := projectredis.Open(ctx, os.Getenv("REDIS_URL"))
	if err != nil {
		t.Fatal(err)
	}
	adminID := time.Now().UnixNano()
	canvasID := adminID + 1
	keys := []string{permissionstate.MenuStateKey(adminID), permissionstate.MenuStateKey(canvasID), permissionstate.StateKey(adminID)}
	t.Cleanup(func() { _ = client.DeleteMany(context.Background(), keys); _ = client.Close() })
	if err := db.WithContext(ctx).Exec(`CREATE TABLE permission_auth_platform(id bigint PRIMARY KEY,code varchar(64) NOT NULL,status smallint NOT NULL,menu_version bigint NOT NULL,deleted_at timestamptz,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE permission_menu(LIKE public.permission_menu INCLUDING ALL);
ALTER TABLE permission_menu ALTER COLUMN id DROP DEFAULT;
ALTER TABLE permission_menu ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE permission_role_menu(id bigint PRIMARY KEY,role_id bigint NOT NULL,menu_id bigint NOT NULL,deleted_at timestamptz);`).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Exec(`INSERT INTO permission_auth_platform(id,code,status,menu_version) VALUES(?,'admin',1,24),(?,'canvas',1,5)`, adminID, canvasID).Error; err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(filepath.Join("../../../docs/database/2026-10-28-ai-menu.sql"))
	if err != nil {
		t.Fatal(err)
	}
	return db, ctx, client, adminID, canvasID, string(raw)
}

func TestMenuPublishUsesDatabaseVersionAndTouchesOnlyAdminState(t *testing.T) {
	db, ctx, client, adminID, canvasID, migration := menuFixture(t)
	store := permissionstate.NewMenuStore(client)
	for id, version := range map[int64]int64{adminID: 24, canvasID: 5} {
		if err := store.RebuildReadyState(ctx, id, version); err != nil {
			t.Fatal(err)
		}
	}
	const userState = `{"schemaVersion":2,"state":"ready","version":7}`
	if err := client.SetString(ctx, permissionstate.StateKey(adminID), userState, 0); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	if err := execute(ctx, db, store, false, &out); err != nil {
		t.Fatal(err)
	}
	var before report
	if err := json.Unmarshal(out.Bytes(), &before); err != nil || !before.DryRun || before.Facts.Nodes != 0 || before.Facts.Version != 24 {
		t.Fatalf("preview = %s, %v", out.String(), err)
	}
	if err := execute(ctx, db, store, true, &bytes.Buffer{}); err == nil {
		t.Fatal("published unseeded AI menu")
	}
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(migration).Error }); err != nil {
		t.Fatal(err)
	}
	for _, apply := range []bool{false, true, true} {
		out.Reset()
		if err := execute(ctx, db, store, apply, &out); err != nil {
			t.Fatal(err)
		}
		var actual report
		if err := json.Unmarshal(out.Bytes(), &actual); err != nil || actual.Facts.Nodes != 45 || actual.Facts.Version != 25 {
			t.Fatalf("after migration = %s, %v", out.String(), err)
		}
		want := int64(24)
		if apply {
			want = 25
		}
		state, found, err := store.Read(ctx, adminID)
		if err != nil || !found || state.Version != want {
			t.Fatalf("Admin state = %+v, %v, %v", state, found, err)
		}
	}
	state, found, err := store.Read(ctx, canvasID)
	if err != nil || !found || state.Version != 5 {
		t.Fatalf("Canvas state changed: %+v, %v", state, err)
	}
	value, _, err := client.GetString(ctx, permissionstate.StateKey(adminID))
	if err != nil || value != userState {
		t.Fatalf("user access state changed: %q, %v", value, err)
	}
	var grants int64
	if err := db.WithContext(ctx).Table("permission_role_menu").Count(&grants).Error; err != nil || grants != 0 {
		t.Fatalf("grants changed: %d, %v", grants, err)
	}
}

func TestMenuPublishPreservesInvalidatingNewerAndCorruptStates(t *testing.T) {
	db, ctx, client, adminID, _, migration := menuFixture(t)
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(migration).Error }); err != nil {
		t.Fatal(err)
	}
	store := permissionstate.NewMenuStore(client)
	for name, raw := range map[string]string{
		"mutation": `{"schemaVersion":2,"state":"invalidating","version":0,"mutationToken":"owner","baseVersion":24}`,
		"newer":    `{"schemaVersion":2,"state":"ready","version":26}`,
		"corrupt":  `{broken`,
	} {
		t.Run(name, func(t *testing.T) {
			if err := client.SetString(ctx, permissionstate.MenuStateKey(adminID), raw, 0); err != nil {
				t.Fatal(err)
			}
			if err := execute(ctx, db, store, true, &bytes.Buffer{}); err == nil {
				t.Fatal("unsafe state overwritten")
			}
			got, _, err := client.GetString(ctx, permissionstate.MenuStateKey(adminID))
			if err != nil || got != raw {
				t.Fatalf("state changed: %s, %v", got, err)
			}
		})
	}
	if err := db.WithContext(ctx).Exec("DELETE FROM permission_menu WHERE code='ai:chat:cancel'").Error; err != nil {
		t.Fatal(err)
	}
	if err := client.SetString(ctx, permissionstate.MenuStateKey(adminID), `{"schemaVersion":2,"state":"ready","version":24}`, 0); err != nil {
		t.Fatal(err)
	}
	if err := execute(ctx, db, store, true, &bytes.Buffer{}); err == nil {
		t.Fatal("published partial AI menu")
	}
}

