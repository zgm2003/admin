func TestIntegrationPricePublishPreservesHistoryAndNewSyncRMB(t *testing.T) {
	db, ctx := priceIntegrationFixture(t)
	repo := NewRepository(db)
	s := NewService(repo, &pgRuntime{db: db})
	at := time.Now().UTC().Add(-time.Hour).Truncate(time.Microsecond)
	source := sourceFor(textRate("1"))
	source.EffectiveAt = &at
	p, err := s.PreviewSync(ctx, 1, source, 1)
	if err != nil {
		t.Fatal(err)
	}
	if err := s.Publish(ctx, 1, p.ID, p.SnapshotDigest, 1); err != nil {
		t.Fatal(err)
	}
	if err := s.Publish(ctx, 1, p.ID, p.SnapshotDigest, 1); err != nil {
		t.Fatal(err)
	}
	future := time.Now().UTC().Add(time.Hour).Truncate(time.Microsecond)
	updated, err := s.PreviewUpdate(ctx, 1, p.ID, UpdatePriceRequest{EffectiveAt: &future, Rates: []UpdateRate{{RateID: p.Rates[0].ID, BillingUnitPriceUnits: ptr(222)}}}, 1)
	if err != nil {
		t.Fatal(err)
	}
	if err := s.Publish(ctx, 1, updated.ID, updated.SnapshotDigest, 1); err != nil {
		t.Fatal(err)
	}
	effective, err := s.Effective(ctx, 1, time.Now())
	if err != nil || effective.ID != p.ID {
		t.Fatalf("old Run repriced: id=%v err=%v", effective, err)
	}
	next, err := s.PreviewSync(ctx, 1, sourceFor(textRate("3")), 1)
	if err != nil {
		t.Fatal(err)
	}
	if next.Rates[0].BillingUnitPriceUnits == nil || *next.Rates[0].BillingUnitPriceUnits != 222 {
		t.Fatalf("RMB overwritten %+v", next.Rates)
	}
	old, err := repo.Find(ctx, 1, p.ID)
	if err != nil || old.Rates[0].SourceUnitPrice != "1.000000000000" || *old.Rates[0].BillingUnitPriceUnits != 100000000 {
		t.Fatalf("history mutated %+v %v", old, err)
	}
	if err := s.SetBillingPrice(ctx, 1, p.ID, UpdatePriceRequest{Rates: []UpdateRate{{RateID: p.Rates[0].ID, BillingUnitPriceUnits: ptr(3)}}}, 1); err == nil {
		t.Fatal("published price mutable")
	}
}
func TestIntegrationPriceConcurrentSyncHasDistinctVersions(t *testing.T) {
	db, ctx := priceIntegrationFixture(t)
	s := NewService(NewRepository(db), &pgRuntime{db: db})
	var wg sync.WaitGroup
	errs := make(chan error, 2)
	for i := 0; i < 2; i++ {
		wg.Add(1)
		go func() { defer wg.Done(); _, err := s.PreviewSync(ctx, 1, sourceFor(textRate("1")), 1); errs <- err }()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		if err != nil {
			t.Fatal(err)
		}
	}
	var versions []int64
	if err := db.WithContext(ctx).Raw("SELECT version FROM ai_provider_model_price_version ORDER BY version").Scan(&versions).Error; err != nil {
		t.Fatal(err)
	}
	if len(versions) != 2 || versions[0] != 1 || versions[1] != 2 {
		t.Fatalf("versions=%v", versions)
	}
}

type pgRuntime struct {
	db *gorm.DB
	mu sync.Mutex
}

func (r *pgRuntime) Mutate(ctx context.Context, fn func(context.Context, int64) (configcache.MutationResult, error)) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	base, err := configcache.NewRepository(r.db).Current(ctx, configcache.Scope{Namespace: "ai.runtime", ScopeKey: "global"})
	if err != nil {
		return err
	}
	_, err = fn(ctx, base)
	return err
}
