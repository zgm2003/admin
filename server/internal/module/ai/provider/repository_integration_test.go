type providerPGRuntime struct {
	db *gorm.DB
	mu sync.Mutex
}

func (r *providerPGRuntime) Mutate(ctx context.Context, fn func(context.Context, int64) (configcache.MutationResult, error)) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	base, err := configcache.NewRepository(r.db).Current(ctx, configcache.Scope{Namespace: "ai.runtime", ScopeKey: "global"})
	if err != nil {
		return err
	}
	_, err = fn(ctx, base)
	return err
}

type fixturePricingSource struct{ snapshot OpenAIPricingSnapshot }

func (f fixturePricingSource) FetchPricing(context.Context) (OpenAIPricingSnapshot, error) {
	return f.snapshot, nil
}
func TestIntegrationProviderModelPriceAndCredentialRevisions(t *testing.T) {
	db, ctx := providerIntegrationFixture(t)
	runtime := &providerPGRuntime{db: db}
	repo := NewRepository(db)
	svc := NewService(repo, testCipher(t), runtime)
	request := fixtureCreate()
	request.Code = "openai"
	request.BaseURL = "https://api.openai.com/v1"
	p, err := svc.Create(ctx, request, 1)
	if err != nil {
		t.Fatal(err)
	}
	first, err := repo.CurrentVersion(ctx, p.ID)
	if err != nil {
		t.Fatal(err)
	}
	_, err = svc.Update(ctx, p.ID, UpdateRequest{Name: "Updated", BaseURL: request.BaseURL, MediaHostAllowlist: request.MediaHostAllowlist, RequestTimeoutMS: 30000}, 1)
	if err != nil {
		t.Fatal(err)
	}
	current, err := repo.CurrentVersion(ctx, p.ID)
	if err != nil || current.ID == first.ID || current.APIKeyCiphertext != first.APIKeyCiphertext {
		t.Fatal("credential revision contract", err)
	}
	frozen, err := repo.Version(ctx, first.ID)
	if err != nil || frozen.BaseURL != first.BaseURL {
		t.Fatal("frozen version changed", err)
	}
	standard := official.NewService(official.NewRepository(db))
	standard.SetRuntimeCoordinator(runtime)
	o, err := standard.Create(ctx, official.CreateRequest{VendorCode: "openai", ModelKey: "gpt-5", Name: "Fixture standard", Operations: []string{"text.generate"}, SourceURLs: []byte(`[]`), Status: 1}, 1)
	if err != nil {
		t.Fatal(err)
	}
	models := price.NewModelService(price.NewModelRepository(db))
	models.SetRuntimeCoordinator(runtime)
	m, err := models.Create(ctx, p.ID, price.CreateModelRequest{UpstreamModelID: "gpt-5", Name: "Fixture", OfficialModelID: &o.ID, Operations: []string{"text.generate"}, Limits: []byte(`{}`)})
	if err != nil {
		t.Fatal(err)
	}
	if err := models.SetStatus(ctx, p.ID, m.ID, 1); err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile("model/testdata/openai-pricing.md")
	if err != nil {
		t.Fatal(err)
	}
	rates, err := ParsePricingMarkdown(raw)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(raw)
	prices := price.NewService(price.NewRepository(db), runtime)
	sync := NewPriceSyncService(repo, fixturePricingSource{OpenAIPricingSnapshot{Digest: hex.EncodeToString(sum[:]), Payload: raw, SyncedAt: time.Now().UTC(), Rates: rates}}, prices)
	preview, err := sync.Preview(ctx, p.ID, m.ID, 1)
	if err != nil {
		t.Fatal(err)
	}
	if len(preview.Rates) != 3 {
		t.Fatalf("model prices mixed: %d", len(preview.Rates))
	}
	if err := prices.Publish(ctx, m.ID, preview.ID, preview.SnapshotDigest, 1); err != nil {
		t.Fatal(err)
	}
	if _, err := prices.Effective(ctx, m.ID, time.Now().UTC()); err != nil {
		t.Fatal(err)
	}
	var gen, outbox int64
	if err := db.WithContext(ctx).Raw(`SELECT generation FROM system_config_cache_state`).Scan(&gen).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_config_cache_outbox`).Scan(&outbox).Error; err != nil || outbox != gen-1 {
		t.Fatalf("config facts not atomic: gen=%d outbox=%d %v", gen, outbox, err)
	}
}
func TestIntegrationProviderMutationRollsBackWhenGenerationOutboxFails(t *testing.T) {
	db, ctx := providerIntegrationFixture(t)
	runtime := &providerPGRuntime{db: db}
	repo := NewRepository(db)
	svc := NewService(repo, testCipher(t), runtime)
	p, err := svc.Create(ctx, fixtureCreate(), 1)
	if err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Exec(`DROP TABLE system_config_cache_outbox`).Error; err != nil {
		t.Fatal(err)
	}
	_, err = svc.Update(ctx, p.ID, UpdateRequest{Name: "Must rollback", BaseURL: "https://api.example.test/v1", MediaHostAllowlist: []byte(`[]`), RequestTimeoutMS: 30000}, 1)
	if err == nil {
		t.Fatal("outbox failure accepted")
	}
	saved, err := repo.Find(ctx, p.ID)
	if err != nil || saved.Name != "Fixture" || saved.CurrentVersion != 1 {
		t.Fatal("provider escaped rollback", err)
	}
	var count int64
	if err := db.WithContext(ctx).Table("ai_provider_version").Count(&count).Error; err != nil || count != 1 {
		t.Fatal("credential escaped rollback", err)
	}
}
