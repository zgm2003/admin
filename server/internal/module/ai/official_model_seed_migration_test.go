func applyOfficialModelSeed(t *testing.T, db *gorm.DB, ctx context.Context, sql string) error {
	t.Helper()
	return db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error })
}

func TestAIOfficialModelSeedIsIdempotentAndPreservesExistingRows(t *testing.T) {
	db, ctx, sql := officialModelSeedFixture(t)
	if err := applyOfficialModelSeed(t, db, ctx, sql); err != nil {
		t.Fatal(err)
	}
	var count int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM ai_official_model`).Scan(&count).Error; err != nil || count != 24 {
		t.Fatalf("seeded model count=%d err=%v", count, err)
	}
	var counts struct {
		OpenAI    int64
		Anthropic int64
		Chat      int64
		Image     int64
	}
	if err := db.WithContext(ctx).Raw(`
SELECT count(*) FILTER(WHERE vendor_code='openai') AS open_ai,
 count(*) FILTER(WHERE vendor_code='anthropic') AS anthropic,
 count(*) FILTER(WHERE operations=ARRAY['text.generate']::text[]) AS chat,
 count(*) FILTER(WHERE operations=ARRAY['image.generate']::text[]) AS image
FROM ai_official_model`).Scan(&counts).Error; err != nil {
		t.Fatal(err)
	}
	if counts.OpenAI != 14 || counts.Anthropic != 10 || counts.Chat != 23 || counts.Image != 1 {
		t.Fatalf("unexpected official model distribution: %+v", counts)
	}
	var version int64
	if err := db.WithContext(ctx).Raw(`SELECT generation FROM system_config_cache_state WHERE namespace='ai.runtime' AND scope_key='global'`).Scan(&version).Error; err != nil || version != 2 {
		t.Fatalf("runtime generation=%d err=%v", version, err)
	}
	if err := db.WithContext(ctx).Exec(`UPDATE ai_official_model SET name='Administrator name',status=0 WHERE vendor_code='openai' AND model_key='gpt-5.5'`).Error; err != nil {
		t.Fatal(err)
	}
	before := aiOfficialModelSeedFacts(t, db, ctx)
	if err := applyOfficialModelSeed(t, db, ctx, sql); err != nil {
		t.Fatal(err)
	}
	if after := aiOfficialModelSeedFacts(t, db, ctx); after != before {
		t.Fatalf("seed replay changed existing facts\nbefore=%s\nafter=%s", before, after)
	}
	var name string
	var status int16
	if err := db.WithContext(ctx).Raw(`SELECT name,status FROM ai_official_model WHERE vendor_code='openai' AND model_key='gpt-5.5'`).Row().Scan(&name, &status); err != nil || name != "Administrator name" || status != 0 {
		t.Fatalf("existing admin-owned row changed: name=%q status=%d err=%v", name, status, err)
	}
}

func aiOfficialModelSeedFacts(t *testing.T, db *gorm.DB, ctx context.Context) string {
	t.Helper()
	var facts string
	err := db.WithContext(ctx).Raw(`SELECT jsonb_build_object(
 'models',(SELECT coalesce(jsonb_agg(to_jsonb(m) ORDER BY id),'[]'::jsonb) FROM ai_official_model m),
 'state',(SELECT coalesce(jsonb_agg(to_jsonb(s) ORDER BY namespace,scope_key),'[]'::jsonb) FROM system_config_cache_state s),
 'outbox',(SELECT coalesce(jsonb_agg(to_jsonb(o) ORDER BY id),'[]'::jsonb) FROM system_config_cache_outbox o),
 'settings',(SELECT coalesce(jsonb_agg(to_jsonb(s) ORDER BY id),'[]'::jsonb) FROM system_setting s),
 'menus',(SELECT md5(coalesce(string_agg(to_jsonb(m)::text,'' ORDER BY m.id),'')) FROM permission_auth_platform m),
 'roleGrants',(SELECT coalesce(jsonb_agg(to_jsonb(g) ORDER BY id),'[]'::jsonb) FROM permission_role_menu g)
)::text`).Scan(&facts).Error
	if err != nil {
		t.Fatal(err)
	}
	return facts
}
