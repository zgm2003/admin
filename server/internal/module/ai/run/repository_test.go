func TestRunRepositoryAdmissionIdempotencyAndFrozenSnapshot(t *testing.T) {
	r, db, ctx := runDB(t)
	in := fixtureInput()
	snap := fixtureSnapshot()
	policy := json.RawMessage(`{"userInflightLimit":2}`)
	first, created, err := r.Create(ctx, in, snap, policy, snap.AcceptedAt)
	if err != nil || !created || first.ID < 1 {
		t.Fatalf("create=%+v %v %v", first, created, err)
	}
	snap.Prompt = "changed"
	second, created, err := r.Create(ctx, in, snap, policy, time.Now())
	var frozen RuntimeSnapshot
	decodeErr := json.Unmarshal(second.ConfigSnapshot, &frozen)
	if err != nil || decodeErr != nil || created || first.ID != second.ID || frozen.Prompt != "p" {
		t.Fatalf("replay=%+v created=%v err=%v", second, created, err)
	}
	in.Input = json.RawMessage(`{"text":"different"}`)
	if _, _, err := r.Create(ctx, in, snap, policy, time.Now()); !errors.Is(err, ErrIdempotencyConflict) {
		t.Fatalf("conflict=%v", err)
	}
	var jobs, events int64
	db.WithContext(ctx).Table("system_scheduler_job").Count(&jobs)
	db.WithContext(ctx).Table("ai_run_event").Count(&events)
	if jobs != 1 || events != 1 {
		t.Fatalf("jobs=%d events=%d", jobs, events)
	}
	var balance int64
	db.WithContext(ctx).Raw(`SELECT balance_units FROM payment_wallet WHERE user_id=1`).Scan(&balance)
	if balance != 100 {
		t.Fatalf("admission debited wallet=%d", balance)
	}
}
func TestRunRepositoryConcurrentSameKeyOneRunAndCrossPlatformReservations(t *testing.T) {
	r, db, ctx := runDB(t)
	in := fixtureInput()
	snap := fixtureSnapshot()
	policy := json.RawMessage(`{"userInflightLimit":2}`)
	var wg sync.WaitGroup
	errs := make(chan error, 2)
	ids := make(chan int64, 2)
	for i := 0; i < 2; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			m, _, e := r.Create(ctx, in, snap, policy, time.Now())
			errs <- e
			ids <- m.ID
		}()
	}
	wg.Wait()
	close(errs)
	for e := range errs {
		if e != nil {
			t.Fatal(e)
		}
	}
	a, b := <-ids, <-ids
	if a != b || a == 0 {
		t.Fatalf("ids=%d %d", a, b)
	}
	in.RequestKey = uuid.NewString()
	in.PlatformID = 2
	in.EstimatedUnits = 30
	if _, _, err := r.Create(ctx, in, snap, policy, time.Now()); !errors.Is(err, ErrAdmissionDenied) {
		t.Fatalf("cross platform coverage=%v", err)
	}
	db.WithContext(ctx).Exec(`UPDATE ai_run SET usage_status=2 WHERE id=?`, a)
	in.EstimatedUnits = 1
	if _, _, err := r.Create(ctx, in, snap, policy, time.Now()); !errors.Is(err, ErrUnknownInflight) {
		t.Fatalf("unknown=%v", err)
	}
}

func TestRecoverQueuedUsesFrozenQueuePolicyInsteadOfRunDeadline(t *testing.T) {
	r, db, ctx := runDB(t)
	in := fixtureInput()
	in.RequestKey = uuid.NewString()
	at := time.Now().UTC().Add(-10 * time.Second)
	in.DeadlineAt = at.Add(10 * time.Minute)
	snap := fixtureSnapshot()
	snap.AcceptedAt = at
	p := Policy{
		UserInflightLimit: 2, UserRatePerSecond: 1, UserRateBurst: 1, MaxQueuedSeconds: 1,
	}
	policy, err := json.Marshal(p)
	if err != nil {
		t.Fatal(err)
	}
	row, created, err := r.Create(ctx, in, snap, policy, at)
	if err != nil || !created {
		t.Fatalf("create=%+v created=%v err=%v", row, created, err)
	}
	if err := db.WithContext(ctx).Exec(`UPDATE system_scheduler_job SET status=4,last_error='failed',updated_at=now() WHERE source_key=?`, "ai.run.execute:"+fmt.Sprint(row.ID)+":1").Error; err != nil {
		t.Fatal(err)
	}
	count, err := r.RecoverQueued(ctx, at.Add(2*time.Second), 10)
	if err != nil || count != 1 {
		t.Fatalf("count=%d err=%v", count, err)
	}
	got, err := r.Find(ctx, row.ID)
	if err != nil || got.ExecutionStatus != 4 || got.ErrorCode == nil || *got.ErrorCode != "QUEUE_TIMEOUT" {
		t.Fatalf("run=%+v err=%v", got, err)
	}
}

func TestRuntimeRepositoryCapturesCompleteBindingAndFuturePriceBoundary(t *testing.T) {
	_, db, ctx := runDB(t)
	runtime := NewRuntimeRepository(db)
	at := time.Now().UTC()
	old, next, err := runtime.LoadRuntime(ctx, 1, at)
	if err != nil || next != nil || old.ProviderVersionID != 1 || old.PriceVersionID != 1 || old.BindingID != 1 || old.Prompt != "p" {
		t.Fatalf("snapshot=%+v next=%v err=%v", old, next, err)
	}
	if err := db.WithContext(ctx).Exec(`INSERT INTO ai_provider_model_price_version(id,provider_model_id,version,status,currency,source_currency,source_digest,snapshot_digest,source_payload,synced_at,created_by) VALUES(2,1,2,0,'CNY','USD',repeat('d',64),repeat('e',64),'{}',now(),1);INSERT INTO ai_provider_model_price_rate(price_version_id,operation,usage_key,selector,selector_hash,unit,unit_quantity,source_unit_price,billing_unit_price_units) VALUES(2,'text.generate','input','{}',repeat('f',64),'token',1000000,2,2);UPDATE ai_provider_model_price_version SET status=1,effective_at=now()+interval '1 hour',published_at=now(),published_by=1 WHERE id=2;UPDATE ai_agent SET system_prompt='changed' WHERE id=1;`).Error; err != nil {
		t.Fatal(err)
	}
	current, boundary, err := runtime.LoadRuntime(ctx, 1, at)
	if err != nil || current.PriceVersionID != 1 || boundary == nil || !boundary.After(at) || old.Prompt != "p" || current.Prompt != "changed" {
		t.Fatalf("current=%+v boundary=%v old=%+v err=%v", current, boundary, old, err)
	}
	future, _, err := runtime.LoadRuntime(ctx, 1, boundary.Add(time.Second))
	if err != nil || future.PriceVersionID != 2 {
		t.Fatalf("future=%+v err=%v", future, err)
	}
}
