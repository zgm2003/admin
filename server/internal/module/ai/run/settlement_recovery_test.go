package run

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"sync"
	"testing"
	"time"

	pr "admin/server/internal/module/ai/providerRequest"
	"admin/server/internal/module/ai/usage"
	"admin/server/internal/module/ai/usage/charge"
	ledger "admin/server/internal/module/payment/transaction"
	"admin/server/internal/module/payment/wallet"
	"admin/server/internal/module/system/scheduler"
	"github.com/google/uuid"
)

func TestSettlementDurableRetryRecoversAndDebitsOnce(t *testing.T) {
	r, db, ctx := runDB(t)
	if err := db.WithContext(ctx).Exec(`CREATE TABLE payment_transaction(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,transaction_no varchar(32) NOT NULL UNIQUE,user_id bigint NOT NULL,platform_id bigint NOT NULL,direction smallint NOT NULL,amount_units bigint NOT NULL,balance_before_units bigint NOT NULL,balance_after_units bigint NOT NULL,order_id bigint,redeem_code_id bigint,ai_usage_charge_id bigint UNIQUE,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL)`).Error; err != nil {
		t.Fatal(err)
	}
	snap := fixtureSnapshot()
	snap.Config = json.RawMessage(`{"rates":[{"id":1,"operation":"text.generate","usageKey":"input","selector":{},"unit":"token","unitQuantity":"1000000","billingUnitPriceUnits":1},{"id":2,"operation":"text.generate","usageKey":"output","selector":{},"unit":"token","unitQuantity":"1000000","billingUnitPriceUnits":1}]}`)
	now := time.Now().UTC().Truncate(time.Microsecond)
	row, _, err := r.Create(ctx, fixtureInput(), snap, completeClaimPolicy(t), now)
	if err != nil {
		t.Fatal(err)
	}
	token := uuid.NewString()
	if _, err = r.Claim(ctx, row.ID, token, now); err != nil {
		t.Fatal(err)
	}
	request, err := r.StartRequest(ctx, row.ID, token, 1, json.RawMessage(`{"model":"fixture"}`), now)
	if err != nil {
		t.Fatal(err)
	}
	if err = r.FinishRequest(ctx, row.ID, token, request.ID, pr.TextResponse{Usage: pr.TokenUsage{Known: true, InputTokens: 1, OutputTokens: 1, Raw: json.RawMessage(`{"output_tokens":1,"input_tokens":1}`)}}, nil, now); err != nil {
		t.Fatal(err)
	}
	if err = r.FinishText(ctx, row.ID, token, 3, "", "answer", now); err != nil {
		t.Fatal(err)
	}
	var ch charge.Model
	if err = db.WithContext(ctx).Where("run_id=?", row.ID).First(&ch).Error; err != nil {
		t.Fatal(err)
	}
	store := usage.NewRepository(db, wallet.NewRepository(db), ledger.NewRepository(db))
	// Failure recording and its durable retry job must commit together.
	if err = store.MarkFailure(ctx, ch.ID, errors.New("private dependency detail"), now); err == nil {
		t.Fatal("missing scheduler accepted")
	}
	if err = db.WithContext(ctx).First(&ch, ch.ID).Error; err != nil || ch.SettlementAttempts != 0 || ch.Status != 1 {
		t.Fatalf("partial failure record %+v %v", ch, err)
	}
	store.SetScheduler(scheduler.NewRepository(db))
	if err = store.MarkFailure(ctx, ch.ID, errors.New("private dependency detail"), now); err != nil {
		t.Fatal(err)
	}
	if err = db.WithContext(ctx).First(&ch, ch.ID).Error; err != nil || ch.NextSettleAt == nil || !ch.NextSettleAt.Equal(now.Add(5*time.Second)) {
		t.Fatalf("retry %+v %v", ch, err)
	}
	failedRun, err := r.Find(ctx, row.ID)
	if err != nil || failedRun.BillingStatus != 3 || failedRun.ReservationStatus != 1 {
		t.Fatalf("Run lost retry status: %+v %v", failedRun, err)
	}
	key := fmt.Sprintf("ai.usage.settle:%d:retry:1", ch.ID)
	var job scheduler.Job
	if err = db.WithContext(ctx).Where("source_key=?", key).First(&job).Error; err != nil {
		t.Fatal(err)
	}
	if job.MaxAttempts != 1 {
		t.Fatal("retry transport owns business retries")
	}
	if err = db.WithContext(ctx).Model(&job).Update("status", scheduler.JobFailed).Error; err != nil {
		t.Fatal(err)
	}
	if n, e := store.RecoverSettlements(ctx, now.Add(4*time.Second), 100); e != nil || n != 0 {
		t.Fatalf("early recover=%d %v", n, e)
	}
	if n, e := store.RecoverSettlements(ctx, now.Add(6*time.Second), 100); e != nil || n != 1 {
		t.Fatalf("recover=%d %v", n, e)
	}
	if err = db.WithContext(ctx).First(&job, job.ID).Error; err != nil || job.Status != scheduler.JobQueued {
		t.Fatalf("job=%+v %v", job, err)
	}
	if err = db.WithContext(ctx).Model(&charge.Model{}).Where("id=?", ch.ID).Update("settlement_attempts", 9).Error; err != nil {
		t.Fatal(err)
	}
	if err = store.MarkFailure(ctx, ch.ID, errors.New("dependency still unavailable"), now.Add(time.Minute)); err != nil {
		t.Fatal(err)
	}
	chargeID := ch.ID
	ch = charge.Model{}
	if err = db.WithContext(ctx).First(&ch, chargeID).Error; err != nil || ch.Status != 3 || ch.NextSettleAt != nil || ch.UsageComplete != 1 {
		t.Fatalf("exhausted known usage lost: %+v %v", ch, err)
	}
	if n, e := store.RecoverSettlements(ctx, now.Add(time.Hour), 100); e != nil || n != 0 {
		t.Fatalf("exhausted retry was automatic: %d %v", n, e)
	}
	service := usage.NewService(store)
	errs := make(chan error, 2)
	var wg sync.WaitGroup
	for range 2 {
		wg.Add(1)
		go func() { defer wg.Done(); errs <- service.Settle(ctx, ch.ID) }()
	}
	wg.Wait()
	close(errs)
	for e := range errs {
		if e != nil {
			t.Fatal(e)
		}
	}
	var count, balance int64
	if err = db.WithContext(ctx).Table("payment_transaction").Where("ai_usage_charge_id=?", ch.ID).Count(&count).Error; err != nil {
		t.Fatal(err)
	}
	if err = db.WithContext(ctx).Raw(`SELECT balance_units FROM payment_wallet WHERE user_id=1`).Scan(&balance).Error; err != nil {
		t.Fatal(err)
	}
	if count != 1 || balance != 99 {
		t.Fatalf("ledger=%d balance=%d", count, balance)
	}
	if n, e := store.RecoverSettlements(context.WithoutCancel(ctx), now.Add(time.Minute), 100); e != nil || n != 0 {
		t.Fatalf("settled recovered=%d %v", n, e)
	}
}
