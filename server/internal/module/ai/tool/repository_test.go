func TestUpdateCreatesImmutableVersionAndKeepsFrozenVersion(t *testing.T) {
	db, ctx := toolDB(t)
	svc := NewService(NewRepository(db), directRuntime{db})
	in := ToolInput{Code: "c", Name: "C", Status: StatusEnabled, ActorID: 1, Version: VersionInput{Type: TypeBuiltin, BuiltinKey: "calculator", Description: "one", InputSchema: json.RawMessage(`{"type":"object"}`), OutputSchema: json.RawMessage(`{"type":"object"}`), TimeoutMS: 1000, OutputLimitBytes: 65536}}
	id, e := svc.Create(ctx, in)
	if e != nil {
		t.Fatal(e)
	}
	first, e := svc.CurrentVersion(ctx, id)
	if e != nil {
		t.Fatal(e)
	}
	in.Version.Description = "two"
	if e := svc.Update(ctx, id, UpdateInput{Name: "C2", ActorID: 1, Version: in.Version}); e != nil {
		t.Fatal(e)
	}
	second, e := svc.CurrentVersion(ctx, id)
	if e != nil || second.Version != 2 || first.ID == second.ID {
		t.Fatalf("new version missing %+v %v", second, e)
	}
	frozen, e := svc.Version(ctx, first.ID)
	if e != nil || frozen.Description != "one" {
		t.Fatalf("old version overwritten %+v %v", frozen, e)
	}
	if e := db.WithContext(ctx).Exec(`UPDATE ai_tool_version SET description='tampered' WHERE id=?`, first.ID).Error; e == nil {
		t.Fatal("immutable version modified")
	}
}

type directRuntime struct{ db *gorm.DB }

func (r directRuntime) Mutate(ctx context.Context, fn func(context.Context, int64) (configcache.MutationResult, error)) error {
	gen, e := configcache.NewRepository(r.db).Current(ctx, configcache.Scope{Namespace: "ai.runtime", ScopeKey: "global"})
	if e != nil {
		return e
	}
	_, e = fn(ctx, gen)
	return e
}
