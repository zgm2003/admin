func TestAICoreSeedMatchesCurrentPostgreSQLSharedStructure(t *testing.T) {
	db, ctx, sql := aiCoreSeedFixture(t)
	// LIKE copies checks/indexes but not FKs. Replace every copied ID default
	// before inserting: a serial default must never consume a public sequence.
	if err := db.WithContext(ctx).Exec(`
DROP TABLE system_config_cache_outbox,system_config_cache_state,system_setting,system_scheduler_schedule;
CREATE TABLE system_setting(LIKE public.system_setting INCLUDING ALL);
CREATE TABLE system_config_cache_state(LIKE public.system_config_cache_state INCLUDING ALL);
CREATE TABLE system_config_cache_outbox(LIKE public.system_config_cache_outbox INCLUDING ALL);
CREATE TABLE system_scheduler_schedule(LIKE public.system_scheduler_schedule INCLUDING ALL);
DO $$ DECLARE name_ text; BEGIN
 FOREACH name_ IN ARRAY ARRAY['system_setting','system_config_cache_outbox','system_scheduler_schedule'] LOOP
  EXECUTE format('ALTER TABLE %I ALTER COLUMN id DROP IDENTITY IF EXISTS',name_);
  EXECUTE format('ALTER TABLE %I ALTER COLUMN id DROP DEFAULT',name_);
  EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',name_);
 END LOOP;
END $$;
ALTER TABLE system_config_cache_outbox ADD FOREIGN KEY(namespace,scope_key) REFERENCES system_config_cache_state(namespace,scope_key);
INSERT INTO system_config_cache_state(namespace,scope_key,generation) VALUES('system.setting','global',7);
`).Error; err != nil {
		t.Fatal(err)
	}
	var wrongSequence int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM unnest(ARRAY['system_setting','system_config_cache_outbox','system_scheduler_schedule']) t(name) JOIN pg_class c ON c.oid=pg_get_serial_sequence(name,'id')::regclass JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname<>current_schema()`).Scan(&wrongSequence).Error; err != nil || wrongSequence != 0 {
		t.Fatalf("fixture points at public sequence: %d %v", wrongSequence, err)
	}
	if err := applyAICoreSeed(t, db, ctx, sql); err != nil {
		t.Fatal(err)
	}
	before := aiSeedFacts(t, db, ctx)
	if err := applyAICoreSeed(t, db, ctx, sql); err != nil {
		t.Fatal(err)
	}
	if got := aiSeedFacts(t, db, ctx); got != before {
		t.Fatal("replay changed current-schema clone")
	}
}

