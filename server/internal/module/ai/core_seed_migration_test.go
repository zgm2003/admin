func TestAICoreSeedIsIdempotentAndInitializesGenerationAndSchedules(t *testing.T) {
	db, ctx, sql := aiCoreSeedFixture(t)
	if err := applyAICoreSeed(t, db, ctx, sql); err != nil {
		t.Fatal(err)
	}
	want := map[string]string{
		"ai.run.user_inflight_limit": "2", "ai.run.user_rate_per_second": "1", "ai.run.user_rate_burst": "5",
		"ai.run.global_rate_per_second": "200", "ai.run.global_rate_burst": "400",
		"ai.run.queued_backpressure_threshold": "1000", "ai.run.active_backpressure_threshold": "2000",
		"ai.run.max_queued_seconds": "60", "ai.run.text_timeout_seconds": "180", "ai.run.image_timeout_seconds": "300",
		"ai.run.audio_timeout_seconds": "300", "ai.run.video_timeout_seconds": "3600", "ai.run.max_model_rounds": "8",
		"ai.run.max_tool_calls": "16", "ai.run.max_bound_tools": "16", "ai.run.max_input_attachments": "4",
		"ai.run.max_output_tokens": "4096", "ai.run.max_text_input_bytes": "131072", "ai.run.max_images": "4",
		"ai.media.image_max_bytes": "10485760", "ai.media.audio_max_bytes": "104857600", "ai.media.video_max_bytes": "524288000",
		"ai.media.download_timeout_seconds": "300", "ai.media.transfer_timeout_seconds": "900",
		"ai.media.spool_max_bytes_per_worker": "2147483648", "ai.run.event_retention_days": "7",
	}
	var rows []struct {
		Key                          string `gorm:"column:setting_key"`
		Value                        string
		ValueType, Status, IsBuiltin int16
	}
	if err := db.WithContext(ctx).Raw(`SELECT setting_key,value,value_type,status,is_builtin FROM system_setting`).Scan(&rows).Error; err != nil {
		t.Fatal(err)
	}
	for _, row := range rows {
		if row.Value != want[row.Key] || row.ValueType != 2 || row.Status != 1 || row.IsBuiltin != 1 {
			t.Fatalf("incorrect policy seed: %+v", row)
		}
		delete(want, row.Key)
	}
	if len(want) != 0 {
		t.Fatalf("missing policy seeds: %v", want)
	}
	var settings int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_setting WHERE setting_key LIKE 'ai.%' AND deleted_at IS NULL`).Scan(&settings).Error; err != nil || settings != 26 {
		t.Fatalf("AI setting count=%d err=%v", settings, err)
	}
	var generation, outbox int64
	if err := db.WithContext(ctx).Raw(`SELECT generation FROM system_config_cache_state WHERE namespace='ai.runtime' AND scope_key='global'`).Scan(&generation).Error; err != nil || generation != 1 {
		t.Fatalf("generation=%d err=%v", generation, err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_config_cache_outbox WHERE namespace='ai.runtime' AND scope_key='global' AND generation=1`).Scan(&outbox).Error; err != nil || outbox != 1 {
		t.Fatalf("outbox=%d err=%v", outbox, err)
	}
	var schedules int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_scheduler_schedule WHERE builtin_key IN ('ai.run.recover','ai.run.event.cleanup') AND deleted_at IS NULL`).Scan(&schedules).Error; err != nil || schedules != 2 {
		t.Fatalf("schedules=%d err=%v", schedules, err)
	}
	var invalidSchedules int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_scheduler_schedule WHERE task_type<>builtin_key OR timezone<>'Asia/Shanghai' OR params<>'{}'::jsonb OR status<>0 OR next_run_at IS NOT NULL OR (builtin_key='ai.run.recover' AND cron_expression<>'* * * * *') OR (builtin_key='ai.run.event.cleanup' AND cron_expression<>'0 3 * * *')`).Scan(&invalidSchedules).Error; err != nil || invalidSchedules != 0 {
		t.Fatalf("scheduler seed runs before worker activation, or has invalid shape: %d %v", invalidSchedules, err)
	}
	var settingGeneration int64
	if err := db.WithContext(ctx).Raw(`SELECT generation FROM system_config_cache_state WHERE namespace='system.setting' AND scope_key='global'`).Scan(&settingGeneration).Error; err != nil || settingGeneration != 8 {
		t.Fatalf("setting cache not invalidated: generation=%d err=%v", settingGeneration, err)
	}
	if err := db.WithContext(ctx).Exec(`UPDATE system_setting SET value='9' WHERE setting_key='ai.run.max_tool_calls'`).Error; err != nil {
		t.Fatal(err)
	}
	before := aiSeedFacts(t, db, ctx)
	if err := applyAICoreSeed(t, db, ctx, sql); err != nil {
		t.Fatal(err)
	}
	var value string
	if err := db.WithContext(ctx).Raw(`SELECT value FROM system_setting WHERE setting_key='ai.run.max_tool_calls'`).Scan(&value).Error; err != nil || value != "9" {
		t.Fatalf("existing setting overwritten: %q err=%v", value, err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_setting WHERE setting_key LIKE 'ai.%' AND deleted_at IS NULL`).Scan(&settings).Error; err != nil || settings != 26 {
		t.Fatalf("replay duplicated settings=%d err=%v", settings, err)
	}
	if got := aiSeedFacts(t, db, ctx); got != before {
		t.Fatal("replay changed timestamps, policy, generation, outbox or scheduler facts")
	}
}

