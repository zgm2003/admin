type mediaDeadlineVideoPoller struct{ deadlines chan time.Time }

func (p *mediaDeadlineVideoPoller) Poll(ctx context.Context, _ providerrequest.FrozenConfig, _ string) (providerrequest.VideoResource, error) {
	deadline, ok := ctx.Deadline()
	if !ok {
		p.deadlines <- time.Time{}
		return providerrequest.VideoResource{}, errors.New("provider poll has no deadline")
	}
	p.deadlines <- deadline
	<-ctx.Done()
	return providerrequest.VideoResource{}, ctx.Err()
}

