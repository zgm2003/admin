func TestImportRetryPersistsNextJobAndFrozenDeadline(t *testing.T) {
	r, db, ctx := mediaRepositoryDB(t)
	now := time.Now().UTC()
	deadline := now.Add(time.Minute)
	key := "123e4567-e89b-12d3-a456-426614174001"
	f := &File{RunID: 1, Role: FileRoleGenerated, Ordinal: 0, ImportRequestKey: &key, SourceKind: SourceURL, SourceRecoverable: 1, SourceCiphertext: ptrString("sealed"), EncryptionKeyID: ptrString("key"), TransferDeadline: &deadline, Metadata: []byte(`{}`), TransferStatus: TransferQueued, CreatedAt: now, UpdatedAt: now}
	if err := r.CreateGeneratedFile(ctx, f); err != nil {
		t.Fatal(err)
	}
	claimed, found, err := r.ClaimImport(ctx, now)
	if err != nil || !found {
		t.Fatalf("found=%v err=%v", found, err)
	}
	s := &Service{repository: r}
	if err := s.retryImport(ctx, claimed, "TEMP", "private", now); err != nil {
		t.Fatal(err)
	}
	var saved File
	if err := db.WithContext(ctx).First(&saved, f.ID).Error; err != nil {
		t.Fatal(err)
	}
	if saved.NextTransferAt == nil || !saved.NextTransferAt.Equal(now.Add(5*time.Second)) || !saved.TransferDeadline.Equal(deadline) {
		t.Fatalf("saved=%+v", saved)
	}
	var jobs []scheduler.Job
	if err := db.WithContext(ctx).Order("id").Find(&jobs).Error; err != nil {
		t.Fatal(err)
	}
	if len(jobs) != 2 || !jobs[1].AvailableAt.Equal(*saved.NextTransferAt) {
		t.Fatalf("jobs=%+v", jobs)
	}
}
