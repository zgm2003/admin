func TestInlineImportRejectsCompletionFromStaleAttempt(t *testing.T) {
	r, db, ctx := mediaRepositoryDB(t)
	now := time.Now().UTC()
	key := "123e4567-e89b-12d3-a456-426614174003"
	row := File{RunID: 1, Role: FileRoleGenerated, Ordinal: 1, ImportRequestKey: &key, SourceKind: SourceStream, SourceRecoverable: 0, TransferDeadline: ptrTime(now.Add(time.Minute)), MIMEType: ptrString("image/png"), Metadata: []byte(`{}`), TransferStatus: Transfering, TransferAttempts: 2, CreatedAt: now, UpdatedAt: now}
	if err := db.WithContext(ctx).Create(&row).Error; err != nil {
		t.Fatal(err)
	}
	stale := row
	stale.TransferAttempts = 1
	path := filepath.Join(t.TempDir(), "image.png")
	if err := os.WriteFile(path, []byte("image"), 0600); err != nil {
		t.Fatal(err)
	}
	s := &Service{repository: r, files: mediaImportStub{}, now: func() time.Time { return now }}
	_, err := s.saveInlineSpool(ctx, auth.Identity{UserID: 1, PlatformID: 1}, InlineImport{RunID: 1, OriginalName: "image.png", MIME: "image/png"}, &stale, &SpoolFile{Path: path, MIME: "image/png", SizeBytes: 5})
	if !errors.Is(err, ErrConflict) {
		t.Fatalf("stale completion error=%v want=%v", err, ErrConflict)
	}
	var saved File
	if err := db.WithContext(ctx).First(&saved, row.ID).Error; err != nil {
		t.Fatal(err)
	}
	if saved.TransferStatus != Transfering || saved.TransferAttempts != 2 || saved.StorageFileID != nil {
		t.Fatalf("stale completion changed current attempt: %+v", saved)
	}
}
