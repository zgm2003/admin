func mediaRepositoryDB(t *testing.T) (*Repository, *gorm.DB, context.Context) {
	t.Helper()
	if testing.Short() || os.Getenv("RUN_AI_MEDIA_INTEGRATION") != "1" {
		t.Skip("AI media PostgreSQL integration requires RUN_AI_MEDIA_INTEGRATION=1")
	}
	_ = godotenv.Load("../../../../.env")
	db, ctx := testschema.Open(t, os.Getenv("POSTGRES_DSN"), "test_ai_media")
	db = db.Session(&gorm.Session{Logger: logger.Default.LogMode(logger.Silent)})
	ddl := `
CREATE TABLE ai_run(id bigint PRIMARY KEY,transfer_status smallint NOT NULL DEFAULT 0,updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE ai_media_task(id bigint PRIMARY KEY);
CREATE TABLE storage_file(id bigint PRIMARY KEY);
CREATE TABLE system_scheduler_job(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,schedule_id bigint,task_type text NOT NULL,payload jsonb NOT NULL,trigger_source text NOT NULL,source_key text UNIQUE,scheduled_at timestamptz NOT NULL,available_at timestamptz NOT NULL,status smallint NOT NULL,attempt_count integer NOT NULL,max_attempts integer NOT NULL,retry_of_job_id bigint,triggered_by bigint,error_class text,last_error text,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL);
CREATE TABLE ai_media_file(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id bigint NOT NULL REFERENCES ai_run(id),media_task_id bigint NULL REFERENCES ai_media_task(id),role smallint NOT NULL,ordinal integer NOT NULL,storage_file_id bigint NULL REFERENCES storage_file(id),import_request_key uuid NULL,source_kind smallint NOT NULL,source_ciphertext text NULL,encryption_key_id varchar(64) NULL,source_recoverable smallint NOT NULL,source_expires_at timestamptz NULL,transfer_deadline_at timestamptz NULL,mime_type varchar(100) NULL,size_bytes bigint NULL,metadata jsonb NOT NULL,transfer_status smallint NOT NULL,transfer_attempts integer NOT NULL DEFAULT 0,next_transfer_at timestamptz NULL,error_code varchar(64) NULL,error_message varchar(1000) NULL,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL,
 UNIQUE(run_id,role,ordinal),UNIQUE(import_request_key)
);`
	if err := db.WithContext(ctx).Exec(ddl).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Exec(`INSERT INTO ai_run(id) VALUES(1); INSERT INTO storage_file(id) VALUES(7)`).Error; err != nil {
		t.Fatal(err)
	}
	return NewRepository(db, scheduler.NewRepository(db)), db, ctx
}

func TestCreateGeneratedFileAcceptsSynchronousOutputAndReplaysIdempotently(t *testing.T) {
	r, db, ctx := mediaRepositoryDB(t)
	now := time.Now().UTC()
	key := "123e4567-e89b-12d3-a456-426614174000"
	f := &File{RunID: 1, Role: FileRoleGenerated, Ordinal: 0, StorageFileID: ptrInt64(7), ImportRequestKey: &key, SourceKind: SourceStream, SourceRecoverable: 0, TransferDeadline: ptrTime(now.Add(time.Minute)), MIMEType: ptrString("image/png"), SizeBytes: ptrInt64(8), Metadata: []byte(`{}`), TransferStatus: TransferReady, CreatedAt: now, UpdatedAt: now}
	if err := r.CreateGeneratedFile(ctx, f); err != nil {
		t.Fatal(err)
	}
	firstID := f.ID
	if firstID < 1 {
		t.Fatal("file id not assigned")
	}
	replay := *f
	replay.ID = 0
	if err := r.CreateGeneratedFile(ctx, &replay); err != nil {
		t.Fatal(err)
	}
	if replay.ID != firstID {
		t.Fatalf("replay id=%d want=%d", replay.ID, firstID)
	}
	var count int64
	if err := db.WithContext(ctx).Table("ai_media_file").Count(&count).Error; err != nil || count != 1 {
		t.Fatalf("count=%d err=%v", count, err)
	}
}

func ptrInt64(v int64) *int64        { return &v }
func ptrTime(v time.Time) *time.Time { return &v }
func ptrString(v string) *string     { return &v }

func TestImportRetryPersistsNextJobAndFrozenDeadline(t *testing.T) {
	r, db, ctx := mediaRepositoryDB(t)
	now := time.Now().UTC()
	deadline := now.Add(time.Minute)
	key := "123e4567-e89b-12d3-a456-426614174001"
	f := &File{RunID: 1, Role: FileRoleGenerated, Ordinal: 0, ImportRequestKey: &key, SourceKind: SourceURL, SourceRecoverable: 1, SourceCiphertext: ptrString("sealed"), EncryptionKeyID: ptrString("key"), TransferDeadline: &deadline, Metadata: []byte(`{}`), TransferStatus: TransferQueued, CreatedAt: now, UpdatedAt: now}
	if err := r.CreateGeneratedFile(ctx, f); err != nil {
		t.Fatal(err)
	}
	claimed, found, err := r.ClaimImport(ctx, now)
	if err != nil || !found {
		t.Fatalf("found=%v err=%v", found, err)
	}
	s := &Service{repository: r}
	if err := s.retryImport(ctx, claimed, "TEMP", "private", now); err != nil {
		t.Fatal(err)
	}
	var saved File
	if err := db.WithContext(ctx).First(&saved, f.ID).Error; err != nil {
		t.Fatal(err)
	}
	if saved.NextTransferAt == nil || !saved.NextTransferAt.Equal(now.Add(5*time.Second)) || !saved.TransferDeadline.Equal(deadline) {
		t.Fatalf("saved=%+v", saved)
	}
	var jobs []scheduler.Job
	if err := db.WithContext(ctx).Order("id").Find(&jobs).Error; err != nil {
		t.Fatal(err)
	}
	if len(jobs) != 2 || !jobs[1].AvailableAt.Equal(*saved.NextTransferAt) {
		t.Fatalf("jobs=%+v", jobs)
	}
}
func TestClaimImportRecoversAbandonedClaimAndStopsAfterThree(t *testing.T) {
	r, db, ctx := mediaRepositoryDB(t)
	now := time.Now().UTC()
	deadline := now.Add(time.Minute)
	key := "123e4567-e89b-12d3-a456-426614174002"
	f := &File{RunID: 1, Role: FileRoleGenerated, Ordinal: 0, ImportRequestKey: &key, SourceKind: SourceURL, SourceRecoverable: 1, SourceCiphertext: ptrString("sealed"), EncryptionKeyID: ptrString("key"), TransferDeadline: &deadline, Metadata: []byte(`{}`), TransferStatus: Transfering, TransferAttempts: 1, NextTransferAt: ptrTime(now.Add(-time.Second)), CreatedAt: now.Add(-time.Minute), UpdatedAt: now.Add(-time.Minute)}
	if err := db.WithContext(ctx).Create(f).Error; err != nil {
		t.Fatal(err)
	}
	got, found, err := r.ClaimImport(ctx, now)
	if err != nil || !found || got.TransferAttempts != 2 {
		t.Fatalf("got=%+v found=%v err=%v", got, found, err)
	}
	if err := db.WithContext(ctx).Model(f).Updates(map[string]any{"transfer_attempts": 3, "next_transfer_at": now.Add(-time.Second)}).Error; err != nil {
		t.Fatal(err)
	}
	got, found, err = r.ClaimImport(ctx, now)
	if err != nil || !found || got.TransferStatus != TransferFailed {
		t.Fatalf("got=%+v found=%v err=%v", got, found, err)
	}
}
