func aiMenuFixture(t *testing.T) (*gorm.DB, context.Context, string) {
	t.Helper()
	if testing.Short() {
		t.Skip("PostgreSQL integration")
	}
	if err := godotenv.Load("../../../.env"); err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	db, ctx := testschema.Open(t, os.Getenv("POSTGRES_DSN"), "test_ai_menu")
	db = db.Session(&gorm.Session{Logger: logger.Default.LogMode(logger.Silent)})
	if err := db.WithContext(ctx).Exec(`
CREATE TABLE permission_auth_platform(id bigint PRIMARY KEY,code varchar(64) NOT NULL,status smallint NOT NULL,menu_version bigint NOT NULL,deleted_at timestamptz,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now());
INSERT INTO permission_auth_platform(id,code,status,menu_version) VALUES(1,'admin',1,24),(2,'canvas',1,5);
CREATE TABLE permission_menu(LIKE public.permission_menu INCLUDING ALL);
ALTER TABLE permission_menu ALTER COLUMN id DROP DEFAULT;
ALTER TABLE permission_menu ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE permission_menu ADD FOREIGN KEY(platform_id) REFERENCES permission_auth_platform(id),ADD FOREIGN KEY(parent_id,platform_id) REFERENCES permission_menu(id,platform_id);
`).Error; err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile("../../../../docs/database/2026-10-28-ai-menu.sql")
	if err != nil {
		t.Fatal(err)
	}
	return db, ctx, string(raw)
}

func TestAIMenuSeedsExactlyFortyFiveNodesWithoutCanvasAndReplays(t *testing.T) {
	db, ctx, sql := aiMenuFixture(t)
	apply := func() error {
		return db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error })
	}
	if err := apply(); err != nil {
		t.Fatal(err)
	}
	var rows []struct {
		MenuType string
		Count    int64
	}
	if err := db.WithContext(ctx).Raw(`SELECT menu_type,count(*) FROM permission_menu WHERE platform_id=1 GROUP BY menu_type ORDER BY menu_type`).Scan(&rows).Error; err != nil {
		t.Fatal(err)
	}
	if len(rows) != 3 || rows[0].MenuType != "action" || rows[0].Count != 38 || rows[1].MenuType != "directory" || rows[1].Count != 1 || rows[2].MenuType != "page" || rows[2].Count != 6 {
		t.Fatalf("bad menu shape: %+v", rows)
	}
	var versions []int64
	if err := db.WithContext(ctx).Raw(`SELECT menu_version FROM permission_auth_platform ORDER BY id`).Scan(&versions).Error; err != nil || len(versions) != 2 || versions[0] != 25 || versions[1] != 5 {
		t.Fatalf("versions=%v err=%v", versions, err)
	}
	var canvasCount int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM permission_menu WHERE platform_id=2`).Scan(&canvasCount).Error; err != nil || canvasCount != 0 {
		t.Fatalf("Canvas mutated: %d %v", canvasCount, err)
	}
	var before, after string
	snapshot := `SELECT jsonb_build_object('menus',(SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM permission_menu m),'platforms',(SELECT jsonb_agg(to_jsonb(p) ORDER BY id) FROM permission_auth_platform p))::text`
	if err := db.WithContext(ctx).Raw(snapshot).Scan(&before).Error; err != nil {
		t.Fatal(err)
	}
	if err := apply(); err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Raw(snapshot).Scan(&after).Error; err != nil || before != after {
		t.Fatalf("replay changed facts: %v", err)
	}
}

func TestAIMenuRejectsPartialSeedAndWrongParentAtomically(t *testing.T) {
	for _, partial := range []bool{true, false} {
		t.Run(map[bool]string{true: "partial", false: "wrong parent"}[partial], func(t *testing.T) {
			db, ctx, sql := aiMenuFixture(t)
			apply := func() error {
				return db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error })
			}
			if partial {
				if err := db.WithContext(ctx).Exec(`INSERT INTO permission_menu(platform_id,menu_type,name,code,i18n_key) VALUES(1,'directory','AI','ai','navigation.ai')`).Error; err != nil {
					t.Fatal(err)
				}
			} else {
				if err := apply(); err != nil {
					t.Fatal(err)
				}
				if err := db.WithContext(ctx).Exec(`UPDATE permission_menu SET parent_id=(SELECT id FROM permission_menu WHERE code='ai:tool:view') WHERE code='ai:provider:list'`).Error; err != nil {
					t.Fatal(err)
				}
			}
			var before, after string
			snapshot := `SELECT jsonb_build_object('menus',(SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM permission_menu m),'platforms',(SELECT jsonb_agg(to_jsonb(p) ORDER BY id) FROM permission_auth_platform p))::text`
			if err := db.WithContext(ctx).Raw(snapshot).Scan(&before).Error; err != nil {
				t.Fatal(err)
			}
			if err := apply(); err == nil {
				t.Fatal("corrupt menu accepted")
			}
			if err := db.WithContext(ctx).Raw(snapshot).Scan(&after).Error; err != nil || before != after {
				t.Fatalf("failed seed changed facts: %v", err)
			}
		})
	}
}
