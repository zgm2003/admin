func TestCreateEnabledAgentWithInitialProviderModelIsAtomic(t *testing.T) {
	db, ctx := agentDB(t)
	seedAgentRows(t, db, ctx)
	svc := NewService(NewRepository(db), priceValidator{db}, directRuntime{db})
	model := int64(1)
	in := CreateInput{Code: "created", Name: "Created", Capabilities: []string{"text"}, SystemPrompt: "created prompt", MultiplierPPM: 2000000, GenerationParams: json.RawMessage(`{}`), Status: 1, ActorID: 1, ActiveProviderModelID: &model, Bindings: []BindingInput{{ProviderModelID: 1, Status: 1, TextProtocol: 1, Parameters: json.RawMessage(`{}`)}}}
	id, e := svc.Create(ctx, in)
	if e != nil {
		t.Fatal(e)
	}
	var m Model
	if e := db.WithContext(ctx).First(&m, id).Error; e != nil {
		t.Fatal(e)
	}
	if m.Status != 1 || m.ActiveBindingID == nil {
		t.Fatal("initial binding not activated")
	}
	bad := int64(999)
	in.Code = "rollback"
	in.ActiveProviderModelID = &bad
	if _, e := svc.Create(ctx, in); e == nil {
		t.Fatal("missing initial provider accepted")
	}
	var n int64
	db.WithContext(ctx).Model(&Model{}).Where("code='rollback'").Count(&n)
	if n != 0 {
		t.Fatal("failed create left partial agent")
	}
}
func TestOrdinaryUpdatePreservesCurrentAndRollsBackRemoval(t *testing.T) {
	db, ctx := agentDB(t)
	seedAgentRows(t, db, ctx)
	svc := NewService(NewRepository(db), priceValidator{db}, directRuntime{db})
	in := UpdateInput{Name: "Updated", Capabilities: []string{"text"}, SystemPrompt: "new prompt", MultiplierPPM: 3000000, GenerationParams: json.RawMessage(`{}`), ActorID: 1, Bindings: []BindingInput{{ProviderModelID: 1, Status: 1, TextProtocol: 1, Parameters: json.RawMessage(`{}`)}, {ProviderModelID: 2, Status: 1, TextProtocol: 1, Parameters: json.RawMessage(`{}`)}}}
	if e := svc.Update(ctx, 1, in); e != nil {
		t.Fatal(e)
	}
	m, e := svc.Find(ctx, 1)
	if e != nil || m.ActiveBindingID == nil || *m.ActiveBindingID != 1 || m.Status != 1 {
		t.Fatalf("current changed %+v %v", m, e)
	}
	before, e := configcache.NewRepository(db).Current(ctx, configcache.Scope{Namespace: "ai.runtime", ScopeKey: "global"})
	if e != nil {
		t.Fatal(e)
	}
	in.Name = "Must rollback"
	in.Bindings = in.Bindings[1:]
	if e := svc.Update(ctx, 1, in); e == nil {
		t.Fatal("active binding removal accepted")
	}
	m, e = svc.Find(ctx, 1)
	if e != nil || m.Name != "Updated" {
		t.Fatalf("partial update %+v %v", m, e)
	}
	after, _ := configcache.NewRepository(db).Current(ctx, configcache.Scope{Namespace: "ai.runtime", ScopeKey: "global"})
	if after != before {
		t.Fatal("rolled-back update advanced generation")
	}
	if e := svc.UpdateStatus(ctx, 1, 0, 1); e != nil {
		t.Fatal(e)
	}
	if e := svc.Update(ctx, 1, in); e != nil {
		t.Fatal(e)
	}
	if e := svc.UpdateStatus(ctx, 1, 1, 1); e == nil {
		t.Fatal("reenabled with disabled current binding")
	}
}
