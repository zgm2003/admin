func TestSwitchBindingLocksAgentAndRejectsDisabledOrUnpriced(t *testing.T) {
	db, ctx := agentDB(t)
	seedAgentRows(t, db, ctx)
	repo := NewService(NewRepository(db), priceValidator{db}, directRuntime{db})
	if err := repo.SwitchBinding(ctx, 1, 2); err == nil {
		t.Fatal("unpriced binding accepted")
	}
	if err := db.WithContext(ctx).Exec(`INSERT INTO ai_provider_model_price_version(id,provider_model_id,version,status,currency,source_currency,source_digest,snapshot_digest,source_payload,synced_at,created_by) VALUES(2,2,1,0,'CNY','USD',repeat('d',64),repeat('e',64),'{}',now(),1);INSERT INTO ai_provider_model_price_rate(price_version_id,operation,usage_key,selector,selector_hash,unit,unit_quantity,source_unit_price,billing_unit_price_units) VALUES(2,'text.generate','x','{}',repeat('f',64),'token',1000000,1,1);UPDATE ai_provider_model_price_version SET status=1,effective_at=now(),published_at=now(),published_by=1 WHERE id=2;`).Error; err != nil {
		t.Fatal(err)
	}
	if err := repo.SwitchBinding(ctx, 1, 2); err != nil {
		t.Fatal(err)
	}
	var got int64
	if err := db.WithContext(ctx).Raw(`SELECT active_binding_id FROM ai_agent WHERE id=1`).Scan(&got).Error; err != nil || got != 2 {
		t.Fatalf("current=%d err=%v", got, err)
	}
}

type priceValidator struct{ db *gorm.DB }

func (p priceValidator) ValidateBinding(ctx context.Context, id int64, _ int16, _ []string) error {
	var n int64
	e := p.db.WithContext(ctx).Raw(`SELECT count(*) FROM ai_provider_model_price_version WHERE provider_model_id=? AND status=1 AND effective_at<=now()`, id).Scan(&n).Error
	if e != nil {
		return e
	}
	if n == 0 {
		return fmt.Errorf("missing price")
	}
	return nil
}

type directRuntime struct{ db *gorm.DB }

func (r directRuntime) Mutate(ctx context.Context, fn func(context.Context, int64) (configcache.MutationResult, error)) error {
	gen, e := configcache.NewRepository(r.db).Current(ctx, configcache.Scope{Namespace: "ai.runtime", ScopeKey: "global"})
	if e != nil {
		return e
	}
	_, e = fn(ctx, gen)
	return e
}

