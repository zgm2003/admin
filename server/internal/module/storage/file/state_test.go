type memoryCOS struct {
	mu                       sync.Mutex
	objects                  map[string]storagecos.ObjectInfo
	data                     []byte
	copyStarted, copyRelease chan struct{}
	deleteErrors             map[string]error
}

func (m *memoryCOS) HeadObject(_ context.Context, _ storagecos.Credentials, key string) (storagecos.ObjectInfo, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	v, ok := m.objects[key]
	if !ok {
		return v, storagecos.ErrObjectNotFound
	}
	return v, nil
}
func (m *memoryCOS) CopyObject(ctx context.Context, _ storagecos.Credentials, _ storagecos.Credentials, r storagecos.CopyRequest) (storagecos.ObjectInfo, error) {
	if m.copyStarted != nil {
		select {
		case m.copyStarted <- struct{}{}:
		default:
		}
		select {
		case <-m.copyRelease:
		case <-ctx.Done():
			return storagecos.ObjectInfo{}, ctx.Err()
		}
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	source, ok := m.objects[r.SourceKey]
	if !ok {
		return source, storagecos.ErrObjectNotFound
	}
	if source.ETag != r.SourceETag {
		return source, storagecos.ErrObjectChanged
	}
	source.Key = r.TargetKey
	m.objects[r.TargetKey] = source
	return source, nil
}
func (m *memoryCOS) DeleteObject(_ context.Context, _ storagecos.Credentials, key string) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if e := m.deleteErrors[key]; e != nil {
		return e
	}
	delete(m.objects, key)
	return nil
}
func (m *memoryCOS) ReadObject(_ context.Context, _ storagecos.Credentials, key, etag string, limit int64) ([]byte, error) {
	return m.data, nil
}
