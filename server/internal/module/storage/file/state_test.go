func TestCopyLeaseBlocksExpiredPendingCleanup(t *testing.T) {
	s, db, ctx, client, id := fileFixture(t)
	f := upload(t, s, ctx, client, id, "in-flight")
	client.copyStarted = make(chan struct{}, 1)
	client.copyRelease = make(chan struct{})
	done := make(chan error, 1)
	go func() { _, e := s.Complete(ctx, id, f); done <- e }()
	select {
	case <-client.copyStarted:
	case e := <-done:
		t.Fatalf("complete before copy: %v", e)
	case <-time.After(5 * time.Second):
		t.Fatal("copy did not start")
	}
	_ = db.Model(&Model{}).Where("id=?", f).Update("credential_expires_at", time.Now().Add(-time.Hour)).Error
	if e := s.Cleanup(ctx, f); !errors.Is(e, ErrConflict) {
		t.Fatalf("active copy cleaned: %v", e)
	}
	close(client.copyRelease)
	if e := <-done; e != nil {
		t.Fatal(e)
	}
	m := mustFind(t, s, ctx, id, f)
	if m.Status != StatusReady {
		t.Fatal("copy lost")
	}
}
