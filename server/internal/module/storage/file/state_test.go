func TestCompletionRecoveryAndIsolation(t *testing.T) {
	s, db, ctx, client, id := fileFixture(t)
	f := upload(t, s, ctx, client, id, "final")
	if _, e := s.Complete(ctx, auth.Identity{UserID: 2, PlatformID: 1}, f); e == nil {
		t.Fatal("cross-owner complete")
	}
	if e := db.Exec(`CREATE FUNCTION fail_finish() RETURNS trigger AS $$BEGIN IF NEW.status=2 THEN RAISE EXCEPTION 'fixture failure';END IF;RETURN NEW;END;$$ LANGUAGE plpgsql;CREATE TRIGGER fail_finish BEFORE UPDATE ON storage_file FOR EACH ROW EXECUTE FUNCTION fail_finish();`).Error; e != nil {
		t.Fatal(e)
	}
	if _, e := s.Complete(ctx, id, f); e == nil {
		t.Fatal("database failure hidden")
	}
	if _, e := client.HeadObject(ctx, storagecos.Credentials{}, "final"); e != nil {
		t.Fatal("copy not created")
	}
	_ = db.Exec("DROP TRIGGER fail_finish ON storage_file").Error
	client.mu.Lock()
	client.objects[".staging/final-temp"] = storagecos.ObjectInfo{Key: "final-temp", Size: int64(len(client.data)), MIME: "image/png", ETag: `"later"`}
	client.mu.Unlock()
	result, e := s.Complete(ctx, id, f)
	if e != nil || result.ObjectKey != "final" {
		t.Fatalf("recovery %+v %v", result, e)
	}
	head, _ := client.HeadObject(ctx, storagecos.Credentials{}, "final")
	if head.ETag != `"first"` {
		t.Fatal("final overwritten")
	}
	if _, e = s.Get(ctx, auth.Identity{UserID: 1, PlatformID: 2}, f); e == nil {
		t.Fatal("platform bypass")
	}
	if e = s.AuthorizeObject(ctx, auth.Identity{UserID: 2, PlatformID: 1}, "final"); e == nil {
		t.Fatal("object-url owner bypass")
	}
	if e = s.AuthorizeObject(ctx, id, ".staging/final-temp"); e == nil {
		t.Fatal("temporary read bypass")
	}
}
func TestConcurrentCompletionAndDeleteIntentRollback(t *testing.T) {
	s, db, ctx, client, id := fileFixture(t)
	f := upload(t, s, ctx, client, id, "parallel")
	s2 := NewService(s.repository, s.keys, client, s.runtime, s.rules)
	var wg sync.WaitGroup
	errs := make(chan error, 8)
	for n := 0; n < 8; n++ {
		wg.Add(1)
		go func() { defer wg.Done(); _, e := s2.Complete(ctx, id, f); errs <- e }()
	}
	wg.Wait()
	close(errs)
	for e := range errs {
		if e != nil {
			t.Fatal(e)
		}
	}
	page, e := s.List(ctx, id, ListQuery{Page: 1, PageSize: 20})
	if e != nil || page.Total != 1 {
		t.Fatalf("list %+v %v", page, e)
	}
	s.repository.scheduler = nil
	if e = s.Delete(ctx, id, f); e == nil {
		t.Fatal("missing job writer hidden")
	}
	m, _ := s.repository.Find(ctx, id, f)
	if m.Status != StatusReady {
		t.Fatal("delete did not rollback")
	}
	s.repository.scheduler = scheduler.NewRepository(db)
	if e = s.Delete(ctx, id, f); e != nil {
		t.Fatal(e)
	}
	page, _ = s.List(ctx, id, ListQuery{Page: 1, PageSize: 20})
	if page.Total != 0 {
		t.Fatal("delete still visible")
	}
	if e = s.Cleanup(ctx, f); !errors.Is(e, ErrConflict) {
		t.Fatalf("live PUT cleared: %v", e)
	}
	_ = db.Model(&Model{}).Where("id=?", f).Updates(map[string]any{"credential_expires_at": time.Now().Add(-time.Hour), "operation_lease_until": time.Now().Add(-time.Hour)}).Error
	if e = s.Cleanup(ctx, f); e != nil {
		t.Fatal(e)
	}
	if e = s.Cleanup(ctx, f); e != nil {
		t.Fatal("repeat cleanup", e)
	}
	if _, e = client.HeadObject(ctx, storagecos.Credentials{}, "parallel"); !errors.Is(e, storagecos.ErrObjectNotFound) {
		t.Fatal("final retained")
	}
}
