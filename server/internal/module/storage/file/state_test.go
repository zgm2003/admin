func encrypted(t *testing.T, key []byte, value string) string {
	t.Helper()
	block, e := aes.NewCipher(key)
	if e != nil {
		t.Fatal(e)
	}
	g, e := cipher.NewGCM(block)
	if e != nil {
		t.Fatal(e)
	}
	nonce := make([]byte, g.NonceSize())
	return "v1:" + base64.RawStdEncoding.EncodeToString(g.Seal(nonce, nonce, []byte(value), nil))
}
