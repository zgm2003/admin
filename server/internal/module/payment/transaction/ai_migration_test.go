func aiLedgerFixture(t *testing.T) (*gorm.DB, context.Context) {
	t.Helper()
	if testing.Short() {
		t.Skip("PostgreSQL integration")
	}
	if err := godotenv.Load("../../../../.env"); err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	dsn := os.Getenv("POSTGRES_DSN")
	if dsn == "" {
		t.Fatal("POSTGRES_DSN required for AI ledger migration validation")
	}
	db, ctx := testschema.Open(t, dsn, "test_ai_ledger")
	db = db.Session(&gorm.Session{Logger: logger.Default.LogMode(logger.Silent)})
	if err := db.WithContext(ctx).Exec(legacyLedgerFixture).Error; err != nil {
		t.Fatal(err)
	}
	return db, ctx
}

func aiLedgerMigration(t *testing.T) string {
	t.Helper()
	raw, err := os.ReadFile("../../../../../docs/database/2026-10-28-ai-payment.sql")
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

func applyAILedger(db *gorm.DB, ctx context.Context, script string) error {
	err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(script).Error })
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) {
		return fmt.Errorf("AI ledger SQL at %d, internal %d, context %s: %w", pgErr.Position, pgErr.InternalPosition, pgErr.Where, err)
	}
	return err
}

func ledgerSchemaDigest(t *testing.T, db *gorm.DB, ctx context.Context) string {
	t.Helper()
	var digest string
	err := db.WithContext(ctx).Raw(`SELECT md5(string_agg(definition,E'\n' ORDER BY definition)) FROM (
SELECT 'column:'||attname||':'||format_type(atttypid,atttypmod)||':'||attnotnull::text AS definition FROM pg_attribute WHERE attrelid='payment_transaction'::regclass AND attnum>0 AND NOT attisdropped
UNION ALL SELECT 'constraint:'||conname||':'||pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid='payment_transaction'::regclass
UNION ALL SELECT 'index:'||indexdef FROM pg_indexes WHERE schemaname=current_schema() AND tablename='payment_transaction'
UNION ALL SELECT 'trigger:'||pg_get_triggerdef(oid)||':'||tgenabled::text FROM pg_trigger WHERE tgrelid='payment_transaction'::regclass AND NOT tgisinternal
) facts`).Scan(&digest).Error
	if err != nil {
		t.Fatal(err)
	}
	return digest
}

func TestAILedgerMigrationBackfillsAndReplaysWithoutChangingFacts(t *testing.T) {
	db, ctx := aiLedgerFixture(t)
	script := aiLedgerMigration(t)
	var original string
	query := `SELECT md5(string_agg((to_jsonb(t)-'direction'-'balance_before_units'-'ai_usage_charge_id')::text,E'\n' ORDER BY id)) FROM payment_transaction t`
	if err := db.WithContext(ctx).Raw(query).Scan(&original).Error; err != nil {
		t.Fatal(err)
	}
	if err := applyAILedger(db, ctx, script); err != nil {
		t.Fatal(err)
	}
	var rows []struct {
		Direction int16
		Before    int64 `gorm:"column:balance_before_units"`
	}
	if err := db.WithContext(ctx).Raw(`SELECT direction,balance_before_units FROM payment_transaction ORDER BY id`).Scan(&rows).Error; err != nil {
		t.Fatal(err)
	}
	if len(rows) != 2 || rows[0].Direction != 1 || rows[0].Before != -10 || rows[1].Direction != 1 || rows[1].Before != -9223372036854775808 {
		t.Fatalf("invalid legacy backfill: %+v", rows)
	}
	digest := ledgerSchemaDigest(t, db, ctx)
	if err := applyAILedger(db, ctx, script); err != nil {
		t.Fatal(err)
	}
	if got := ledgerSchemaDigest(t, db, ctx); got != digest {
		t.Fatal("replay changed ledger structure")
	}
	var after string
	if err := db.WithContext(ctx).Raw(query).Scan(&after).Error; err != nil || after != original {
		t.Fatalf("legacy facts changed: %v", err)
	}
}

