func TestAILedgerMigrationRejectsCorruptLegacyAndRollsBack(t *testing.T) {
	for _, corruption := range []struct{ name, sql string }{
		{"overflow", `ALTER TABLE payment_transaction DROP CONSTRAINT ck_payment_transaction_balance; INSERT INTO payment_transaction(transaction_no,user_id,platform_id,amount_units,balance_after_units,order_id) VALUES('PT-corrupt',1,1,1,-9223372036854775808,2)`},
		{"two sources", `ALTER TABLE payment_transaction DROP CONSTRAINT ck_payment_transaction_source_xor; INSERT INTO payment_transaction(transaction_no,user_id,platform_id,amount_units,balance_after_units,order_id,redeem_code_id) VALUES('PT-corrupt',1,1,1,0,2,2)`},
		{"guard missing", `DROP TRIGGER payment_transaction_no_delete ON payment_transaction`},
		{"guard disabled", `ALTER TABLE payment_transaction DISABLE TRIGGER payment_transaction_immutable`},
		{"guard body replaced", `CREATE OR REPLACE FUNCTION payment_transaction_immutable_guard() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END$$;`},
		{"column-specific guard", `DROP TRIGGER payment_transaction_immutable ON payment_transaction; CREATE TRIGGER payment_transaction_immutable BEFORE UPDATE OF amount_units ON payment_transaction FOR EACH STATEMENT EXECUTE FUNCTION payment_transaction_immutable_guard()`},
		{"same-name weak legacy check", `ALTER TABLE payment_transaction DROP CONSTRAINT ck_payment_transaction_source_xor; ALTER TABLE payment_transaction ADD CONSTRAINT ck_payment_transaction_source_xor CHECK(true)`},
		{"partial columns", `ALTER TABLE payment_transaction ADD COLUMN direction smallint`},
		{"conflicting constraint", `ALTER TABLE payment_transaction ADD CONSTRAINT ck_payment_transaction_direction CHECK (amount_units<1000)`},
		{"missing core", `DROP TABLE ai_usage_charge`},
	} {
		t.Run(corruption.name, func(t *testing.T) {
			db, ctx := aiLedgerFixture(t)
			if err := db.WithContext(ctx).Exec(corruption.sql).Error; err != nil {
				t.Fatal(err)
			}
			before := ledgerSchemaDigest(t, db, ctx)
			if err := applyAILedger(db, ctx, aiLedgerMigration(t)); err == nil {
				t.Fatal("corrupt/partial ledger migration accepted")
			}
			if got := ledgerSchemaDigest(t, db, ctx); got != before {
				t.Fatal("failed migration did not roll back DDL/guards")
			}
		})
	}
}

func TestAILedgerMigrationRejectsDriftOnReplay(t *testing.T) {
	for _, drift := range []struct{ name, sql string }{
		{"wrong source check", `ALTER TABLE payment_transaction DROP CONSTRAINT ck_payment_transaction_ai_source_xor; ALTER TABLE payment_transaction ADD CONSTRAINT ck_payment_transaction_ai_source_xor CHECK (true)`},
		{"nonunique charge index", `DROP INDEX ux_payment_transaction_ai_usage_charge; CREATE INDEX ux_payment_transaction_ai_usage_charge ON payment_transaction(ai_usage_charge_id)`},
		{"nullable direction", `ALTER TABLE payment_transaction ALTER COLUMN direction DROP NOT NULL`},
		{"disabled guard", `ALTER TABLE payment_transaction DISABLE TRIGGER payment_transaction_immutable`},
		{"no-op update guard", `CREATE OR REPLACE FUNCTION payment_transaction_immutable_guard() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END$$;`},
		{"column-specific guard", `DROP TRIGGER payment_transaction_immutable ON payment_transaction; CREATE TRIGGER payment_transaction_immutable BEFORE UPDATE OF amount_units ON payment_transaction FOR EACH STATEMENT EXECUTE FUNCTION payment_transaction_immutable_guard()`},
		{"wrong AI foreign key", `ALTER TABLE payment_transaction DROP CONSTRAINT fk_payment_transaction_ai_usage_charge; ALTER TABLE payment_transaction ADD CONSTRAINT fk_payment_transaction_ai_usage_charge FOREIGN KEY(ai_usage_charge_id) REFERENCES payment_order(id) ON DELETE RESTRICT`},
		{"new unrelated column", `ALTER TABLE payment_transaction ADD COLUMN unrelated text`},
	} {
		t.Run(drift.name, func(t *testing.T) {
			db, ctx := aiLedgerFixture(t)
			script := aiLedgerMigration(t)
			if err := applyAILedger(db, ctx, script); err != nil {
				t.Fatal(err)
			}
			if err := db.WithContext(ctx).Exec(drift.sql).Error; err != nil {
				t.Fatal(err)
			}
			before := ledgerSchemaDigest(t, db, ctx)
			if err := applyAILedger(db, ctx, script); err == nil {
				t.Fatal("ledger drift silently accepted")
			}
			if got := ledgerSchemaDigest(t, db, ctx); got != before {
				t.Fatal("drift was silently repaired")
			}
		})
	}
}

func TestAILedgerMigrationRequiresExplicitTransaction(t *testing.T) {
	db, ctx := aiLedgerFixture(t)
	// psql without --single-transaction executes each block independently; the
	// migration must refuse that mode before changing or disabling any guard.
	script := aiLedgerMigration(t)
	first, _, ok := strings.Cut(script, ";")
	if !ok {
		t.Fatal("migration has no SQL statement")
	}
	before := ledgerSchemaDigest(t, db, ctx)
	if err := db.WithContext(ctx).Exec(first + ";").Error; err == nil {
		t.Fatal("autocommit migration accepted")
	}
	if got := ledgerSchemaDigest(t, db, ctx); got != before {
		t.Fatal("autocommit guard modified ledger")
	}
}

func TestAILedgerMigrationComposesWithFullAICore(t *testing.T) {
	db, ctx := aiLedgerFixture(t)
	if err := db.WithContext(ctx).Exec("DROP TABLE ai_usage_charge; CREATE TABLE user_account(id bigint PRIMARY KEY); CREATE TABLE storage_file(id bigint PRIMARY KEY); INSERT INTO user_account VALUES(1)").Error; err != nil {
		t.Fatal(err)
	}
	core, err := os.ReadFile("../../../../../docs/database/2026-10-28-ai-core.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err := applyAILedger(db, ctx, string(core)); err != nil {
		t.Fatal(err)
	}
	if err := applyAILedger(db, ctx, aiLedgerMigration(t)); err != nil {
		t.Fatal(err)
	}
	if err := applyAILedger(db, ctx, aiLedgerMigration(t)); err != nil {
		t.Fatal(err)
	}
	var count int64
	if err := db.WithContext(ctx).Raw("SELECT count(*) FROM pg_tables WHERE schemaname=current_schema() AND tablename LIKE 'ai\\_%' ESCAPE '\\'").Scan(&count).Error; err != nil || count != 21 {
		t.Fatalf("AI tables=%d err=%v", count, err)
	}
	var target string
	if err := db.WithContext(ctx).Raw("SELECT confrelid::regclass::text FROM pg_constraint WHERE conrelid='payment_transaction'::regclass AND conname='fk_payment_transaction_ai_usage_charge'").Scan(&target).Error; err != nil || target != "ai_usage_charge" {
		t.Fatalf("AI foreign key target=%q err=%v", target, err)
	}
}
