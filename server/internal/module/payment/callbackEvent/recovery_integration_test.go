func TestConcurrentRecoveryCommitsOneLedgerAndCompletesOriginalEvent(t *testing.T) {
	if testing.Short() {
		t.Skip("PostgreSQL integration")
	}
	if err := godotenv.Load("../../../../.env"); err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	cfg, err := settings.LoadWorker(os.LookupEnv)
	if err != nil {
		t.Fatal(err)
	}
	db, ctx := testschema.Open(t, cfg.PostgresDSN, "test_payment_callback_recovery")
	ddl := `
CREATE TABLE payment_config(id bigint PRIMARY KEY,app_id text NOT NULL,seller_id text NOT NULL,environment smallint NOT NULL);
CREATE TABLE payment_config_version(config_id bigint NOT NULL,version bigint NOT NULL,PRIMARY KEY(config_id,version));
CREATE TABLE payment_order(id bigint PRIMARY KEY,order_no text UNIQUE NOT NULL,user_id bigint NOT NULL,platform_id bigint NOT NULL,amount_cents bigint NOT NULL,config_id bigint NOT NULL,config_version bigint NOT NULL,status smallint NOT NULL,provider_trade_no text,paid_at timestamptz,credited_at timestamptz,next_check_at timestamptz,check_token uuid,check_lease_until timestamptz,updated_at timestamptz NOT NULL);
CREATE TABLE payment_wallet(user_id bigint PRIMARY KEY,balance_units bigint NOT NULL,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL);
CREATE TABLE payment_transaction(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,transaction_no text UNIQUE NOT NULL,user_id bigint NOT NULL,platform_id bigint NOT NULL,amount_units bigint NOT NULL,balance_after_units bigint NOT NULL,order_id bigint UNIQUE,redeem_code_id bigint,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL);
CREATE TABLE payment_callback_event(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,config_id bigint NOT NULL,config_version bigint NOT NULL,dedupe_key bytea NOT NULL,order_id bigint,payload jsonb NOT NULL,process_status smallint NOT NULL,error_code smallint,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL,UNIQUE(config_id,config_version,dedupe_key));
CREATE INDEX ix_callback_pending ON payment_callback_event(created_at,id) WHERE process_status=1;
INSERT INTO payment_config VALUES(3,'20260001','20880001',1);
INSERT INTO payment_config_version VALUES(3,4);
INSERT INTO payment_order(id,order_no,user_id,platform_id,amount_cents,config_id,config_version,status,updated_at) VALUES(11,'ORDER-1',7,1,300,3,4,1,CURRENT_TIMESTAMP);
INSERT INTO payment_wallet VALUES(7,-7000000000,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);`
	if err := db.WithContext(ctx).Exec(ddl).Error; err != nil {
		t.Fatal(err)
	}
	f := newEventFixture(t)
	service := NewService(NewRepository(db))
	service.SetRuntime(eventRuntimeStub{credentials: f.credentials}, payment.EnvironmentSandbox)
	service.SetConfirmer(&eventConfirmerStub{err: errors.New("injected settlement outage")})
	service.now = f.service.now
	if _, err := service.Receive(ctx, 3, 4, f.signed(t, nil)); err == nil {
		t.Fatal("initial settlement outage acknowledged")
	}
	var before Model
	if err := db.WithContext(ctx).First(&before).Error; err != nil {
		t.Fatal(err)
	}
	if before.ProcessStatus != ProcessPending {
		t.Fatalf("event not recoverable: %+v", before)
	}
	settlement := order.NewService(order.NewRepository(db))
	settlement.SetRuntime(nil, nil, payment.EnvironmentSandbox)
	service.SetConfirmer(settlement)
	now := service.now().Add(time.Minute)
	service.now = func() time.Time { return now }
	var wg sync.WaitGroup
	start := make(chan struct{})
	for range 2 {
		wg.Go(func() {
			<-start
			if err := service.RecoverPending(ctx); err != nil {
				t.Error(err)
			}
		})
	}
	close(start)
	wg.Wait()
	if err := service.RecoverPending(ctx); err != nil {
		t.Fatal(err)
	}
	var after Model
	if err := db.WithContext(ctx).First(&after, before.ID).Error; err != nil {
		t.Fatal(err)
	}
	var balance, ledgerCount int64
	if err := db.WithContext(ctx).Table("payment_wallet").Select("balance_units").Where("user_id=7").Scan(&balance).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Table("payment_transaction").Count(&ledgerCount).Error; err != nil {
		t.Fatal(err)
	}
	if after.ID != before.ID || after.ProcessStatus != ProcessSuccess || after.ErrorCode != nil || after.OrderID == nil || *after.OrderID != 11 || balance != -6700000000 || ledgerCount != 1 {
		t.Fatalf("recovery is not atomic/idempotent: event=%+v balance=%d ledger=%d", after, balance, ledgerCount)
	}
}
