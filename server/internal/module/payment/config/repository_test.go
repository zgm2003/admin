func TestPublishVersionRollsBackWhenCatalogWouldExceedEncodingCap(t *testing.T) {
	db, ctx := configDB(t)
	now := time.Now().UTC()
	models := []Model{}
	versions := []Version{}
	rows := []CatalogItem{}
	for n := int64(1); n <= 1100; n++ {
		app := fmt.Sprint(n)
		models = append(models, Model{ID: n, Name: "a", Provider: 1, Environment: 1, AppID: app, SellerID: "20880001", CurrentVersion: 9, CreatedAt: now, UpdatedAt: now})
		rows = append(rows, CatalogItem{ID: n, Name: "a", Provider: 1, Environment: 1, AppID: app, SellerID: "20880001", CurrentVersion: 9})
		versions = append(versions, Version{ConfigID: n, Version: 9, PrivateKeyCiphertext: "x", AppCertPEM: "a", AlipayCertPEM: "b", RootCertPEM: "c", NotifyURL: fmt.Sprintf("https://pay.example.test/api/v1/payment/callback/alipay/%d/9", n), PayMethods: PayMethods{1}, CreatedAt: now, UpdatedAt: now})
	}
	raw, _ := json.Marshal(snapshot{SchemaVersion: 1, Generation: int64(^uint64(0) >> 1), Variant: "catalog", Catalog: rows})
	remaining := MaxSnapshotBytes - len(raw)
	if remaining < 0 || remaining > 127*len(rows) {
		t.Fatalf("boundary fixture no longer fits: base %d remaining %d", len(raw), remaining)
	}
	for i := range rows {
		extra := min(127, remaining)
		rows[i].Name = strings.Repeat("a", extra+1)
		models[i].Name = rows[i].Name
		remaining -= extra
	}
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		if err := tx.CreateInBatches(models, 100).Error; err != nil {
			return err
		}
		return tx.CreateInBatches(versions, 100).Error
	}); err != nil {
		t.Fatal(err)
	}
	if err := checkCatalogSize(ctx, db); err != nil {
		t.Fatal("exactly full catalog should fit", err)
	}
	r := NewRepository(db)
	r.SetGenerations(cache.NewRepository(db))
	v := versions[0]
	v.PayMethods = PayMethods{2}
	if _, err := r.PublishVersion(ctx, 1, v, 2, now); err == nil {
		t.Fatal("9 to 10 version growth accepted an uncacheable catalog")
	}
	c, err := r.FindByID(ctx, 1)
	if err != nil || c.Config.CurrentVersion != 9 {
		t.Fatal("oversized version publication did not roll back", err)
	}
}

