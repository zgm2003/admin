func TestRuntimeCacheTwoInstancesLoadPostgresOnceAndKeepHotReadsInRedis(t *testing.T) {
	database, _ := openSMSGenerationDatabase(t)
	firstClient := openSMSRuntimeRedis(t)
	secondClient := openSMSRuntimeRedis(t)
	first := newSMSCacheTestStore(t, database, firstClient)
	second := secondSMSCacheTestStore(database, secondClient)
	var loads atomic.Int32
	loaderEntered := make(chan struct{})
	contenderWaited := make(chan struct{})
	releaseLoader := make(chan struct{})
	var signalContender sync.Once
	for _, cache := range []*RuntimeCache{first, second} {
		cache.wait = func(ctx context.Context, duration time.Duration) error {
			signalContender.Do(func() { close(contenderWaited) })
			return waitForSMSCache(ctx, duration)
		}
	}
	loader := func(ctx context.Context) (RuntimeFacts, error) {
		if loads.Add(1) == 1 {
			close(loaderEntered)
		}
		select {
		case <-ctx.Done():
			return RuntimeFacts{}, ctx.Err()
		case <-releaseLoader:
			return runtimeFactsForCacheTest(), nil
		}
	}
	errorsFound := make(chan error, 2)
	var wait sync.WaitGroup
	stores := []*RuntimeCache{first, second}
	for index := 0; index < 2; index++ {
		wait.Add(1)
		go func(worker int) {
			defer wait.Done()
			facts, err := stores[worker%len(stores)].Load(context.Background(), loader)
			if err != nil || !facts.Configured {
				errorsFound <- fmt.Errorf("load=%+v err=%w", facts, err)
			}
		}(index)
	}
	select {
	case <-loaderEntered:
	case <-time.After(2 * time.Second):
		t.Fatal("no cache fill leader entered the loader")
	}
	select {
	case <-contenderWaited:
	case <-time.After(2 * time.Second):
		t.Fatal("second cache instance did not contend for the fill lease")
	}
	close(releaseLoader)
	wait.Wait()
	close(errorsFound)
	for err := range errorsFound {
		t.Fatal(err)
	}
	if loads.Load() != 1 {
		t.Fatalf("source loads=%d, want 1", loads.Load())
	}
	for index := 0; index < 50; index++ {
		if _, err := stores[index%len(stores)].Load(context.Background(), loader); err != nil {
			t.Fatal(err)
		}
	}
	if loads.Load() != 1 {
		t.Fatalf("hot reads reached source: %d", loads.Load())
	}
}

func TestRuntimeAndReadinessUseOneGenerationWithSeparateVariants(t *testing.T) {
	database, ctx := openSMSGenerationDatabase(t)
	client := openSMSRuntimeRedis(t)
	cache := newSMSCacheTestStore(t, database, client)
	if _, err := cache.Load(ctx, func(context.Context) (RuntimeFacts, error) { return runtimeFactsForCacheTest(), nil }); err != nil {
		t.Fatal(err)
	}
	ready, err := cache.LoadReadiness(ctx, "login", func(context.Context) (VerifyCodeReadiness, error) {
		return VerifyCodeReadiness{Ready: true, TTLMinutes: 5}, nil
	})
	if err != nil || !ready.Ready || ready.TTLMinutes != 5 {
		t.Fatalf("readiness=%+v err=%v", ready, err)
	}
	runtimeKey, _ := cachegeneration.SnapshotKey(smsGenerationScope, 1, runtimeSnapshotVariant)
	readinessKey, _ := cachegeneration.SnapshotKey(smsGenerationScope, 1, "readiness:login")
	if _, found, err := client.GetString(ctx, runtimeKey); err != nil || !found {
		t.Fatalf("runtime snapshot found=%v err=%v", found, err)
	}
	if _, found, err := client.GetString(ctx, readinessKey); err != nil || !found {
		t.Fatalf("readiness snapshot found=%v err=%v", found, err)
	}
}

func TestRuntimeCacheCorruptSnapshotIsRebuilt(t *testing.T) {
	database, ctx := openSMSGenerationDatabase(t)
	client := openSMSRuntimeRedis(t)
	cache := newSMSCacheTestStore(t, database, client)
	key, _ := cachegeneration.SnapshotKey(smsGenerationScope, 1, runtimeSnapshotVariant)
	corrupt := `{"schemaVersion":1,"generation":1,"configured":true}`
	if err := client.SetString(ctx, key, corrupt, time.Minute); err != nil {
		t.Fatal(err)
	}
	var loads atomic.Int32
	facts, err := cache.Load(ctx, func(context.Context) (RuntimeFacts, error) {
		loads.Add(1)
		return runtimeFactsForCacheTest(), nil
	})
	if err != nil || !facts.Configured {
		t.Fatalf("rebuilt facts=%+v err=%v", facts, err)
	}
	if loads.Load() != 1 {
		t.Fatalf("source loads=%d, want 1", loads.Load())
	}
	raw, found, err := client.GetString(ctx, key)
	if err != nil || !found || raw == corrupt {
		t.Fatalf("rebuilt snapshot found=%v err=%v raw=%s", found, err, raw)
	}
}

