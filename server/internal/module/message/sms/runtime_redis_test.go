func smsCacheTestKeys(t *testing.T) []string {
	t.Helper()
	stateKey := cachegeneration.StateKey(smsGenerationScope)
	keys := []string{stateKey}
	variants := []string{runtimeSnapshotVariant}
	for _, scene := range []string{"login", "forget", "bind_phone", "change_password"} {
		variants = append(variants, "readiness:"+scene)
	}
	for generation := int64(1); generation <= 8; generation++ {
		for _, variant := range variants {
			snapshot, err := cachegeneration.SnapshotKey(smsGenerationScope, generation, variant)
			if err != nil {
				t.Fatal(err)
			}
			fill, err := cachegeneration.FillKey(smsGenerationScope, generation, variant)
			if err != nil {
				t.Fatal(err)
			}
			keys = append(keys, snapshot)
			keys = append(keys, cacheFillKeys(stateKey, fill)...)
		}
	}
	for _, variant := range variants {
		keys = append(keys, cacheFillKeys(stateKey, "repair:"+variant)...)
	}
	return keys
}

func cacheFillKeys(scope, target string) []string {
	scopeHash := sha256.Sum256([]byte(scope))
	targetHash := sha256.Sum256([]byte(target))
	prefix := fmt.Sprintf("cachefill:{%x}:", scopeHash[:8])
	return []string{fmt.Sprintf("%skey:%x", prefix, targetHash), prefix + "slots", prefix + "starts"}
}

