func TestScheduleStatusUsesSingleNumericField(t *testing.T) {
	for _, status := range []ScheduleStatus{ScheduleDisabled, ScheduleEnabled} {
		raw, err := json.Marshal(scheduleDTO(Schedule{Status: status}))
		if err != nil {
			t.Fatal(err)
		}
		var fields map[string]json.RawMessage
		if err := json.Unmarshal(raw, &fields); err != nil {
			t.Fatal(err)
		}
		if string(fields["status"]) != string([]byte{byte('0' + status)}) {
			t.Fatalf("status must be numeric 0/1: %s", raw)
		}
		if _, found := fields["isEnabled"]; found {
			t.Fatal("legacy field exposed")
		}
	}
	if ScheduleDisabled != 0 || ScheduleEnabled != 1 {
		t.Fatal("binary status values changed")
	}
}

func TestScheduleNumericStatusPersistsFiltersAndSurvivesEdit(t *testing.T) {
	db, ctx := openSchedulerRepositoryDatabase(t)
	if err := db.WithContext(ctx).Exec(`CREATE TABLE system_scheduler_schedule(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,description TEXT NOT NULL,
 task_type TEXT NOT NULL,cron_expression TEXT NOT NULL,timezone TEXT NOT NULL,params JSONB NOT NULL,
 status SMALLINT NOT NULL CHECK(status IN (0,1)),next_run_at TIMESTAMPTZ,builtin_key TEXT,
 created_by BIGINT,updated_by BIGINT,created_at TIMESTAMPTZ NOT NULL,updated_at TIMESTAMPTZ NOT NULL,deleted_at TIMESTAMPTZ)`).Error; err != nil {
		t.Fatal(err)
	}
	repo := NewRepository(db)
	now := time.Now().UTC()
	actor := int64(1)
	input := ScheduleInput{Name: "Example", TaskType: "example", CronExpression: "* * * * *", Timezone: "UTC", Params: json.RawMessage(`{}`), Status: ScheduleDisabled}
	disabled, err := repo.CreateSchedule(ctx, input, &actor, now)
	if err != nil {
		t.Fatal(err)
	}
	input.Status = ScheduleEnabled
	enabled, err := repo.CreateSchedule(ctx, input, &actor, now)
	if err != nil {
		t.Fatal(err)
	}
	if disabled.Status != 0 || disabled.NextRunAt != nil || enabled.Status != 1 || enabled.NextRunAt == nil {
		t.Fatal("incorrect binary state", disabled, enabled)
	}
	zero := ScheduleDisabled
	rows, err := repo.ListSchedules(ctx, ScheduleQuery{Status: &zero, Limit: 100})
	if err != nil || len(rows) != 1 || rows[0].ID != disabled.ID {
		t.Fatal("zero filter ignored", rows, err)
	}
	catalog, err := NewTaskCatalog(TaskDefinition{Type: "example", DisplayName: "Example", Queue: "default", Timeout: time.Minute, MaxAttempts: 1, AdminCreatable: true, DefaultParams: json.RawMessage(`{}`), ValidateParams: func(json.RawMessage) error { return nil }, Execute: func(context.Context, ExecutionContext) error { return nil }})
	if err != nil {
		t.Fatal(err)
	}
	service := NewService(repo, catalog)
	input.Status = ScheduleDisabled
	input.Name = "Edited"
	edited, err := service.UpdateSchedule(ctx, enabled.ID, input, actor)
	if err != nil || edited.Status != ScheduleEnabled {
		t.Fatal("editing changed status", edited, err)
	}
	if err := service.SetStatus(ctx, enabled.ID, ScheduleDisabled, actor); err != nil {
		t.Fatal(err)
	}
	row, err := repo.GetSchedule(ctx, enabled.ID)
	if err != nil || row.Status != 0 || row.NextRunAt != nil {
		t.Fatal("disable failed", row, err)
	}
}

func TestScheduleRequestRejectsInvalidStatus(t *testing.T) {
	for _, raw := range []string{`{"status":2}`, `{"status":-1}`, `{"status":true}`, `{"status":null}`, `{}`} {
		var req scheduleRequest
		if err := json.Unmarshal([]byte(raw), &req); err != nil {
			continue
		}
		req.Name = "Example"
		req.TaskType = "example"
		req.CronExpression = "* * * * *"
		req.Timezone = "UTC"
		if _, err := req.input(true); err == nil {
			t.Errorf("accepted invalid status: %s", raw)
		}
	}
	for _, raw := range []string{`{"status":0}`, `{"status":1}`} {
		var req scheduleRequest
		if err := json.Unmarshal([]byte(raw), &req); err != nil {
			t.Fatal(err)
		}
		req.Name = "Example"
		req.TaskType = "example"
		req.CronExpression = "* * * * *"
		req.Timezone = "UTC"
		if _, err := req.input(true); err != nil {
			t.Fatalf("valid status %s: %v", raw, err)
		}
	}
}

