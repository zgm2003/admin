func paymentSeedFixture(t *testing.T) (*gorm.DB, context.Context, string) {
	t.Helper()
	db, ctx := openSchedulerRepositoryDatabase(t)
	_, file, _, _ := runtime.Caller(0)
	root := filepath.Join(filepath.Dir(file), "../../../../..")
	raw, err := os.ReadFile(filepath.Join(root, "docs/database/current.sql"))
	if err != nil {
		t.Fatal(err)
	}
	ddl := regexp.MustCompile(`(?s)CREATE TABLE public\.system_scheduler_schedule \(.*?\n\);`).FindString(string(raw))
	if ddl == "" {
		t.Fatal("scheduler snapshot missing")
	}
	ddl = strings.ReplaceAll(ddl, "public.", "") + ` ALTER TABLE system_scheduler_schedule ADD PRIMARY KEY(id); ALTER TABLE system_scheduler_schedule ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;`
	if err := db.WithContext(ctx).Exec(ddl).Error; err != nil {
		t.Fatal(err)
	}
	for _, ddl := range regexp.MustCompile(`CREATE (?:UNIQUE )?INDEX [^;]+ ON public\.system_scheduler_schedule[^;]+;`).FindAllString(string(raw), -1) {
		if err := db.WithContext(ctx).Exec(strings.ReplaceAll(ddl, "public.", "")).Error; err != nil {
			t.Fatal(err)
		}
	}
	for _, table := range []string{"payment_config", "payment_config_version", "payment_recharge_package", "payment_order", "payment_wallet", "payment_transaction", "payment_callback_event"} {
		if err := db.WithContext(ctx).Exec("CREATE TABLE " + table + " (id bigint PRIMARY KEY)").Error; err != nil {
			t.Fatal(err)
		}
	}
	sql, err := os.ReadFile(filepath.Join(root, "docs/database/2026-10-16-payment-order-reconcile.sql"))
	if err != nil {
		t.Fatal(err)
	}
	return db, ctx, string(sql)
}

func TestPaymentSeedReplaysWithoutChangingScheduleOrUnrelatedFacts(t *testing.T) {
	db, ctx, sql := paymentSeedFixture(t)
	if err := db.WithContext(ctx).Exec(`INSERT INTO system_scheduler_schedule(name,task_type,cron_expression,timezone,params,status) VALUES('Existing schedule','other.task','0 * * * *','UTC','{}',0)`).Error; err != nil {
		t.Fatal(err)
	}
	apply := func() error {
		return db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error })
	}
	if err := apply(); err != nil {
		t.Fatal(err)
	}
	var before, after string
	digest := `SELECT md5(jsonb_agg(to_jsonb(s) ORDER BY id)::text) FROM system_scheduler_schedule s`
	if err := db.WithContext(ctx).Raw(digest).Scan(&before).Error; err != nil {
		t.Fatal(err)
	}
	if err := apply(); err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Raw(digest).Scan(&after).Error; err != nil {
		t.Fatal(err)
	}
	if before != after {
		t.Fatal("seed replay rewrote schedule facts")
	}
	var count int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_scheduler_schedule WHERE builtin_key='payment.order.reconcile' AND task_type='payment.order.reconcile' AND cron_expression='* * * * *' AND timezone='UTC' AND params='{}'::jsonb AND status=1 AND next_run_at IS NOT NULL AND deleted_at IS NULL`).Scan(&count).Error; err != nil || count != 1 {
		t.Fatalf("payment schedule count=%d err=%v", count, err)
	}
	// Administrator scheduling choices are durable, not migration defaults.
	if err := db.WithContext(ctx).Exec(`UPDATE system_scheduler_schedule SET cron_expression='*/2 * * * *',status=0 WHERE builtin_key='payment.order.reconcile'`).Error; err != nil {
		t.Fatal(err)
	}
	if err := apply(); err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM system_scheduler_schedule WHERE builtin_key='payment.order.reconcile' AND cron_expression='*/2 * * * *' AND status=0`).Scan(&count).Error; err != nil || count != 1 {
		t.Fatal("replay overwrote administrator configuration")
	}
}

func TestPaymentSeedRejectsConflictsAndMissingPaymentTablesAtomically(t *testing.T) {
	for _, setup := range []string{
		`DROP TABLE payment_order`,
		`INSERT INTO system_scheduler_schedule(name,task_type,cron_expression,builtin_key) VALUES('Conflicting payment task','other.task','* * * * *','payment.order.reconcile')`,
		`INSERT INTO system_scheduler_schedule(name,task_type,cron_expression,builtin_key,deleted_at) VALUES('Deleted payment task','payment.order.reconcile','* * * * *','payment.order.reconcile',CURRENT_TIMESTAMP)`,
		`INSERT INTO system_scheduler_schedule(name,task_type,cron_expression) VALUES('Duplicate payment task','payment.order.reconcile','* * * * *')`,
	} {
		t.Run(setup, func(t *testing.T) {
			db, ctx, sql := paymentSeedFixture(t)
			if err := db.WithContext(ctx).Exec(setup).Error; err != nil {
				t.Fatal(err)
			}
			var before, after string
			digest := `SELECT COALESCE(md5(jsonb_agg(to_jsonb(s) ORDER BY id)::text),'empty') FROM system_scheduler_schedule s`
			if err := db.WithContext(ctx).Raw(digest).Scan(&before).Error; err != nil {
				t.Fatal(err)
			}
			err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error })
			if err == nil {
				t.Fatal("incompatible seed accepted")
			}
			if err := db.WithContext(ctx).Raw(digest).Scan(&after).Error; err != nil {
				t.Fatal(err)
			}
			if before != after {
				t.Fatal("conflict left partial schedule changes")
			}
		})
	}
}
