func schedulerCleanupSQL(t *testing.T) string {
	t.Helper()
	_, file, _, _ := runtime.Caller(0)
	root := filepath.Join(filepath.Dir(file), "../../../../..")
	sql, err := os.ReadFile(filepath.Join(root, "docs/database/2026-10-12-scheduler-cleanup.sql"))
	if err != nil {
		t.Fatal(err)
	}
	return string(sql)
}

func oldSchedulerSchema(t *testing.T) (*gorm.DB, context.Context) {
	t.Helper()
	db, ctx := openSchedulerRepositoryDatabase(t)
	_, file, _, _ := runtime.Caller(0)
	snapshot, err := os.ReadFile(filepath.Join(filepath.Dir(file), "../../../../../docs/database/current.sql"))
	if err != nil {
		t.Fatal(err)
	}
	for _, table := range []string{"system_scheduler_schedule", "system_scheduler_job", "system_scheduler_run"} {
		ddl := regexp.MustCompile(`(?s)CREATE TABLE public\.` + table + ` \(.*?\n\);`).FindString(string(snapshot))
		if ddl == "" {
			t.Fatalf("missing snapshot table %s", table)
		}
		ddl = strings.ReplaceAll(ddl, "public.", "")
		if err := db.WithContext(ctx).Exec(ddl + " ALTER TABLE " + table + " ADD PRIMARY KEY (id); ALTER TABLE " + table + " ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;").Error; err != nil {
			t.Fatal(err)
		}
	}
	for _, ddl := range regexp.MustCompile(`CREATE (?:UNIQUE )?INDEX [^;]+ ON public\.system_scheduler_[^;]+;`).FindAllString(string(snapshot), -1) {
		if err := db.WithContext(ctx).Exec(strings.ReplaceAll(ddl, "public.", "")).Error; err != nil {
			t.Fatal(err)
		}
	}
	if err := db.WithContext(ctx).Exec(`ALTER TABLE system_scheduler_job ADD COLUMN IF NOT EXISTS queue VARCHAR(64) NOT NULL DEFAULT 'default', ADD COLUMN IF NOT EXISTS timeout_seconds INTEGER NOT NULL DEFAULT 30, ADD COLUMN IF NOT EXISTS worker_id VARCHAR(128);
ALTER TABLE system_scheduler_run ADD COLUMN IF NOT EXISTS result_summary VARCHAR(1024) NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS ux_system_scheduler_job_task_attempt ON system_scheduler_job(id,attempt_count);
CREATE INDEX IF NOT EXISTS ix_system_scheduler_run_job_list ON system_scheduler_run(job_id,attempt_no DESC);
CREATE INDEX IF NOT EXISTS ix_system_scheduler_run_cleanup ON system_scheduler_run(finished_at,id) WHERE status IN (2,3);
INSERT INTO system_scheduler_job(id,task_type,trigger_source,source_key,scheduled_at,available_at,status,max_attempts,queue,timeout_seconds,completed_at) VALUES (100,'example','manual','original',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,4,3,'default',30,CURRENT_TIMESTAMP);
SELECT setval(pg_get_serial_sequence('system_scheduler_job','id'),100,true);
INSERT INTO system_scheduler_run(job_id,attempt_no,status,worker_id,started_at,finished_at) VALUES (100,1,2,'original-worker',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);`).Error; err != nil {
		t.Fatal(err)
	}
	return db, ctx
}

func applySchedulerCleanup(db *gorm.DB, ctx context.Context, sql string) error {
	return db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error })
}

func TestSchedulerCleanupPreservesHistoryAndRuntimeAfterRepeat(t *testing.T) {
	db, ctx := oldSchedulerSchema(t)
	sql := schedulerCleanupSQL(t)
	for i := 0; i < 2; i++ {
		if err := applySchedulerCleanup(db, ctx, sql); err != nil {
			t.Fatal(err)
		}
	}
	var fields int64
	if err := db.Raw(`SELECT count(*) FROM information_schema.columns WHERE table_schema=current_schema() AND ((table_name='system_scheduler_job' AND column_name IN ('queue','timeout_seconds','worker_id')) OR (table_name='system_scheduler_run' AND column_name='result_summary'))`).Scan(&fields).Error; err != nil || fields != 0 {
		t.Fatalf("removed columns=%d: %v", fields, err)
	}
	var worker string
	if err := db.Raw(`SELECT worker_id FROM system_scheduler_run WHERE job_id=100`).Scan(&worker).Error; err != nil || worker != "original-worker" {
		t.Fatalf("preserved worker=%q: %v", worker, err)
	}
	var redundant int64
	if err := db.Raw(`SELECT count(*) FROM pg_indexes WHERE schemaname=current_schema() AND indexname IN ('ux_system_scheduler_job_task_attempt','ix_system_scheduler_run_job_list','ix_system_scheduler_run_cleanup')`).Scan(&redundant).Error; err != nil || redundant != 0 {
		t.Fatalf("redundant indexes=%d: %v", redundant, err)
	}
	repo := NewRepository(db)
	now := time.Now().UTC()
	job := Job{TaskType: "example", Payload: []byte(`{}`), TriggerSource: TriggerManual, SourceKey: "new", ScheduledAt: now, AvailableAt: now, Status: JobScheduled, MaxAttempts: 3, CreatedAt: now, UpdatedAt: now}
	if err := repo.CreateJob(ctx, &job); err != nil {
		t.Fatal(err)
	}
	claimed, err := repo.ClaimPublishableJobs(ctx, now, 50, "dispatch", time.Minute)
	if err != nil || len(claimed) != 1 {
		t.Fatalf("publish claim: %+v %v", claimed, err)
	}
	if err := repo.MarkQueued(ctx, job.ID, "dispatch", now); err != nil {
		t.Fatal(err)
	}
	if _, _, err := repo.ClaimRun(ctx, job.ID, 1, "dispatch", "new-worker", "run", now, time.Minute); err != nil {
		t.Fatal(err)
	}
	if err := repo.FailRun(ctx, job.ID, 1, "run", "timeout", "private diagnostic", nil, now); err != nil {
		t.Fatal(err)
	}
	service := NewService(repo, TaskCatalog{})
	for _, locale := range []i18n.Locale{i18n.ZhCN, i18n.EnUS} {
		row, err := service.GetJob(i18n.WithLocale(ctx, locale), job.ID)
		if err != nil || strings.Contains(row.LastError, "private") || row.LastError == "timeout" || row.LastError == "" {
			t.Fatalf("public diagnostic: %+v %v", row, err)
		}
		if locale == i18n.ZhCN && !strings.Contains(row.LastError, "执行时间") {
			t.Fatalf("Chinese diagnostic: %q", row.LastError)
		}
		runs, err := service.ListRuns(i18n.WithLocale(ctx, locale), RunQuery{JobID: job.ID, Limit: 100})
		if err != nil || len(runs) != 1 || runs[0].ErrorMessage != row.LastError || runs[0].WorkerID != "new-worker" {
			t.Fatalf("localized run: %+v %v", runs, err)
		}
	}
	// A manual retry creates a new job while preserving the failed attempt.
	retried, err := repo.CreateRetryJob(ctx, job.ID, nil, now)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := repo.ClaimPublishableJobs(ctx, now, 50, "retry-dispatch", time.Minute); err != nil {
		t.Fatal(err)
	}
	if err := repo.MarkQueued(ctx, retried.ID, "retry-dispatch", now); err != nil {
		t.Fatal(err)
	}
	if _, _, err := repo.ClaimRun(ctx, retried.ID, 1, "retry-dispatch", "retry-worker", "retry-run", now, time.Minute); err != nil {
		t.Fatal(err)
	}
	if err := repo.CompleteRun(ctx, retried.ID, 1, "retry-run", now); err != nil {
		t.Fatal(err)
	}
	finished, err := repo.GetJob(ctx, retried.ID)
	if err != nil || finished.Status != JobCompleted || finished.RetryOfJobID == nil || *finished.RetryOfJobID != job.ID {
		t.Fatalf("completed retry: %+v %v", finished, err)
	}
	var count int64
	if err := db.Table("system_scheduler_job").Where("id=100 AND status=4").Count(&count).Error; err != nil || count != 1 {
		t.Fatalf("history: %d %v", count, err)
	}
}

func TestSchedulerCleanupRollsBackIncompatibleQueuedIndex(t *testing.T) {
	db, ctx := oldSchedulerSchema(t)
	if err := db.Exec(`DROP INDEX IF EXISTS ix_system_scheduler_job_queued_lease; CREATE INDEX ix_system_scheduler_job_queued_lease ON system_scheduler_job(available_at,id) WHERE status=2`).Error; err != nil {
		t.Fatal(err)
	}
	if err := applySchedulerCleanup(db, ctx, schedulerCleanupSQL(t)); err == nil {
		t.Fatal("incompatible existing index must be rejected")
	}
	var count int64
	if err := db.Raw(`SELECT count(*) FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='system_scheduler_job' AND column_name='queue'`).Scan(&count).Error; err != nil || count != 1 {
		t.Fatalf("DDL rollback: %d %v", count, err)
	}
}

func TestSchedulerPublicDiagnosticsAreLocalizedAndDoNotEchoUnknownErrors(t *testing.T) {
	for _, class := range []string{"timeout", "canceled", "task-failed", "unknown-task-type", "invalid-payload", "worker-lost", "publish", "transport-lost", "private TOKEN=password"} {
		zh, err := executionErrorMessage(i18n.WithLocale(context.Background(), i18n.ZhCN), class)
		if err != nil || zh == "" || strings.Contains(zh, "TOKEN") {
			t.Fatalf("Chinese diagnostic %q: %q %v", class, zh, err)
		}
		en, err := executionErrorMessage(i18n.WithLocale(context.Background(), i18n.EnUS), class)
		if err != nil || en == "" || en == zh || strings.Contains(en, "TOKEN") {
			t.Fatalf("English diagnostic %q: %q %v", class, en, err)
		}
	}
}

