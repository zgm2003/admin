func applyCustomRecharge(t *testing.T, db *gorm.DB, ctx context.Context) {
	t.Helper()
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(customRechargeMigration(t)).Error }); err != nil {
		t.Fatal(err)
	}
}

func TestPaymentCustomRechargeMigrationPreservesHistoryAndIsIdempotent(t *testing.T) {
	db, ctx := customRechargeSchema(t)
	seedPaymentOrderWalletFacts(t, db, ctx)
	before := paymentRowsDigest(t, db, ctx)
	applyCustomRecharge(t, db, ctx)
	if paymentRowsDigest(t, db, ctx) != before {
		t.Fatal("historical financial facts changed")
	}
	var generation, events int64
	if err := db.WithContext(ctx).Raw(`SELECT generation FROM system_config_cache_state WHERE namespace='system.setting' AND scope_key='global'`).Scan(&generation).Error; err != nil || generation != 20 {
		t.Fatalf("generation=%d err=%v", generation, err)
	}
	if err := db.WithContext(ctx).Table("system_config_cache_outbox").Count(&events).Error; err != nil || events != 1 {
		t.Fatalf("events=%d err=%v", events, err)
	}
	if err := db.WithContext(ctx).Exec(`UPDATE system_setting SET value='25' WHERE setting_key='payment.recharge.minimum_amount'`).Error; err != nil {
		t.Fatal(err)
	}
	applyCustomRecharge(t, db, ctx)
	var state struct {
		Generation int64
		Value      string
		Events     int64
	}
	if err := db.WithContext(ctx).Raw(`SELECT generation,(SELECT value FROM system_setting WHERE setting_key='payment.recharge.minimum_amount') AS value,(SELECT count(*) FROM system_config_cache_outbox) AS events FROM system_config_cache_state WHERE namespace='system.setting' AND scope_key='global'`).Scan(&state).Error; err != nil || state.Generation != 20 || state.Value != "25" || state.Events != 1 {
		t.Fatalf("replay state=%+v err=%v", state, err)
	}
	for _, statement := range []string{
		`UPDATE system_setting SET value='0' WHERE setting_key='payment.recharge.minimum_amount'`,
		`UPDATE system_setting SET value='92233720369' WHERE setting_key='payment.recharge.minimum_amount'`,
		`UPDATE system_setting SET value='1.5' WHERE setting_key='payment.recharge.minimum_amount'`,
		`UPDATE system_setting SET is_enabled=0 WHERE setting_key='payment.recharge.minimum_amount'`,
		`UPDATE system_setting SET deleted_at=CURRENT_TIMESTAMP WHERE setting_key='payment.recharge.minimum_amount'`,
	} {
		if err := db.WithContext(ctx).Exec(statement).Error; err == nil {
			t.Fatalf("invalid setting accepted: %s", statement)
		}
	}
}

func TestPaymentCustomRechargeMigrationRollsBackIncompatibleSetting(t *testing.T) {
	db, ctx := customRechargeSchema(t)
	if err := db.WithContext(ctx).Exec(`INSERT INTO system_setting(setting_key,value,value_type,description,is_enabled,is_builtin,created_at,updated_at) VALUES('payment.recharge.minimum_amount','0',2,'bad',1,1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)`).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(customRechargeMigration(t)).Error }); err == nil {
		t.Fatal("incompatible setting accepted")
	}
	var notNull bool
	if err := db.WithContext(ctx).Raw(`SELECT attnotnull FROM pg_attribute WHERE attrelid='payment_order'::regclass AND attname='package_id'`).Scan(&notNull).Error; err != nil || !notNull {
		t.Fatalf("DDL did not roll back: notnull=%v err=%v", notNull, err)
	}
	var generation int64
	if err := db.WithContext(ctx).Raw(`SELECT generation FROM system_config_cache_state WHERE namespace='system.setting' AND scope_key='global'`).Scan(&generation).Error; err != nil || generation != 19 {
		t.Fatalf("generation=%d err=%v", generation, err)
	}
}

func TestPaymentCustomRechargeMigrationRejectsCheckDrift(t *testing.T) {
	for name, statement := range map[string]string{
		"order predicate":    `ALTER TABLE payment_order ADD CONSTRAINT ck_payment_order_package_id CHECK(package_id > -10)`,
		"setting predicate":  `ALTER TABLE system_setting ADD CONSTRAINT ck_system_setting_recharge_minimum_amount CHECK(true)`,
		"setting validation": `ALTER TABLE system_setting ADD CONSTRAINT ck_system_setting_recharge_minimum_amount CHECK(true) NOT VALID`,
	} {
		t.Run(name, func(t *testing.T) {
			db, ctx := customRechargeSchema(t)
			if err := db.WithContext(ctx).Exec(statement).Error; err != nil {
				t.Fatal(err)
			}
			if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(customRechargeMigration(t)).Error }); err == nil {
				t.Fatal("same-name incompatible CHECK accepted")
			}
			var count int64
			if err := db.WithContext(ctx).Table("system_setting").Count(&count).Error; err != nil || count != 0 {
				t.Fatalf("failed migration leaked seed: %d %v", count, err)
			}
		})
	}
}

func TestPaymentCustomRechargeConcurrentCreateAndCreditOnce(t *testing.T) {
	db, ctx := customRechargeSchema(t)
	applyCustomRecharge(t, db, ctx)
	now := time.Now().UTC()
	repo := order.NewRepository(db)
	row := order.Model{OrderNo: "PO-CUSTOM-1", UserID: 7, PlatformID: 1, PackageName: "Custom recharge", AmountCents: 2539, ConfigID: 1, ConfigVersion: 1, PayMethod: 1, RequestID: "00000000-0000-4000-8000-000000000001", RequestFingerprint: make([]byte, 32), ReturnURL: "https://app.example.test/paid", Status: order.StatusPending, ExpiresAt: now.Add(time.Hour), CreatedAt: now, UpdatedAt: now}
	var wg sync.WaitGroup
	created := make(chan bool, 8)
	for range 8 {
		wg.Add(1)
		go func() { defer wg.Done(); candidate := row; created <- repo.Create(ctx, &candidate) == nil }()
	}
	wg.Wait()
	close(created)
	successes := 0
	for success := range created {
		if success {
			successes++
		}
	}
	if successes != 1 {
		t.Fatalf("orders created=%d", successes)
	}
	stored, err := repo.FindByRequest(ctx, 7, 1, row.RequestID)
	if err != nil || stored.PackageID != nil || stored.AmountCents != 2539 {
		t.Fatalf("custom order=%+v err=%v", stored, err)
	}
	for _, statement := range []string{`UPDATE payment_order SET amount_cents=2540 WHERE order_no='PO-CUSTOM-1'`, `UPDATE payment_order SET package_id=1 WHERE order_no='PO-CUSTOM-1'`, `DELETE FROM payment_order WHERE order_no='PO-CUSTOM-1'`} {
		if err := db.WithContext(ctx).Exec(statement).Error; err == nil {
			t.Fatal("immutable custom order changed")
		}
	}
	seller := "20880001"
	proof := order.ConfirmedPayment{ConfigID: 1, ConfigVersion: 1, Environment: payment.EnvironmentSandbox, OrderNo: row.OrderNo, TradeNo: "TRADE-CUSTOM-1", AppID: "20260001", SellerID: &seller, ProofSource: order.ProofSourceQuery, AmountCents: 2539, Status: "TRADE_SUCCESS"}
	bad := proof
	bad.AmountCents++
	if _, err := repo.Confirm(ctx, bad, nil, now); err == nil {
		t.Fatal("wrong proof amount credited")
	}
	type outcome struct {
		id  int64
		err error
	}
	credits := make(chan outcome, 8)
	for range 8 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			result, err := repo.Confirm(ctx, proof, nil, now)
			credits <- outcome{result.TransactionID, err}
		}()
	}
	wg.Wait()
	close(credits)
	var id int64
	for credit := range credits {
		if credit.err != nil || credit.id < 1 || (id != 0 && id != credit.id) {
			t.Fatalf("concurrent credit=%+v", credit)
		}
		id = credit.id
	}
	var balance, count int64
	if err := db.WithContext(ctx).Raw(`SELECT balance_units FROM payment_wallet WHERE user_id=7`).Scan(&balance).Error; err != nil || balance != 2539000000 {
		t.Fatalf("balance=%d err=%v", balance, err)
	}
	if err := db.WithContext(ctx).Table("payment_transaction").Count(&count).Error; err != nil || count != 1 {
		t.Fatalf("credits=%d err=%v", count, err)
	}
}
