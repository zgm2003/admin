package database_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"admin/server/internal/database/testschema"
	rechargepackage "admin/server/internal/module/payment/rechargePackage"
	"admin/server/internal/shared/yesno"
	"github.com/joho/godotenv"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"
)

func TestPaymentRechargePackageCodeMigrationIsIdempotentAndPreservesRows(t *testing.T) {
	dsn := os.Getenv("POSTGRES_DSN")
	if dsn == "" {
		if err := godotenv.Load(filepath.Join(repoRoot(t), "server", ".env")); err == nil {
			dsn = os.Getenv("POSTGRES_DSN")
		}
	}
	if dsn == "" {
		t.Skip("POSTGRES_DSN is not configured")
	}
	db, ctx := testschema.Open(t, dsn, "test_payment_recharge_package_code")
	db = db.Session(&gorm.Session{Logger: logger.Default.LogMode(logger.Silent)})
	if err := db.WithContext(ctx).Exec(`CREATE TABLE payment_recharge_package(
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code varchar(64) NOT NULL UNIQUE,
        name varchar(128) NOT NULL,
        amount_cents bigint NOT NULL DEFAULT 1000,
        badge varchar(32), sort_order integer NOT NULL DEFAULT 0,
        is_enabled smallint NOT NULL DEFAULT 0,
        created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        deleted_at timestamptz
    );
    CREATE FUNCTION payment_recharge_package_identity_guard() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        IF ROW(NEW.id,NEW.code,NEW.created_at) IS DISTINCT FROM ROW(OLD.id,OLD.code,OLD.created_at) THEN
            RAISE EXCEPTION 'payment recharge package identity is immutable';
        END IF;
        RETURN NEW;
    END $$;
    CREATE TRIGGER payment_recharge_package_identity BEFORE UPDATE ON payment_recharge_package
    FOR EACH ROW EXECUTE FUNCTION payment_recharge_package_identity_guard();`).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.WithContext(ctx).Exec(`INSERT INTO payment_recharge_package(code,name) VALUES('starter','Starter')`).Error; err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(repoRoot(t), "docs", "database", "2026-10-17-payment-recharge-package-code.sql"))
	if err != nil {
		t.Fatal(err)
	}
	sql := strings.ReplaceAll(string(data), "\r\n", "\n")
	for range 2 {
		if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(sql).Error }); err != nil {
			t.Fatal(err)
		}
	}
	var hasCode bool
	if err := db.WithContext(ctx).Raw(`SELECT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='payment_recharge_package' AND column_name='code')`).Scan(&hasCode).Error; err != nil {
		t.Fatal(err)
	}
	if hasCode {
		t.Fatal("recharge package code column remains")
	}
	var name string
	if err := db.WithContext(ctx).Raw(`SELECT name FROM payment_recharge_package WHERE id=1`).Scan(&name).Error; err != nil || name != "Starter" {
		t.Fatalf("preserved row=%q err=%v", name, err)
	}
	service := rechargepackage.NewService(rechargepackage.NewRepository(db))
	id, err := service.Create(ctx, rechargepackage.CreateInput{Name: "New package", AmountCents: 1001, IsEnabled: yesno.No})
	if err != nil || id <= 1 {
		t.Fatalf("create after migration: id=%d err=%v", id, err)
	}
	if err := service.Update(ctx, id, rechargepackage.UpdateInput{Name: "Updated package", AmountCents: 1234}); err != nil {
		t.Fatalf("update after migration: %v", err)
	}
	if err := service.UpdateStatus(ctx, id, yesno.Yes); err != nil {
		t.Fatalf("enable after migration: %v", err)
	}
	var saved rechargepackage.Model
	if err := db.WithContext(ctx).First(&saved, id).Error; err != nil || saved.AmountCents != 1234 || saved.IsEnabled != yesno.Yes {
		t.Fatalf("saved package: %#v err=%v", saved, err)
	}
}
