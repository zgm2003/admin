func applyPaymentRedeemMenuMigration(t *testing.T, db *gorm.DB, ctx context.Context) {
	t.Helper()
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error { return tx.Exec(readPaymentRedeemMenuMigration(t)).Error }); err != nil {
		t.Fatal(err)
	}
}

func readPaymentRedeemMenuMigration(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(repoRoot(t), "docs", "database", "2026-10-17-payment-redeem-code-menu.sql"))
	if err != nil {
		t.Fatal(err)
	}
	return strings.ReplaceAll(string(data), "\r\n", "\n")
}

func assertPaymentRedeemMenuState(t *testing.T, db *gorm.DB, ctx context.Context, menuVersion, accessVersion int64) {
	t.Helper()
	var count int64
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM permission_menu WHERE platform_id=1 AND code IN ('payment:redeemCode:view','payment:myWallet:view') AND deleted_at IS NULL`).Scan(&count).Error; err != nil || count != 2 {
		t.Fatalf("pages=%d err=%v", count, err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT count(*) FROM permission_menu WHERE platform_id=1 AND parent_id=(SELECT id FROM permission_menu WHERE code='payment:redeemCode:view') AND menu_type='action' AND code IN ('payment:redeemCode:list','payment:redeemCode:detail','payment:redeemCode:generate','payment:redeemCode:void','payment:redeemCode:export') AND is_hidden=1 AND is_enabled=1 AND deleted_at IS NULL`).Scan(&count).Error; err != nil || count != 5 {
		t.Fatalf("redeem actions=%d err=%v", count, err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT menu_version FROM permission_auth_platform WHERE id=1`).Scan(&count).Error; err != nil || count != menuVersion {
		t.Fatalf("menu version=%d err=%v", count, err)
	}
	if err := db.WithContext(ctx).Raw(`SELECT version FROM permission_access_version WHERE user_id=7`).Scan(&count).Error; err != nil || count != accessVersion {
		t.Fatalf("access version=%d err=%v", count, err)
	}
}

func paymentRedeemMenuDigest(t *testing.T, db *gorm.DB, ctx context.Context) string {
	t.Helper()
	var digest string
	if err := db.WithContext(ctx).Raw(`SELECT md5(jsonb_build_object('menus',(SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM permission_menu m),'platforms',(SELECT jsonb_agg(to_jsonb(p) ORDER BY id) FROM permission_auth_platform p),'roles',(SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM permission_role r),'grants',(SELECT jsonb_agg(to_jsonb(g) ORDER BY id) FROM permission_role_menu g),'versions',(SELECT jsonb_agg(to_jsonb(v) ORDER BY user_id) FROM permission_access_version v))::text)`).Scan(&digest).Error; err != nil {
		t.Fatal(err)
	}
	return digest
}
