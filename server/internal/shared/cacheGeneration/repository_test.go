func TestAdvanceTxCreatesDurableOutboxInTheSameTransaction(t *testing.T) {
	db, ctx := openGenerationDatabase(t)
	repository := NewRepository(db)
	scope, err := NewScope("system.setting", "global")
	if err != nil {
		t.Fatal(err)
	}
	now := time.Now().UTC()

	var event Event
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		created, err := repository.AdvanceTx(ctx, tx, scope, 1, now)
		if err != nil {
			return err
		}
		event = created
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	if event.Generation != 2 || event.ID < 1 {
		t.Fatalf("event=%+v", event)
	}
	current, err := repository.Current(ctx, scope)
	if err != nil || current != 2 {
		t.Fatalf("generation=%d err=%v", current, err)
	}
	claimed, err := repository.ClaimPending(ctx, 10, "claim-token", time.Now().UTC(), time.Minute)
	if err != nil || len(claimed) != 1 || claimed[0].ID != event.ID {
		t.Fatalf("claimed=%+v err=%v", claimed, err)
	}
}

// loadIntegrationSettings resolves the repository root instead of a hard-coded
// relative path, mirroring the existing PostgreSQL integration test pattern.
func loadIntegrationSettings(t *testing.T) config.Worker {
	t.Helper()
	if testing.Short() {
		t.Skip("integration test")
	}
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	repoRoot := filepath.Clean(filepath.Join(filepath.Dir(filename), "..", "..", "..", ".."))
	if err := godotenv.Load(filepath.Join(repoRoot, "server", ".env")); err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	settings, err := config.LoadWorker(os.LookupEnv)
	if err != nil {
		t.Fatal(err)
	}
	return settings
}

func openGenerationDatabase(t *testing.T) (*gorm.DB, context.Context) {
	t.Helper()
	settings := loadIntegrationSettings(t)
	db, ctx := testschema.Open(t, settings.PostgresDSN, "test_config_cache_generation")
	if err := db.WithContext(ctx).Exec(`
CREATE TABLE system_config_cache_generation (
 namespace varchar(128) NOT NULL, scope_key varchar(128) NOT NULL, generation bigint NOT NULL,
 created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, PRIMARY KEY(namespace, scope_key));
CREATE TABLE system_config_cache_outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 namespace varchar(128) NOT NULL, scope_key varchar(128) NOT NULL, generation bigint NOT NULL,
 attempts integer NOT NULL DEFAULT 0, available_at timestamptz NOT NULL,
 locked_until timestamptz, lock_token varchar(64), last_error varchar(512) NOT NULL DEFAULT '',
 published_at timestamptz, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
 UNIQUE(namespace, scope_key, generation));
INSERT INTO system_config_cache_generation VALUES ('system.setting','global',1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);
`).Error; err != nil {
		t.Fatal(err)
	}
	return db, ctx
}

func TestAdvanceTxRollsBackWithBusinessTransaction(t *testing.T) {
	db, ctx := openGenerationDatabase(t)
	repository := NewRepository(db)
	scope := mustGenerationScope(t)
	sentinel := errors.New("business transaction failed")

	err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		if _, err := repository.AdvanceTx(ctx, tx, scope, 1, time.Now().UTC()); err != nil {
			return err
		}
		return sentinel
	})
	if !errors.Is(err, sentinel) {
		t.Fatalf("transaction error = %v want sentinel", err)
	}
	current, err := repository.Current(ctx, scope)
	if err != nil || current != 1 {
		t.Fatalf("generation after rollback = %d,%v want 1", current, err)
	}
	assertGenerationOutboxCount(t, db, ctx, 0)
}

