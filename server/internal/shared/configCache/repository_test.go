func TestAdvanceTxCreatesDurableOutboxInTheSameTransaction(t *testing.T) {
	db, ctx := openGenerationDatabase(t)
	repository := NewRepository(db)
	scope, err := NewScope("system.setting", "global")
	if err != nil {
		t.Fatal(err)
	}
	now := time.Now().UTC()

	var event Event
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		created, err := repository.AdvanceTx(ctx, tx, scope, 1, now)
		if err != nil {
			return err
		}
		event = created
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	if event.Generation != 2 || event.ID < 1 {
		t.Fatalf("event=%+v", event)
	}
	current, err := repository.Current(ctx, scope)
	if err != nil || current != 2 {
		t.Fatalf("generation=%d err=%v", current, err)
	}
	claimed, err := repository.ClaimPending(ctx, 10, "claim-token", time.Now().UTC(), time.Minute)
	if err != nil || len(claimed) != 1 || claimed[0].ID != event.ID {
		t.Fatalf("claimed=%+v err=%v", claimed, err)
	}
}

// loadIntegrationSettings resolves the repository root instead of a hard-coded
// relative path, mirroring the existing PostgreSQL integration test pattern.
func loadIntegrationSettings(t *testing.T) config.Worker {
	t.Helper()
	if testing.Short() {
		t.Skip("integration test")
	}
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	repoRoot := filepath.Clean(filepath.Join(filepath.Dir(filename), "..", "..", "..", ".."))
	if err := godotenv.Load(filepath.Join(repoRoot, "server", ".env")); err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	settings, err := config.LoadWorker(os.LookupEnv)
	if err != nil {
		t.Fatal(err)
	}
	return settings
}

