func TestInitializeTxCreatesGenerationAndOutboxOnce(t *testing.T) {
	db, ctx := openGenerationDatabase(t)
	repository := NewRepository(db)
	scope := initializeScope(t, "storage.cosconfig", "10")
	now := time.Now().UTC()

	var event Event
	if err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		created, err := repository.InitializeTx(ctx, tx, scope, now)
		if err != nil {
			return err
		}
		event = created
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	if event.Generation != 1 || event.ID < 1 || event.Scope != scope {
		t.Fatalf("event=%+v", event)
	}
	if current, err := repository.Current(ctx, scope); err != nil || current != 1 {
		t.Fatalf("generation=%d err=%v want 1", current, err)
	}
	assertGenerationCount(t, db, ctx, 2)
	assertGenerationOutboxCount(t, db, ctx, 1)

	// 重复初始化必须报告已存在，且不覆盖、不推进既有行。
	err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		_, err := repository.InitializeTx(ctx, tx, scope, now.Add(time.Minute))
		return err
	})
	if !errors.Is(err, ErrGenerationAlreadyExists) {
		t.Fatalf("duplicate initialize error = %v want ErrGenerationAlreadyExists", err)
	}
	if current, err := repository.Current(ctx, scope); err != nil || current != 1 {
		t.Fatalf("generation after duplicate = %d err=%v want 1", current, err)
	}
	assertGenerationCount(t, db, ctx, 2)
	assertGenerationOutboxCount(t, db, ctx, 1)
}

