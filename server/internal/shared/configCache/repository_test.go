// 隔离 fixture 的 outbox 表没有外键，因此可以构造"同 scope 同代 outbox 已存在"的事实异常：
// 初始化必须上抛该冲突，而不能伪装成 ErrGenerationAlreadyExists（那会让调用方以为是自己建的行）。
func TestInitializeTxSurfacesOutboxConflictAsAnomaly(t *testing.T) {
	db, ctx := openGenerationDatabase(t)
	repository := NewRepository(db)
	scope := initializeScope(t, "storage.cosconfig", "13")
	now := time.Now().UTC()
	if err := db.WithContext(ctx).Exec(
		`INSERT INTO system_config_cache_outbox (namespace, scope_key, generation, attempts, available_at, created_at, updated_at)
		 VALUES (?, ?, 1, 0, ?, ?, ?)`,
		scope.Namespace, scope.ScopeKey, now, now, now).Error; err != nil {
		t.Fatal(err)
	}

	err := db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		_, err := repository.InitializeTx(ctx, tx, scope, now)
		return err
	})
	if err == nil {
		t.Fatal("InitializeTx accepted an outbox conflict")
	}
	if errors.Is(err, ErrGenerationAlreadyExists) {
		t.Fatalf("outbox conflict was misreported as ErrGenerationAlreadyExists: %v", err)
	}
	if !strings.Contains(err.Error(), "system_config_cache_outbox") {
		t.Fatalf("error = %v want outbox constraint context", err)
	}
	if _, err := repository.Current(ctx, scope); !errors.Is(err, ErrGenerationRowMissing) {
		t.Fatalf("generation row survived conflicting transaction: %v", err)
	}
	assertGenerationOutboxCount(t, db, ctx, 1)
}

func TestInitializeTxConcurrentInstancesProduceExactlyOneWinner(t *testing.T) {
	db, ctx := openGenerationDatabase(t)
	second := openSecondGenerationInstance(t, db)
	scope := initializeScope(t, "storage.cosconfig", "20")
	now := time.Now().UTC()

	instances := []*gorm.DB{db, second}
	results := make([]error, len(instances))
	start := make(chan struct{})
	var waitGroup sync.WaitGroup
	for index, instance := range instances {
		waitGroup.Add(1)
		go func(index int, instance *gorm.DB) {
			defer waitGroup.Done()
			<-start
			results[index] = instance.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
				_, err := NewRepository(instance).InitializeTx(ctx, tx, scope, now)
				return err
			})
		}(index, instance)
	}
	close(start)
	waitGroup.Wait()

	winners, conflicts := 0, 0
	for _, err := range results {
		switch {
		case err == nil:
			winners++
		case errors.Is(err, ErrGenerationAlreadyExists):
			conflicts++
		default:
			t.Fatalf("unexpected concurrent initialize error: %v", err)
		}
	}
	if winners != 1 || conflicts != 1 {
		t.Fatalf("winners=%d conflicts=%d want 1/1", winners, conflicts)
	}
	if current, err := NewRepository(db).Current(ctx, scope); err != nil || current != 1 {
		t.Fatalf("generation=%d err=%v want 1", current, err)
	}
	assertGenerationCount(t, db, ctx, 2)
	assertGenerationOutboxCount(t, db, ctx, 1)
}

